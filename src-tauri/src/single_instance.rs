    /// Каталог данных при первом запуске ещё не существует.
    #[test]
    fn a_data_dir_that_does_not_exist_yet_is_created() {
        let parent = tempfile::tempdir().expect("временный каталог не создан");
        let dir = parent.path().join("nested").join("data");
        assert!(!dir.exists());

        let Claim::Sole(_lock) = claim(&dir) else {
            panic!(
                "первый запуск не смог взять замок в ещё не созданном каталоге {dir:?} — \
                 приложение отказало бы себе в старте на ровном месте. См. {REASONING}"
            );
        };
    }

    /// Пока держит живой процесс — соседу отказано.
    #[test]
    fn a_lock_held_by_a_live_process_is_reported_as_already_running() {
        let dir = tempfile::tempdir().expect("временный каталог не создан");
        let mut holder = spawn_holder(dir.path());

        let verdict = claim(dir.path());
        holder.kill();

        assert!(
            matches!(verdict, Claim::AlreadyRunning(_)),
            "замок держит живой процесс, а этот запуск считает себя единственным. \
             Это два экземпляра с двумя очередями и общим деревом yt-dlp. \
             См. {REASONING}"
        );
    }

    /// Смерть держателя освобождает замок — без нашего участия.
    ///
    /// Это утверждение про ОС, а не про наш код (`flock` и `LockFileEx`
    /// отпускают замок при закрытии дескриптора), и потому проверяется
    /// убийством настоящего процесса, а не рассуждением: если бы оно было
    /// неверным, любое падение приложения оставляло бы его незапускаемым
    /// до перезагрузки.
    #[test]
    fn the_lock_comes_back_after_the_holder_is_killed() {
        let dir = tempfile::tempdir().expect("временный каталог не создан");
        let mut holder = spawn_holder(dir.path());

        assert!(
            matches!(claim(dir.path()), Claim::AlreadyRunning(_)),
            "замок обязан быть занят до убийства держателя, иначе тест ниже \
             ничего не доказывает. См. {REASONING}"
        );

        holder.kill();

        wait_until(
            "замок не освободился после смерти держателя — упавшее приложение \
             осталось бы незапускаемым",
            || matches!(claim(dir.path()), Claim::Sole(_)),
        );
    }

    /// Контекст нигде не собирается в обход [`super::context`].
    ///
    /// Иначе правка идентификатора отменяется, dev-сборка снова делит
    /// каталог данных и замок с установленной, и заметить это можно только
    /// запуском двух сборок рядом. Имя макроса собирается из кусков
    /// намеренно: иначе исходник самого теста попал бы под собственную
    /// проверку — сторож, ослеплённый собственным текстом, урок TL-53.
    ///
    /// Проверяется только список файлов, и этого хватает — но рассуждение
    /// стоит записать, потому что первая редакция теста ему не доверяла и
    /// добавляла второе утверждение «раскрытие есть именно здесь».
    /// Утверждение оказалось недоказуемым: чтобы оно покраснело, раскрытию
    /// нужно исчезнуть отсюда, а исчезнуть оно может только двумя
    /// способами. Переехало в другой файл — краснеет список (проверено
    /// мутацией: `context` перенесена в `main.rs`, список стал из двух
    /// файлов). Не раскрылось нигде — тогда `Context` неоткуда взять,
    /// другого конструктора у него нет, и падает сборка, а не тест.
    ///
    /// Сторож текстовый и потому груб: doc-комментарий, упомянувший макрос
    /// в другом модуле, тоже уронит тест. Это осознанный перекос в
    /// fail-closed — ложное срабатывание читается за минуту, молчаливый
    /// обход не читается вовсе.
    ///
    /// На macOS у нас есть ещё и защита компилятора, но полагаться на неё
    /// нельзя: второе раскрытие ломает сборку символом `_EMBED_INFO_PLIST`
    /// только когда `target == MacOS && dev` (tauri-codegen 2.6.3,
    /// `src/context.rs:301`), то есть ни в релизной сборке бандла, ни под
    /// Windows и Linux этой ошибки не будет.
    #[test]
    fn generate_context_has_no_second_home() {
        let needle = format!("generate_context{}", "!");
        let src = manifest_dir().join("src");
        let home = src.join("single_instance.rs");

        let mut offenders = Vec::new();
        collect_files(&src, &mut offenders_filter(&needle), &mut offenders);
        offenders.sort();

        assert_eq!(
            offenders,
            vec![home],
            "{needle} встречается в src/ не только в single_instance.rs. \
             Контекст, собранный мимо single_instance::context, приходит с \
             идентификатором из tauri.conf.json как есть — dev-сборка и \
             установленное приложение снова делят каталог данных и замок. \
             См. {REASONING}"
        );
    }

    fn offenders_filter(needle: &str) -> impl FnMut(&Path) -> bool + '_ {
        move |path: &Path| {
            path.extension().is_some_and(|ext| ext == "rs")
                && std::fs::read_to_string(path).is_ok_and(|text| text.contains(needle))
        }
    }

    fn collect_files(dir: &Path, keep: &mut impl FnMut(&Path) -> bool, out: &mut Vec<PathBuf>) {
        let entries =
            std::fs::read_dir(dir).unwrap_or_else(|err| panic!("{dir:?} не читается: {err}"));
        for entry in entries {
            let path = entry
                .unwrap_or_else(|err| panic!("запись в {dir:?} не читается: {err}"))
                .path();
            if path.is_dir() {
                collect_files(&path, keep, out);
            } else if keep(&path) {
                out.push(path);
            }
        }
    }

    /// Блокировка зовётся у fs4 явно, а не методом на `File`.
    ///
    /// Сторож поставлен по живому происшествию, а не из осторожности:
    /// первая редакция писала `file.try_lock()` при `use fs4::FileExt` — и
    /// компилятор молча выбрал **собственный** метод `File`, который
    /// появился в std в Rust 1.89. То есть один и тот же исходник звал бы
    /// разные реализации на разных тулчейнах. Здесь это вылезло ошибкой
    /// типов случайно: у `fs4::TryLockError` и `std::fs::TryLockError`
    /// совпала форма, но не путь, — а совпади и путь, расхождение уехало
    /// бы в релиз молча.
    ///
    /// Имя метода собирается из кусков: иначе строка в самом тесте попала
    /// бы под собственную проверку.
    #[test]
    fn the_lock_is_taken_through_fs4_and_not_through_whatever_std_offers() {
        let bare_call = format!(".try{}lock()", "_");
        let path = manifest_dir().join("src/single_instance.rs");
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|err| panic!("{path:?} не читается: {err}"));

        // Комментарии отбрасываются: этот же файл обсуждает опасный вызов
        // прозой, и без фильтра сторож ловил бы собственное объяснение.
        // Именно так он и упал при первом прогоне.
        let bare_calls: Vec<&str> = text
            .lines()
            .filter(|line| !line.trim_start().starts_with("//"))
            .filter(|line| line.contains(&bare_call))
            .collect();
        assert!(
            bare_calls.is_empty(),
            "в {path:?} появился вызов {bare_call} методом: {bare_calls:?}. \
             Если в области видимости есть трейт fs4, собственный метод \
             `File` из std (Rust 1.89+) всё равно победит — и реализация \
             замка станет зависеть от версии компилятора. Зови полным путём: \
             fs4::FileExt::try_lock(&file). См. {REASONING}"
        );
        assert!(
            text.contains("fs4::FileExt::try_lock(&file)"),
            "в {path:?} не осталось вызова блокировки fs4 полным путём. \
             См. {REASONING}"
        );
    }

    /// Точка входа берёт замок и делает это до `run`.
    ///
    /// Текстовый сторож, и это стоит назвать прямо: он проверяет намерение
    /// в исходнике, а не факт единственности в рантайме. Факт проверяется
    /// тестами с двумя процессами выше — но они ничего не знают о
    /// `main.rs`, и без этого сторожа удалённый вызов не роняет ничего:
    /// сборка зелёная, тесты зелёные, экземпляров два.
    #[test]
    fn the_entry_point_claims_the_lock_before_it_runs() {
        let path = manifest_dir().join("src/main.rs");
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|err| panic!("{path:?} не читается: {err}"));

        assert!(
            text.contains("single_instance::claim_for(app.handle())"),
            "в {path:?} не осталось попытки взять замок единственного \
             экземпляра. Ни сборка, ни остальные тесты этого не заметят: \
             приложение просто снова запускается дважды. См. {REASONING}"
        );
        assert!(
            text.contains(".build(single_instance::context())"),
            "в {path:?} контекст собирается не через single_instance::context — \
             идентификатор dev-сборки не разведён с установленной, а с ним и \
             каталог данных с замком. См. {REASONING}"
        );

        // Проверяется не «где-то до run», а «между build и run», и разница
        // существенная. «После run» защищено типами: `App::run` забирает
        // `app` по значению, так что `app.handle()` после него просто не
        // скомпилируется. А вот перенести взятие замка внутрь `Builder::setup`
        // компилятор позволит — и это тихая поломка: setup выполняется уже
        // из цикла событий, когда окно создано, а подготовка yt-dlp
        // запущена. В тексте `setup` идёт до `.build(`, поэтому нижняя
        // граница здесь именно `.build(`.
        let build_at = text
            .find(".build(single_instance::context())")
            .expect("вызов build только что был найден");
        let claim_at = text
            .find("single_instance::claim_for")
            .expect("вызов claim_for только что был найден");
        let run_at = text.find("app.run(").expect("вызова app.run не осталось");
        assert!(
            build_at < claim_at && claim_at < run_at,
            "замок берётся не между build и run. Внутри setup (а он до build \
             по тексту) окно уже создано и подготовка yt-dlp запущена — \
             лишний экземпляр успел бы мигнуть окном и тронуть дерево \
             установок. См. {REASONING}"
        );
    }
