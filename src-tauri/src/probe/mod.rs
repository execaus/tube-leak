//! Разбор ссылки на ролик: метаданные и лестница качеств (эпик E2).
//!
//! Модуль состоит из типизированной ошибки домена ([`ProbeFailure`],
//! TL-27) — контракта, на который опираются остальные задачи эпика, —
//! схлопывания форматов yt-dlp в лестницу качеств ([`build_quality_ladder`],
//! TL-30) и классификации исхода запуска yt-dlp ([`classify`], TL-31).
//! Все три куска чистые: процессов здесь не запускается и таймаутов не
//! отсчитывается — это TL-32 (оркестрация и команды `probe_url` /
//! `cancel_probe`).
//!
//! Ошибка домена и контрактный [`crate::types::ProbeError`] — разные типы
//! по той же причине, что и в [`crate::ytdlp`]: домен несёт всё, что знает
//! ядро (включая полную формулировку для лога), а через границу команды
//! уходит классификация и уже урезанные технические детали (Н-4).

mod classify;
mod error;
mod quality;

// Реэкспорт наружу модуля — так к ошибке обратятся TL-31 и TL-32
// (`crate::probe::ProbeFailure`), как это уже сделано в `crate::ytdlp` и
// `crate::sidecar`. Пока обращаться некому, отсюда `allow`.
#[allow(unused_imports)]
pub use error::ProbeFailure;

// Классификация исхода запуска yt-dlp (TL-31) — вход оркестрации TL-32:
// та запускает процесс и приносит сюда его код завершения, stdout и
// stderr. До неё вызывающего нет, отсюда `allow`.
#[allow(unused_imports)]
pub use classify::{classify, YtDlpOutcome};

// Лестница качеств (TL-30) — вход оркестрации TL-32: та разберёт JSON
// yt-dlp и передаст его сюда. До неё вызывающего нет, отсюда `allow`.
#[allow(unused_imports)]
pub use quality::build_quality_ladder;
