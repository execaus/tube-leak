//! Разбор ссылки на ролик: метаданные и лестница качеств (эпик E2).
//!
//! Модуль состоит из типизированной ошибки домена ([`ProbeFailure`],
//! TL-27) — контракта, на который опираются остальные задачи эпика, —
//! схлопывания форматов yt-dlp в лестницу качеств ([`build_quality_ladder`],
//! TL-30) и классификации исхода запуска yt-dlp ([`classify`], TL-31).
//! Первые два куска чистые: процессов в них не запускается и таймаутов не
//! отсчитывается. Запуск, таймаут, отмена и порядок вызовов — в
//! [`orchestrate`] (TL-32), она же собирает карточку и её зовут команды
//! `probe_url` / `cancel_probe`.
//!
//! Ошибка домена и контрактный [`crate::types::ProbeError`] — разные типы
//! по той же причине, что и в [`crate::ytdlp`]: домен несёт всё, что знает
//! ядро (включая полную формулировку для лога), а через границу команды
//! уходит классификация и уже урезанные технические детали (Н-4).

mod classify;
mod error;
mod orchestrate;
mod quality;

// Наружу модуля уходит только то, что зовёт команда (TL-32): сам разбор,
// его состояние, продакшен-запускатель, валидация ввода и доменная ошибка.
// Классификация (TL-31) и лестница (TL-30) — внутренние шаги оркестрации,
// и вызывающих за пределами `probe` у них нет.
pub use error::ProbeFailure;
pub use orchestrate::{probe, validate_url, ProbeSession, SidecarLauncher};

// Исключение из правила выше — и оно объявлено здесь, а не сделано молча
// открытием модуля. Четыре класса скачивания (E3) носят на проводе те же
// значения, что классы разбора, потому что тексты для них уже написаны;
// значит и распознаваться они обязаны одними и теми же маркерами, в одном
// и том же порядке. Открыт ровно этот кусок классификации — извлечение
// текста отказа, общие классы, транспортный сбой и под-причина «устарел»;
// сами маркеры и разбор метаданных остаются внутренним делом E2.
// `normalize_typography` открыт по той же причине и на тех же правах:
// маркеры скачивания сравниваются с текстом так же, как маркеры разбора,
// и если сведение типографских знаков к ASCII (TL-122) останется только
// здесь, у второго классификатора вернётся ровно тот дефект, который
// правился в первом.
pub(crate) use classify::{
    fatal_text, is_transport_failure, normalize_typography, shared_failure_class,
    yt_dlp_failure_reason, SharedFailureClass,
};
