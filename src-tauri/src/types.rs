/// Девять классов отказа разбора (Ф-6). Ровно по ним фронтенд выбирает
/// заголовок, пояснение и наличие кнопки «Повторить» (таблица в дизайне
/// E2) — тексты живут на стороне UI, в контракте только классификация.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "probe.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum ProbeErrorKind {
    /// Ввод не является http(s)-ссылкой (С-4). Единственный класс, который
    /// возникает **до** запуска процесса: yt-dlp не запускается вовсе,
    /// поэтому у него нет ни `details`, ни «Подробнее» на экране.
    NotAUrl,
    /// Ролик удалён, снят с публикации или никогда не существовал (С-5).
    /// Приватный ролик сюда НЕ относится — он приходит классом
    /// `signInRequired`: детерминированного правила, отличающего его от
    /// честного «требуется вход», не существует (ревью TL-31).
    VideoUnavailable,
    /// Нужен вход в аккаунт YouTube — возрастное ограничение, подписка и
    /// прочее (С-6). Возрастное ограничение отдельным классом не выделено
    /// сознательно: без входа (E8) действие пользователя одно и то же.
    SignInRequired,
    /// Ролик не показывается в стране пользователя (С-7).
    RegionBlocked,
    /// Нет соединения с интернетом (С-8).
    NetworkUnavailable,
    /// Ссылка ведёт на плейлист или канал (С-9). Ролик с параметром
    /// плейлиста (`watch?v=…&list=…`) этим классом не является — он
    /// разбирается как одиночный ролик.
    PlaylistUnsupported,
    /// Идущий эфир или запланированная премьера (С-10). Завершённая
    /// трансляция с готовой записью — обычный ролик, не этот класс.
    LiveUnsupported,
    /// Сбой yt-dlp, не отнесённый к классам выше (С-12). Под-причина —
    /// в `reason`.
    YtDlpFailure,
    /// Разбор не уложился в отведённое время, процесс убит. Значение
    /// сработавшего порога — в `timeoutSecs`.
    Timeout,
}

/// Под-причина класса `ytDlpFailure` (С-12): меняет только текст пояснения,
/// класс остаётся один — тот же приём, что `launchFailed.reason` в E1.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "probe.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum YtDlpFailureReason {
    /// Ошибка без узнаваемой сигнатуры: «попробуйте ещё раз».
    Generic,
    /// В выводе опознан признак того, что встроенный yt-dlp не понимает
    /// текущий ответ YouTube. Обновление — E6; здесь только честный текст.
    Outdated,
}

/// Технические детали отказа для свёрнутого «Подробнее».
///
/// Через границу команды идёт именно это — хвост stderr и код завершения,
/// а не поток целиком: полный stderr пишется в лог приложения и на экран
/// не попадает ни в каком состоянии (Н-4).
///
/// Пустая структура границу не пересекает: если сказать нечего, у ошибки
/// нет `details` вовсе (см. [`ProbeErrorDetails::is_empty`] и проекцию
/// [`crate::probe::ProbeFailure::to_contract`]). Иначе фронтенд получил бы
/// повод нарисовать «Подробнее», за которым пусто.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "probe.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct ProbeErrorDetails {
    /// Хвост stderr процесса, обрезанный по длине.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stderr_tail: Option<String>,
    /// Код завершения процесса yt-dlp, если процесс успел завершиться сам.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub exit_code: Option<i32>,
}

impl ProbeErrorDetails {
    /// Нечего показывать: ни хвоста stderr, ни кода завершения.
    ///
    /// Так бывает у процесса, убитого по таймауту раньше, чем он что-то
    /// написал, — и это не повод отдавать фронтенду пустой объект.
    pub fn is_empty(&self) -> bool {
        self.stderr_tail.is_none() && self.exit_code.is_none()
    }
}

/// Отказ разбора в сериализуемом виде — то, чем реджектится `probe_url`.
///
/// Решение принимается по `kind` (и по `reason` внутри `ytDlpFailure`);
/// `message` — формулировка ядра для «Подробнее» и лога, **не** основной
/// текст на экране: тексты для пользователя задаёт UI по классу (дизайн
/// E2), и stderr в них не попадает никогда (Н-4).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "probe.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct ProbeError {
    pub kind: ProbeErrorKind,
    pub message: String,
    /// Только при `kind = ytDlpFailure`; для него заполняется всегда.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reason: Option<YtDlpFailureReason>,
    /// Только при `kind = timeout`: сработавший порог в секундах,
    /// подставляется в текст ошибки («…за отведённое время (N с)»).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub timeout_secs: Option<u64>,
    /// Отсутствует, когда деталей нет: `notAUrl` (процесс не запускался) и
    /// вообще любой отказ, о котором нечего сказать технически.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub details: Option<ProbeErrorDetails>,
}

// ───────────────────────── скачивание ролика (TL-38) ─────────────────────────
//
// Контракт эпика E3: чем ядро отчитывается о задаче скачивания и что
// принимают три её команды. Реализация — TL-41 (разбор прогресса и
// агрегация), TL-42 (склейка), TL-43 (классификация ошибок и ретраи),
// TL-44 (оркестрация и сами команды); здесь только объявление типов,
// которые зеркалятся в `src/types/` (TL-39).
//
// До появления оркестрации (TL-44) типы секции никто не конструировал, и
// каждый нёс `#[allow(dead_code)]` — тот же приём и та же причина, что были
// у секции E2: контракт не должен исчезать из-за того, что реализация
// отстаёт на задачу. Вызывающий появился — глушители сняты, и остался ровно
// один, у `DownloadPercent::value` (см. комментарий там же): дальше
// `dead_code` в этой секции означает настоящий мёртвый код.
//
// Три вещи, которые дизайн развёл намеренно, и то, как это выражено здесь:
//
// 1. **Процент осмыслен только внутри фазы `downloading`.** Поэтому
//    [`DownloadProgress`] — размеченное объединение по `phase`, а не
//    структура с опциональным `percent` рядом с полем фазы: сквозную шкалу
//    «сколько процентов всей задачи» этой формой не выразить, и «Склейка»
//    физически не может продолжить ту же шкалу — у её варианта нет поля
//    процента вовсе.
// 2. **Три разных «нет движения»** различены по месту, а не по флагу.
//    Косметический индикатор фронтенда (5 с без событий) в контракте не
//    представлен и представлен быть не может: он определяется отсутствием
//    событий, а не их содержимым. Сторож «ноль байт 20 с» в ядре тоже не
//    имеет своего значения на проводе — по дизайну он не показывается
//    пользователем отдельно, а переводит задачу в третье состояние. И
//    только оно, пауза между попытками, — отдельный вариант
//    [`DownloadingState::WaitingRetry`], а не «то же `Running`, только с
//    другими числами».
// 3. **Что осталось на диске** — не текст UI и не таблица на его стороне, а
//    факт, о котором отчитывается ядро ([`PartialData`]): оно и удаляет.
//    Таблица дизайна почти для всех классов постоянна, но не для всех
//    (у `destinationUnavailable` исход зависит от того, доступна ли ещё
//    папка), а классы, приходящие в фазе `fetching`, не удаляют ничего —
//    удалять нечего. Постоянна и потому выводится из класса только
//    осмысленность повтора: [`DownloadErrorKind::is_retryable`].

/// Фаза задачи скачивания (Ф-3). Ровно семь — по автомату
/// `Queued → Fetching → Downloading → Merging → Done / Failed / Cancelled`.
///
/// Это то, из чего фронтенд рисует степпер шагов, а не внутренние шаги
/// реализации. Ожидание повтора между попытками (С-6) отдельной фазой
/// **не** является: по дизайну степпер в паузе продолжает показывать
/// «Скачивание», а отличается панель содержимым — см.
/// [`DownloadingState`].
///
/// Шаг «Склейка» рисуется не всегда: для «только аудио» и прогрессивного
/// формата (С-2, С-3) ffmpeg не запускается вовсе, и фазы `merging` в
/// жизни такой задачи не будет. Знать об этом заранее — до того, как фаза
/// наступит или не наступит, — фронтенду нужно уже в момент старта, и
/// говорит ему это [`DownloadPlan`], а не догадка по числу форматов.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum DownloadPhase {
    /// Задача создана, процесс ещё не запускался.
    Queued,
    /// yt-dlp запущен, данных о прогрессе ещё нет («Подготовка»).
    Fetching,
    /// Идёт приём байт либо пауза перед следующей попыткой.
    Downloading,
    /// Оба потока скачаны, ffmpeg объединяет их (remux, Ф-9).
    Merging,
    /// Готовый файл лежит в папке назначения под финальным именем.
    Done,
    /// Задача завершилась ошибкой одного из девяти классов.
    Failed,
    /// Задача отменена пользователем (Ф-4).
    Cancelled,
}

/// Сколько потоков скачивает задача — то есть какой степпер рисовать.
///
/// Отдаётся один раз, в ответе команды старта, а не в каждом событии
/// прогресса: величина постоянна на всю жизнь задачи, и повторять её
/// 3 раза в секунду незачем.
///
/// Почему это в контракте, а не выводится фронтендом из того, что он сам
/// же и отправил (два `formatId` — значит будет склейка): правило «два
/// потока ⇒ склейка» живёт в ядре, потому что ядро и решает, запускать ли
/// ffmpeg. Копия правила во фронтенде была бы второй, и разошлись бы они
/// молча — ровно то, чего требование «типы объявляются один раз в Rust»
/// и просит избегать.
///
/// Довода «панель не имеет права зависеть от данных карточки» здесь
/// сознательно нет: как общее правило он неверен — заголовок панели и
/// текст диалога выхода фронтенд всё равно снимает с карточки в момент
/// клика и держит у себя. Речь именно о правиле, а не об источнике
/// данных.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum DownloadPlan {
    /// Раздельные видео- и аудиопоток: Подготовка → Скачивание → Склейка →
    /// Готово.
    VideoAndAudio,
    /// Один поток — «только аудио» либо прогрессивный формат (С-2, С-3):
    /// Подготовка → Скачивание → Готово, шага «Склейка» не будет.
    SingleStream,
}

/// Какой из двух потоков принимается прямо сейчас (подпись «Скачиваем
/// видео…» / «Скачиваем звук…»).
///
/// Это подслой внутри шага «Скачивание», а не фаза задачи: смена потока не
/// меняет ни шаг степпера, ни шкалу процента — процент агрегирован по обоим
/// потокам сразу и от перехода видео → аудио назад не откатывается (Ф-2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum DownloadStream {
    Video,
    Audio,
}

/// Доля скачанного в процентах, 0..=100.
///
/// Отдельный тип, а не голый `u8`, ради одного инварианта: на провод не
/// уходит число больше ста. Это не педантизм — знаменатель агрегации на
/// старте берётся из оценки размера, которую дал разбор E2, и уточняется
/// фактическим размером потока уже по ходу приёма (дизайн, «Агрегация
/// видео+аудио»); заниженная оценка даёт «103 %» раньше, чем уточнение
/// приедет. Обрезание в конструкторе делает это невыразимым, а не
/// оставляет полосе прогресса выезжать за край.
///
/// Для задачи разбора прогресса (TL-41) важно прочесть это правильно:
/// обрезание — **страховка от выезда полосы, а не замена уточнению
/// знаменателя**. Показанные подряд «99, 100, 100, 100 %» на заниженной
/// оценке — такой же дефект «нет движения», как застывшая скорость;
/// чинится он тем, что фактический размер потока, сообщённый yt-dlp,
/// заменяет оценку E2, а не тем, что число упирается в сотню.
///
/// На проводе — просто число (`#[serde(transparent)]`): TS-зеркало видит
/// `number`, отдельного объекта тут нет.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(transparent)]
pub struct DownloadPercent(u8);

impl DownloadPercent {
    /// Единственный конструктор: всё, что больше ста, становится сотней.
    pub fn new(percent: u8) -> Self {
        Self(percent.min(100))
    }

    /// Значение для форматирования на стороне вызывающего.
    ///
    /// Единственный член секции, у которого глушитель остался и после
    /// TL-44: продакшен-путь процент только **строит** и сериализует, а
    /// разворачивать его обратно в число незачем — форматирует его UI по
    /// ту сторону границы. Читают его отсюда только тесты, которые
    /// проверяют, что показанный процент не откатывается назад.
    #[allow(dead_code)]
    pub fn value(self) -> u8 {
        self.0
    }
}

/// Номер попытки и их предел — «попытка 2 из 8».
///
/// `number` — номер той попытки, о которой идёт речь **сейчас**: в
/// [`DownloadingState::Running`] это идущая попытка, в
/// [`DownloadingState::WaitingRetry`] — та, которая начнётся по истечении
/// паузы (дизайн: «Ждём повторной попытки (2 из 8)»). Разница ровно на
/// единицу, и путать её на границе дорого — отсюда явная оговорка здесь, а
/// не два поля с почти одинаковыми именами.
///
/// `total` — предел числа попыток подряд, без продвижения. Дизайн назвал
/// стартовым значением 6; калибровка на собранном bundle (TL-44) подняла
/// его до 8 — замер и его причина записаны у самой константы
/// (`crate::download::retry::MAX_ATTEMPTS`). Число живое: E5 сделает его
/// настройкой, и `total` в событии обязано показывать то, что действует
/// сейчас, а не константу из чьей-нибудь копии. Счётчик обнуляется
/// любым продвижением байт (С-6), поэтому `number` за долгую загрузку
/// может доходить до `total` многократно и это не признак близкого отказа.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadAttempt {
    pub number: u32,
    pub total: u32,
}

/// Что стало с частично скачанными данными к моменту терминальной фазы.
///
/// Отдельное значение на проводе, а не таблица «класс → судьба файлов» на
/// стороне UI, по двум причинам. Во-первых, удаляет их ядро — оно и
/// отчитывается о том, что сделало, а не фронтенд, который угадывает по
/// классу. Во-вторых, таблица дизайна не постоянна: у
/// [`DownloadErrorKind::DestinationUnavailable`] частичное «сохраняется,
/// если технически осталось доступным», а классы, пришедшие ещё в фазе
/// `fetching`, не оставляют и не удаляют ничего — файлов не появлялось.
///
/// Для [`DownloadProgress::Cancelled`] значений бывает ровно два:
/// подчистка при отмене всегда полная и без исключений по классам (Ф-4,
/// таблица «Отмена по фазам»), поэтому либо `removed`, либо
/// `nothingCreated` — если отменили до старта процесса.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum PartialData {
    /// Файлов не появлялось: задача не дошла до приёма байт.
    NothingCreated,
    /// Частично скачанное удалено ядром — на диске не осталось ничего.
    Removed,
    /// Частично скачанное оставлено на диске: повтор продолжит с места
    /// штатным механизмом докачки yt-dlp (С-7, С-9).
    Kept,
}

/// Девять классов отказа скачивания (Ф-10). Ровно по ним фронтенд выбирает
/// заголовок и пояснение (таблица в дизайне E3) — тексты живут на стороне
/// UI, в контракте только классификация.
///
/// Пять классов — свои для E3, четыре последних переиспользуют смысловые
/// классы разбора: их строки на проводе **совпадают** с одноимёнными
/// значениями [`ProbeErrorKind`] намеренно, чтобы тексты, уже написанные
/// для карточки E2, годились без перевода (сторож —
/// `reused_error_kinds_keep_their_probe_wire_values`).
///
/// Чего в девятке сознательно нет:
///
/// - **`timeout`** (E2 выделяет его отдельным классом). Таймаут фазы
///   «Подготовка» (стартовое значение дизайна — 20 с) в E3 отдельного
///   класса не получает: девятка зафиксирована декомпозицией, и честнее
///   всего он ложится в [`DownloadErrorKind::YtDlpFailure`] — тот самый
///   «сбой, не отнесённый к классам выше», с текстом «Попробуйте ещё раз».
/// - **`networkUnavailable`** (тоже класс E2). Отсутствие сети во время
///   скачивания не отказ, а повод к циклу повторов (С-6); отказом оно
///   становится, только когда попытки исчерпаны, и тогда это
///   [`DownloadErrorKind::ConnectionLost`] — вне зависимости от того, была
///   ли сеть в начале.
///
/// А вот под-причина `outdated` у сбоя yt-dlp из E2 переносится и живёт
/// отдельным полем [`DownloadError::reason`] — почему, написано там же.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum DownloadErrorKind {
    /// Соединение потеряно, попытки исчерпаны (С-7).
    ConnectionLost,
    /// Место на диске кончилось по ходу записи (С-9).
    DiskFull,
    /// Выбранный формат больше не отдаётся: данные разбора устарели (С-10).
    StaleFormat,
    /// Потоки скачаны, ffmpeg завершился ошибкой (С-11).
    MergeFailed,
    /// Папка назначения недоступна: нет прав либо её не существует.
    DestinationUnavailable,
    /// Ролик удалён, снят с публикации или не существует (класс E2).
    VideoUnavailable,
    /// Нужен вход в аккаунт YouTube (класс E2).
    SignInRequired,
    /// Ролик не показывается в стране пользователя (класс E2).
    RegionBlocked,
    /// Сбой yt-dlp, не отнесённый к классам выше (класс E2).
    YtDlpFailure,
}

impl DownloadErrorKind {
    /// Имеет ли смысл повтор той же задачи — колонка «Повторить?» таблицы
    /// ошибок дизайна.
    ///
    /// Выводится из класса, а не передаётся отдельным полем структуры:
    /// таблица здесь безусловна, и это единственное место, где она
    /// записана. Им пользуются обе стороны — фронтенд решает, рисовать ли
    /// кнопку, ядро отклоняет команду повтора для класса, где повтор
    /// заведомо бесполезен ([`DownloadCommandErrorKind::NotRetryable`]).
    /// Значение уезжает на провод в поле `retryable` (см.
    /// [`DownloadError`]) — не как второй источник правды, а как проекция
    /// этой функции.
    ///
    /// `false` только там, где повтор гарантированно провалится тем же
    /// образом: устаревшие данные разбора чинятся новым разбором (Н-2 E2
    /// запрещает делать его фоном), а вход в аккаунт и региональная
    /// блокировка — не то, что меняется от повторного запуска (вход — E8).
    pub fn is_retryable(self) -> bool {
        match self {
            Self::ConnectionLost
            | Self::DiskFull
            | Self::MergeFailed
            | Self::DestinationUnavailable
            | Self::VideoUnavailable
            | Self::YtDlpFailure => true,
            Self::StaleFormat | Self::SignInRequired | Self::RegionBlocked => false,
        }
    }
}

/// Технические детали отказа для свёрнутого «Подробнее».
///
/// Форма повторяет [`ProbeErrorDetails`] и повторяет её сознательно, а не
/// переиспользует тип: «Подробнее» панели загрузки и «Подробнее» карточки —
/// разные экраны разных эпиков, и поле, которое понадобится одному, не
/// должно появляться у другого молча. Правило Н-4 E2 общее для обоих:
/// через границу идёт хвост stderr и код завершения, полный поток пишется
/// в лог приложения и на экран не попадает никогда.
///
/// Пустая структура границу не пересекает — см. [`DownloadErrorDetails::is_empty`]
/// и проекцию `crate::download::DownloadFailure::to_contract`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadErrorDetails {
    /// Хвост stderr процесса (yt-dlp либо ffmpeg), обрезанный по длине.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stderr_tail: Option<String>,
    /// Код завершения процесса, если он успел завершиться сам.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub exit_code: Option<i32>,
}

impl DownloadErrorDetails {
    /// Нечего показывать: ни хвоста stderr, ни кода завершения.
    ///
    /// Так бывает у отказа, за которым нет процесса вовсе (недоступная
    /// папка назначения, обнаруженная до запуска), — и это не повод
    /// отдавать фронтенду пустой объект, за которым откроется пустое
    /// «Подробнее».
    pub fn is_empty(&self) -> bool {
        self.stderr_tail.is_none() && self.exit_code.is_none()
    }
}

/// Отказ скачивания в сериализуемом виде — полезная нагрузка фазы `failed`.
///
/// Решение принимается по `kind`; `message` — формулировка ядра для
/// «Подробнее» и лога, **не** основной текст на экране: тексты по классам
/// задаёт UI (таблица дизайна E3), и stderr в них не попадает никогда
/// (Н-4).
///
/// Единственный благословлённый конструктор —
/// `crate::download::DownloadFailure::to_contract`: `retryable` обязано
/// быть ровно [`DownloadErrorKind::is_retryable`] своего класса, а не
/// чьим-то мнением на месте вызова.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadError {
    pub kind: DownloadErrorKind,
    pub message: String,
    /// Проекция [`DownloadErrorKind::is_retryable`]: есть ли смысл в
    /// команде повтора. Фронтенд рисует кнопку по этому полю, а не по
    /// собственной копии таблицы классов.
    pub retryable: bool,
    /// Только при `kind = ytDlpFailure`; для него заполняется всегда —
    /// дословно как `reason` у [`ProbeError`] в E2, и тем же типом
    /// [`YtDlpFailureReason`].
    ///
    /// Меняет текст пояснения, но не класс: девятка классов от этого поля
    /// не растёт. Нужно оно потому, что «yt-dlp устарел» — один из
    /// четырёх классов, которые CLAUDE.md обязывает делать различимыми
    /// («пользователь должен понимать, что делать»), и единственный из
    /// них, у которого в E3 иначе не было бы отдельного представления.
    /// Раздел «Границы» эпика требует при сломанном извлечении честной
    /// ошибки класса E2 — а честная ошибка E2 это и есть сбой с
    /// под-причиной; без неё на экране осталось бы «попробуйте ещё раз»,
    /// то есть ровно противоположное обещанному.
    ///
    /// Довод «действие пользователя всё равно одно» здесь не работает и
    /// был отвергнут ещё в E2: ценность не в другой кнопке, а в честном
    /// объяснении. В E3 цена выше вдвойне — бесполезный повтор разбора
    /// стоит секунд, бесполезный повтор скачивания минут, — и обе секции
    /// по дизайну живут на одном экране одна под другой: без этого поля
    /// приложение отвечало бы на одну и ту же причину двумя разными
    /// способами, не сходя с места.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reason: Option<YtDlpFailureReason>,
    /// Что стало с частично скачанным. Факт, а не свойство класса:
    /// см. [`PartialData`].
    pub partial_data: PartialData,
    /// Отсутствует, когда деталей нет: отказ без процесса за спиной
    /// (недоступная папка назначения) технически сказать ничего не может.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub details: Option<DownloadErrorDetails>,
}

/// Что происходит внутри фазы `downloading` — два взаимоисключающих
/// состояния, а не одно с флагом.
///
/// Дизайн разводит их прямо: пауза перед повтором — «отдельное, не „то же
/// Downloading, только с другим числом“ состояние». Разница видна и в
/// составе полей: у ждущей паузы нет ни скорости, ни оценки оставшегося
/// времени — их неоткуда взять, процесс уже завершился, — зато есть
/// обратный отсчёт; показывать в этот момент последнюю известную скорость
/// значило бы врать (тот же класс дефекта, что «не отвечает» в E1).
///
/// Второе из трёх «нет движения» — сторож ядра «ни одного нового байта
/// за 20 с» (С-8) — своего варианта здесь не имеет намеренно: по дизайну
/// пользователю не показывают «поток завис», зависшая попытка признаётся
/// неудавшейся и уходит в тот же цикл повторов, то есть наблюдаемо
/// становится [`DownloadingState::WaitingRetry`]. Третье, «событий не было
/// 5 с», — косметика фронтенда и в контракте не выразимо в принципе:
/// это отсутствие событий, а не их содержимое.
///
/// Оговорка про сериализацию: `rename_all` у enum переименовывает
/// **варианты**, но не поля внутри них, — за поля struct-вариантов
/// отвечает отдельный `rename_all_fields`. Без него `delay_secs` уехал бы
/// на провод змеиным регистром посреди camelCase-объекта; поймано
/// сравнением значения целиком в тестах ниже, а не глазами.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(
    tag = "state",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum DownloadingState {
    /// Байты идут (или только что пошли).
    Running {
        /// Какой поток принимается. Присутствует только у задачи с двумя
        /// потоками ([`DownloadPlan::VideoAndAudio`]); при одном потоке
        /// различать нечего, и подпись на экране — просто «Скачиваем…».
        #[serde(skip_serializing_if = "Option::is_none")]
        stream: Option<DownloadStream>,
        /// Агрегированная доля обоих потоков. Отсутствует, пока считать
        /// не из чего: размер потока ещё не известен ни из оценки E2, ни
        /// от yt-dlp. Не «0» — ноль означал бы «ничего не скачано».
        #[serde(skip_serializing_if = "Option::is_none")]
        percent: Option<DownloadPercent>,
        /// Мгновенная скорость в байтах в секунду; форматирование
        /// («4,2 МБ/с») — на UI.
        #[serde(skip_serializing_if = "Option::is_none")]
        speed_bytes_per_sec: Option<u64>,
        /// Оценка оставшегося времени в секундах, как её даёт yt-dlp.
        #[serde(skip_serializing_if = "Option::is_none")]
        eta_secs: Option<u64>,
        /// Номер идущей попытки — только начиная со второй: на обычном
        /// пути номер всегда «1», и рисовать его значит загромождать
        /// экран числом, которое ничего не сообщает.
        #[serde(skip_serializing_if = "Option::is_none")]
        attempt: Option<DownloadAttempt>,
    },
    /// Попытка не удалась, идёт пауза перед следующей (С-6).
    WaitingRetry {
        /// Последний известный процент, замороженный на время паузы:
        /// К-6 требует, чтобы он не откатывался к нулю. Отсутствует,
        /// только если процента не было и до обрыва.
        #[serde(skip_serializing_if = "Option::is_none")]
        percent: Option<DownloadPercent>,
        /// Попытка, которая начнётся по истечении паузы, и предел
        /// («2 из 8»). В этом состоянии всегда известна — паузы без
        /// следующей попытки не бывает.
        attempt: DownloadAttempt,
        /// Полная длительность текущей паузы: растёт от 5 с удвоением,
        /// потолок 60 с (стартовые значения дизайна).
        ///
        /// Число **справочное** — для формы, которой нужна доля (кольцо,
        /// полоса ожидания). Инварианта «остаток не больше её» контракт не
        /// держит и конструктором не проверяет: значения приезжают из
        /// разных источников (текущий шаг политики повторов и живой
        /// таймер), и запрет на их расхождение стоил бы конструктора,
        /// умеющего падать, там, где событие обязано уехать всегда. Если
        /// пара разошлась — верен обратный отсчёт.
        delay_secs: u64,
        /// Сколько секунд паузы осталось — обратный отсчёт на экране.
        /// Это то, что показывается пользователю.
        remaining_secs: u64,
    },
}

/// Состояние задачи скачивания на момент события — размеченное по фазе
/// объединение.
///
/// Форма выбрана так, чтобы сквозная шкала «процентов всей задачи» была
/// невыразима (дизайн отвергает её явно): процент есть только внутри
/// `downloading`, у `merging` его нет и быть не может — remux не даёт
/// надёжной оценки дешевле, чем сам remux, и по дизайну показывается
/// нейтральным индикатором без числа.
///
/// На проводе тег — поле `phase` с теми же семью значениями, что у
/// [`DownloadPhase`]; у варианта `downloading` рядом появляется второй тег
/// `state` ([`DownloadingState`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(
    tag = "phase",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum DownloadProgress {
    /// Задача создана, процесс ещё не запускался.
    Queued,
    /// yt-dlp запущен, прогресса ещё нет («Подготовка»). Числа здесь нет
    /// сознательно: пока не пришло ни одной строки прогресса, любое —
    /// выдумка.
    Fetching,
    Downloading(DownloadingState),
    /// ffmpeg объединяет скачанные потоки. Без процента — см. doc типа.
    Merging,
    Done {
        /// Имя готового файла с фактическим расширением, без пути.
        file_name: String,
        /// Папка, куда файл положен на самом деле (Ф-15, TL-83).
        ///
        /// Закрывает долг E3: пока папка была константой, текст «сохранён в
        /// папке „Загрузки“» был правдой. С папкой-настройкой (E5) он
        /// протухает, и показывать нужно ту папку, куда файл лёг.
        /// Объединение, а не строка: см. [`FolderDisplay`]. Поле
        /// обязательное: папка у готового файла есть всегда.
        folder_display: FolderDisplay,
    },
    Failed {
        error: DownloadError,
    },
    Cancelled {
        /// При отмене подчистка всегда полная, поэтому здесь бывает либо
        /// `removed`, либо `nothingCreated` (отмена в `queued`) — разница
        /// ровно та, что разводит два текста панели в дизайне.
        partial_data: PartialData,
    },
}

impl DownloadProgress {
    /// Фаза задачи для степпера.
    ///
    /// Выводится из варианта, а не хранится рядом: два поля, способных
    /// разойтись, — приглашение к состоянию, где степпер показывает одно,
    /// а панель другое. Поле `phase` на проводе — тег этого же
    /// объединения, то есть та же величина, а не её копия.
    pub fn phase(&self) -> DownloadPhase {
        match self {
            Self::Queued => DownloadPhase::Queued,
            Self::Fetching => DownloadPhase::Fetching,
            Self::Downloading(_) => DownloadPhase::Downloading,
            Self::Merging => DownloadPhase::Merging,
            Self::Done { .. } => DownloadPhase::Done,
            Self::Failed { .. } => DownloadPhase::Failed,
            Self::Cancelled { .. } => DownloadPhase::Cancelled,
        }
    }

    /// Терминальна ли фаза: слот свободен, и выход из приложения не
    /// спрашивает подтверждения (Р-2).
    ///
    /// **Терминальная — не значит «навсегда молчащая».** Поток событий по
    /// задаче обрывается насовсем только после отмены и готовности: там
    /// задача прожита до конца. После отказа он **возобновляется** —
    /// команда повтора продолжает ту же задачу с тем же `taskId` (см. doc
    /// [`crate::download`]), снова занимая слот и снова присылая события с
    /// начала своей фазовой цепочки. Подписчику панели поэтому нельзя
    /// отписываться или начинать фильтровать события по факту `failed`:
    /// именно так повтор нарисовался бы мёртвой панелью.
    pub fn is_terminal(&self) -> bool {
        matches!(
            self,
            Self::Done { .. } | Self::Failed { .. } | Self::Cancelled { .. }
        )
    }
}

/// Полезная нагрузка события `download://progress`
/// (константа `PROGRESS_EVENT` в `crate::download`).
///
/// Ключ задачи — `taskId`: события ключуются им с самого начала, хотя
/// активная задача в E3 ровно одна. Это требование CLAUDE.md и задел под
/// очередь E4, который не переписывается: подписчик обязан сверять id, а не
/// считать, что любое пришедшее событие — про его панель.
///
/// Частота эмита ограничена (стартовое значение дизайна — не чаще раза в
/// 300 мс), кроме перехода в терминальную фазу: он не может быть проглочен
/// троттлингом. Это поведение ядра (TL-44), а не свойство типа, но
/// подписчик должен знать, что событий не бывает «на каждый байт».
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadProgressEvent {
    pub task_id: String,
    /// Разворачивается в те же поля объекта, что и сам вариант: `phase`
    /// лежит рядом с `taskId`, а не вложенным объектом.
    #[serde(flatten)]
    pub progress: DownloadProgress,
}

/// Вход команды «начать загрузку».
///
/// Собирается ровно из того, что уже есть на экране к моменту клика:
/// ссылка из поля ввода, название ролика и потоки выбранного пункта
/// лестницы. Папка назначения, число попыток и таймауты параметрами не
/// являются — это константы дизайна (Р-1 и таблица «Числа»), и настройками
/// они станут в E5, не меняя форму этой команды.
///
/// **Про `url`.** Дизайн перечисляет только потоки и название («принимает
/// то, что уже есть у карточки E2»), но без адреса скачивать нечего:
/// yt-dlp запускается как `yt-dlp -f <formatId> <URL>`, а результат разбора
/// E2 адреса не содержит и в ядре между вызовами не хранится. Держать
/// «последнюю разобранную ссылку» состоянием ядра — тот же класс скрытой
/// связи, который С-13 требует разорвать (разбор новой ссылки не должен
/// касаться идущей загрузки), поэтому адрес едет явным полем. Он —
/// пользовательский ввод и потому проверяется ядром заново (Ф-1: ничего
/// непроверенного в аргументы процесса), даже если фронтенд отдаёт ту же
/// строку, которую уже разобрал.
///
/// Название — тоже непроверенный ввод с точки зрения файловой системы:
/// имя файла из него строит санитизация ядра (Ф-6, TL-40), и пустой
/// результат санитизации получает запасное имя, выведенное из адреса.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct StartDownloadRequest {
    /// Ссылка на ролик — та же, которую разобрал E2.
    pub url: String,
    /// Название ролика как его показала карточка, без обрезания: чем оно
    /// станет в имени файла, решает санитизация ядра.
    pub title: String,
    /// Выбранный пункт лестницы в том виде, в каком подписана его строка
    /// (E4, TL-70): вид пункта и ступень качества.
    ///
    /// **Единственная правка формы этой команды за эпик E4**, и без неё
    /// не собирается ни один экран очереди. Заголовок задачи —
    /// ««Название» — качество» (дизайн E4), а очередь переживает
    /// перезапуск приложения (Ф-9): после него у фронтенда нет ни
    /// карточки E2, ни лестницы, из которой он собирал подпись пункта в
    /// момент клика, — и взять её неоткуда, потому что повторный разбор
    /// запрещён обещанием Ф-3 E2. Вывести подпись из `streams` нельзя:
    /// это непрозрачные идентификаторы форматов yt-dlp.
    ///
    /// Ядро значение не интерпретирует и ничего по нему не решает — оно
    /// хранит его вместе с задачей (Ф-9) и возвращает в снимке
    /// ([`QueueTask::quality`]) и в отказе по дублю
    /// ([`QueueTaskRef::quality`]). На сравнение дублей (Ф-8) поле не
    /// влияет: пункт качества там сравнивается по `streams`.
    pub quality: SelectedQuality,
    /// Потоки выбранного пункта лестницы. Тип E2 переиспользуется как
    /// есть — одно из двух полей контракта разбора, которые ходят в обе
    /// стороны границы (см. [`QualityStreams`]). Объект без единого потока
    /// команда обязана отклонить ([`QualityStreams::has_any`],
    /// [`DownloadCommandErrorKind::NoStreamsSelected`]).
    pub streams: QualityStreams,
    /// Оценка размера того же пункта — стартовый знаменатель агрегации
    /// прогресса (дизайн E3: «Ожидаемые размеры на старте берутся из
    /// оценки, которую уже вернул разбор E2»).
    ///
    /// **Поле обязательное, а не `Option`.** Оценка есть у каждого пункта
    /// лестницы всегда — просто иногда со значением
    /// [`QualitySize::Unknown`] (Ф-4 E2); «неизвестно» уже выражено самим
    /// типом, и `Option` поверх него завёл бы третье состояние («поле не
    /// прислали»), которого не существует ни у одного пункта. Фронтенд
    /// берёт величину из того же объекта лестницы, что и `streams`, —
    /// дополнительных данных ему собирать не нужно.
    ///
    /// Зачем она ядру. Пока знаменатель неизвестен, агрегация двух потоков
    /// вынуждена брать веса 50/50 (правило дизайна для неизвестного
    /// размера), а по байтам видео обычно весит около 70 % пункта — полоса
    /// проходила бы половину за 90 % времени и вторую половину за 10 %.
    /// Замерено на живых данных: тест
    /// `two_streams_without_an_estimate_fall_back_to_equal_weights` в
    /// `crate::download::aggregate` показывает ровно эту разницу.
    ///
    /// Ядро оценке не верит на слово: как только yt-dlp сообщает
    /// фактический размер потока, тот вытесняет оценку из знаменателя
    /// (см. шапку `crate::download::aggregate`). Заниженная оценка
    /// поэтому портит только темп полосы, а не её конец.
    pub size: QualitySize,
}

/// Ответ команды «начать загрузку»: задача создана.
///
/// Возвращается быстро и не дожидается ни одного байта — вся работа идёт
/// событиями. Ждать в промисе тут нечего: загрузка длится минуты и часы.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadStarted {
    /// Идентификатор задачи, непрозрачный для фронтенда: он приходит
    /// обратно в событиях и в командах отмены и повтора, но не
    /// разбирается на части и ничего не означает.
    pub task_id: String,
    /// Фаза, в которой задача создана. Всегда `queued` в E3 (активная
    /// задача одна, и стартовать ей нечего ждать), но фронтенд рисует
    /// панель по этому полю, а не по константе: в E4 задача может встать
    /// за уже идущей и остаться в `queued` надолго.
    pub phase: DownloadPhase,
    /// Один поток или два — то есть будет ли шаг «Склейка».
    pub plan: DownloadPlan,
}

/// Почему команда управления загрузкой или очередью отклонена.
///
/// Это **не** классы отказа самой загрузки ([`DownloadErrorKind`]): те
/// описывают судьбу задачи и рисуются панелью, а эти — отказ выполнить
/// вызов, то есть состояние, до которого исправный фронтенд не доводит
/// (кнопки, которых нельзя нажать, он не показывает). Тем не менее они
/// типизированы, а не строки: защита на стороне ядра обязана быть
/// настоящей, а её срабатывание — различимым в логе.
///
/// С эпика E4 тип обслуживает и команды очереди (`dismiss_queue_task`):
/// это те же команды над теми же задачами, и отказы им рисует тот же
/// блок на экране (`DownloadCommandErrorBlock`, дизайн E3). Второй тип
/// с тем же смыслом означал бы второй список текстов на стороне UI.
///
/// # Почему объединение, а не `kind` рядом с опциональными полями
///
/// Отказ по дублю обязан назвать существующую задачу (Р-5 E4: «отказ
/// называет существующую задачу»), остальным классам называть нечего.
/// Плоская структура с опциональной ссылкой сделала бы выразимыми сразу
/// два бессмысленных состояния — «дубль неизвестно чего» и «неизвестная
/// задача, а вот вам ссылка на другую»; здесь они не компилируются. Тот
/// же довод и то же устройство, что у [`YtDlpUpdateFailure`] в E6.
///
/// На проводе это по-прежнему `kind` со строковым значением — тег
/// объединения, — поэтому `switch (error.kind)` на стороне UI работает
/// как работал. Изменилось одно: в TS `DownloadCommandErrorKind` стал
/// объединением объектов, и список вариантов там перечисляется не
/// `Record<DownloadCommandErrorKind, true>`, а
/// `Record<DownloadCommandError['kind'], true>` (правило CLAUDE.md о
/// `satisfies` при этом соблюдается тем же способом).
///
/// # Чего здесь больше нет
///
/// Класса `alreadyActive` («слот занят другой задачей») в контракте нет
/// с TL-70 — это прямое требование Ф-2 E4, а не решение дизайна. С
/// появлением очереди сценарий, в котором ядро обязано так ответить,
/// исчезает: постановка при занятом слоте — теперь штатный путь
/// (задача встаёт в хвост, Ф-2), а не отказ. Единственный оставшийся
/// повод отказать в постановке — дубль ([`Self::DuplicateTask`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum DownloadCommandErrorKind {
    /// Задачи с таким `taskId` ядро не знает: она никогда не создавалась,
    /// была скрыта (`dismiss_queue_task`) либо не пережила перезапуск —
    /// в снимок очереди попадают только нетерминальные задачи (Ф-9).
    UnknownTask,
    /// Повтор запрошен для задачи, которая не в фазе `failed`.
    NotFailed,
    /// Повтор запрошен для класса ошибки, где он заведомо бесполезен
    /// ([`DownloadErrorKind::is_retryable`] = `false`): устаревшие данные
    /// разбора чинятся новым разбором, а не тем же запросом ещё раз.
    NotRetryable,
    /// В запросе нет ни одного идентификатора потока — скачивать нечего
    /// (инвариант [`QualityStreams::has_any`]).
    NoStreamsSelected,
    /// Ссылка не является http(s)-адресом. Проверяется заново, даже если
    /// её уже разобрал E2: ни одна часть пользовательского ввода не
    /// попадает в аргументы процесса непроверенной (Ф-1).
    InvalidUrl,
    /// Тот же ролик с тем же пунктом качества уже стоит в очереди
    /// нетерминальной задачей (Ф-8, Р-5 E4).
    ///
    /// Сравнение — по каноническому id ролика (не по строке URL: одна и
    /// та же ссылка приходит в разных формах записи) и по
    /// [`StartDownloadRequest::streams`]. Другой пункт качества того же
    /// ролика дублем не считается; терминальные задачи в сравнении не
    /// участвуют — повторное скачивание завершённого решено в E3
    /// суффиксом «(N)».
    ///
    /// `existing` — та самая задача, которую называет текст отказа.
    /// Поле обязательное: отказ, не назвавший задачу, отправил бы
    /// пользователя искать её в списке самому, а ради этого класс и
    /// заводился.
    DuplicateTask { existing: QueueTaskRef },
    /// Скрыть (`dismiss_queue_task`) просят задачу, которая ещё не дошла
    /// до терминальной фазы.
    ///
    /// **Второй новый класс эпика E4 — и это расхождение с дизайном,
    /// названное намеренно.** Дизайн пишет «добавляется один класс»
    /// (`duplicateTask`) и тут же требует типизированного отказа для
    /// «скрыть можно только завершённое»: счёт в дизайне неточен, и
    /// подгонять код под число значило бы отдать одному классу два
    /// разных смысла.
    ///
    /// Ни один из существующих не подходит по смыслу, и проверено это
    /// поимённо, а не на глаз. [`Self::UnknownTask`] — неправда: задача
    /// известна, она в очереди и видна на экране. [`Self::NotFailed`] и
    /// [`Self::NotRetryable`] — про повтор: первый говорит «повтор
    /// доступен только упавшей задаче», и его текст на экране
    /// («Повторить можно только упавшую загрузку») к нажатию «Скрыть» не
    /// относится; вдобавок `notFailed` разрешает ровно фазу `failed`, а
    /// скрыть можно любую терминальную, включая `done` и `cancelled` —
    /// то есть множества состояний у них разные, а не просто тексты.
    /// [`Self::NoStreamsSelected`] и [`Self::InvalidUrl`] — про
    /// содержимое запроса постановки, которого у этой команды нет вовсе.
    ///
    /// Имя выбрано по состоянию задачи, а не по команде
    /// (`cannotDismiss`): состояние — то, что тут единственно правдиво,
    /// и оно останется правдой, если это же условие однажды понадобится
    /// другой команде.
    TaskNotFinished,
}

/// Отказ команды управления загрузкой или очередью в сериализуемом виде.
///
/// `message` — диагностика для лога, как и у [`DownloadError`]: решение
/// принимается по `kind`, и stderr в текст на экране не попадает никогда
/// (Н-4 E2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct DownloadCommandError {
    /// Разворачивается в те же поля объекта, что и сам вариант: `kind`
    /// лежит рядом с `message`, а не вложенным объектом.
    #[serde(flatten)]
    pub kind: DownloadCommandErrorKind,
    pub message: String,
}

// ────────────────── самообновление yt-dlp (TL-53, эпик E6) ──────────────────
//
// Контракт контура обновления: чем ядро отчитывается о состоянии блока
// «Обновление yt-dlp» на служебном экране и что принимают его команды.
// Реализация — TL-55 (проверка по метаданным релиза), TL-56 (скачивание и
// проверка архива), TL-57 (smoke-проверка), TL-58 (оркестрация и сами
// команды); здесь только объявление типов. Второго, ручного TS-зеркала у
// секции нет и не будет: оно генерируется (TL-51) в
// `src/types/generated/update.ts`.
//
// Глушители `#[allow(dead_code)]`, которыми секция жила до TL-58, сняты
// вместе с появлением конструирующего кода (`crate::ytdlp::orchestrate` и
// команды контура): контракт больше не опережает реализацию, и лишнее в
// нём теперь видно компилятору, а не только читателю.
//
// # Три команды
//
// Имена фиксируются здесь, а не в задаче оркестрации, потому что на них
// опирается ui-задача TL-59 — она стартует сразу после этой и работает на
// замоканном `invoke` задолго до появления настоящих команд:
//
// - `ytdlp_update_state() -> YtDlpUpdateSnapshot` — снимок при открытии
//   служебного экрана, разовый запрос по образцу `check_sidecar`, не
//   polling. Не отказывает ничем: «ничего ещё не происходило» — это
//   значение [`YtDlpUpdateStatus::NeverChecked`], а не ошибка.
// - `check_ytdlp_update() -> Result<YtDlpUpdateSnapshot, YtDlpUpdateCommandError>`
//   — «Проверить сейчас» (С-12). Запускает тот же конвейер, что плановая
//   проверка, и возвращается сразу: ждать в промисе тут нечего, конвейер
//   идёт минуты, а исход приезжает событием (Н-3 — ничего не блокирует).
//   Возвращает снимок с уже переключённым [`YtDlpUpdateStatus::Checking`],
//   чтобы кнопка гасла, не дожидаясь первого события.
// - `roll_back_ytdlp() -> Result<YtDlpUpdateSnapshot, YtDlpUpdateCommandError>`
//   — «Вернуться к известно-хорошей» (Р-3). **Без параметра-версии**: цель
//   ровно одна по построению (Ф-8 держит на диске не более двух
//   установок), и принимать её от фронтенда значило бы принимать выбор,
//   которого он не делает, — а заодно заводить проверку «а ту ли версию
//   прислали» на пути, где выбирать не из чего.
//
// # Одно значение и на снимок, и на событие
//
// Событие `ytdlp://update` (константа `UPDATE_EVENT` в
// `crate::ytdlp::update`) несёт ровно [`YtDlpUpdateSnapshot`] — тот же
// тип, что возвращают все три команды. Это не экономия на объявлениях, а
// защита от расхождения, и причин две.
//
// 1. **Блок рисуется одной таблицей из 14 строк** (дизайн E6, «Все
//    состояния»), и строка обязана получаться одинаково независимо от
//    того, приехало состояние снимком при открытии экрана или событием
//    по ходу конвейера. Разные формы для снимка и для события — это две
//    проекции на одну таблицу, то есть две копии правила, которые
//    разойдутся на первой же новой строке.
// 2. **Цель отката меняется местами сама.** После переключения на Y
//    известно-хорошей становится X, после возврата на X — снова Y (дизайн
//    E6, «Ручной откат»). Событие без [`YtDlpUpdateSnapshot::rollback_target`]
//    оставило бы на кнопке версию, от которой уже ушли; дочитывать её
//    снимком после каждого терминального события — polling под другим
//    именем, запрещённый Ф-11.
//
// Частоту эмита ограничивает оркестрация (TL-58) — по образцу E3, где
// событие прогресса троттлится, кроме перехода в терминальную фазу.

/// Доля скачанного архива обновления в процентах, 0..=100.
///
/// Отдельный тип, а не голый `u8`, ради того же инварианта, что у
/// [`DownloadPercent`]: на провод не уходит число больше ста. Обрезание в
/// конструкторе делает «103 %» невыразимым, а не оставляет полосе
/// выезжать за край.
///
/// Почему **не** переиспользован [`DownloadPercent`], хотя величина
/// арифметически та же. За тем типом стоит поведенческий договор, к
/// обновлению отношения не имеющий: знаменатель там собирается из оценки
/// размера, которую дал разбор E2, и вытесняется фактическим размером
/// потока уже по ходу приёма. Здесь знаменатель известен заранее и точно
/// — это объявленный размер ассета (`UpdateAsset::size_bytes` в
/// `crate::ytdlp::update`), обязательное поле: ассет без размера контур
/// не устанавливает вовсе. Тот же довод, по которому E3 завёл
/// собственный `DownloadErrorDetails` вместо переиспользования
/// `ProbeErrorDetails`: одинаковая форма не делает вещи одной вещью.
///
/// На проводе — просто число (`#[serde(transparent)]`), как и у соседа.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(transparent)]
pub struct YtDlpUpdatePercent(u8);

impl YtDlpUpdatePercent {
    /// Единственный конструктор: всё, что больше ста, становится сотней.
    pub fn new(percent: u8) -> Self {
        Self(percent.min(100))
    }

    /// Значение для форматирования на стороне вызывающего.
    ///
    /// Глушитель — тот же и по той же причине, что у соседнего
    /// [`DownloadPercent::value`]: продакшен-путь процент только
    /// **строит** и сериализует, а разворачивать его обратно в число
    /// незачем — форматирует его UI по ту сторону границы. Читают его
    /// отсюда только тесты контура обновления, которые проверяют, что
    /// показанная полоса доходит до конца и не едет назад.
    #[allow(dead_code)]
    pub fn value(self) -> u8 {
        self.0
    }
}

/// Пять классов отказа контура (Ф-9) вместе с тем, что о каждом известно.
///
/// Ровно та типизация, которой Ф-9 требует: «нет сети», «источник
/// недоступен», «архив повреждён», «не хватает места», «новая версия не
/// прошла проверку». Ни один из них не влияет на работоспособность
/// активной установки и ни один не показывается как ошибка скачивания
/// ролика — тексты для пользователя задаёт UI по классу (дизайн E6,
/// строки 8–12 таблицы состояний).
///
/// **Почему объединение, а не `kind` + `version: Option<String>`.**
/// Версия известна не всем классам и нужна не всем текстам: проверка
/// метаданных падает раньше, чем становится известно, о какой версии
/// речь, и строки 8–9 её не называют, а строки 10–12 без неё не
/// собираются вовсе («Обновление {Y} скачалось повреждённым»). Плоская
/// структура с опциональной версией сделала бы выразимыми оба
/// бессмысленных состояния сразу — «нет сети у версии 2026.08.21» и
/// «повреждён архив неизвестно чего»; здесь они не компилируются.
///
/// Обрыв сети посреди скачивания архива — это `networkUnavailable`, и
/// версия в этот момент уже известна. Она сюда не кладётся сознательно:
/// строка 8 её не показывает, а поле, которое никто не читает, —
/// приглашение однажды показать не то (К-5 проверяет ровно этот сценарий
/// и ждёт «работаем на {X}», а не «не скачалось {Y}»).
///
/// `message` — формулировка ядра для лога и свёрнутых деталей, **не**
/// основной текст на экране: stderr в него не попадает никогда (Ф-9,
/// правило Н-4 E2). Поле повторено в каждом варианте, а не вынесено
/// рядом с тегом: так у каждого шага конвейера (TL-55, TL-56, TL-57)
/// значение остаётся самодостаточным — вернуть класс без диагностики
/// нельзя.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum YtDlpUpdateFailure {
    /// Нет соединения с интернетом (С-3). Возникает и на проверке
    /// метаданных, и на скачивании архива (К-5).
    NetworkUnavailable { message: String },
    /// Сеть есть, а апстрим не отвечает: GitHub недоступен, ограничение
    /// частоты запросов, неожиданный ответ вместо метаданных релиза
    /// (С-3).
    SourceUnavailable { message: String },
    /// Скачанное отброшено до того, как что-либо тронуло активную
    /// установку (С-4). Один класс на четыре причины — сумма sha256 не
    /// сошлась, архив не читается, превышен потолок распакованного
    /// размера (TL-18), в корне не ровно один исполняемый файл: лекарство
    /// у всех одно (отбросить, попробовать позже), и дизайн сводит их в
    /// один текст сознательно.
    ArchiveCorrupted { version: String, message: String },
    /// На томе с каталогом данных не хватает места под архив или под
    /// распакованное дерево (С-11, проверка из TL-18). Отдельно от
    /// [`Self::ArchiveCorrupted`], потому что действие пользователя
    /// другое и оно есть: освободить место.
    NotEnoughSpace { version: String, message: String },
    /// Установка распакована и прогрета, но не прошла smoke-проверку
    /// (С-5, Ф-6): `--version` не отвечает, отвечает не тем или падает.
    /// Активная установка не менялась.
    SmokeCheckFailed { version: String, message: String },
}

impl YtDlpUpdateFailure {
    /// Диагностика для лога — одно место на всех вместо `match` по месту
    /// вызова.
    pub fn message(&self) -> &str {
        match self {
            Self::NetworkUnavailable { message }
            | Self::SourceUnavailable { message }
            | Self::ArchiveCorrupted { message, .. }
            | Self::NotEnoughSpace { message, .. }
            | Self::SmokeCheckFailed { message, .. } => message,
        }
    }

    /// Версия, о которой шла речь, — у классов, которые её знают и
    /// называют.
    pub fn version(&self) -> Option<&str> {
        match self {
            Self::NetworkUnavailable { .. } | Self::SourceUnavailable { .. } => None,
            Self::ArchiveCorrupted { version, .. }
            | Self::NotEnoughSpace { version, .. }
            | Self::SmokeCheckFailed { version, .. } => Some(version),
        }
    }
}

/// Состояние контура обновления — размеченное объединение, из которого
/// однозначно получается строка блока «Обновление yt-dlp».
///
/// Десять вариантов покрывают все 14 строк таблицы «Все состояния»
/// дизайна E6: девять — по строке каждый, десятый (`failed`) — пять
/// строк, по одной на класс [`YtDlpUpdateFailure`]. Соответствие
/// проверяется поимённо (`the_ten_variants_cover_the_fourteen_design_rows`
/// ниже), и новый вариант или новый класс отказа ломает компиляцию того
/// теста, пока ему не назначена строка.
///
/// **Что сделано невыразимым и зачем.** Процент есть только у
/// `downloading`: ни у распаковки с прогревом (`preparing`), ни у
/// ожидания границы задач числа не бывает — дизайн отвергает полосу на
/// прогреве прямо, тем же доводом, что и на remux в E3 (операция ОС, не
/// дающая надёжной оценки дешевле, чем сама операция). Штамп времени
/// есть только у терминальных состояний: у `neverChecked` его не бывает
/// по смыслу, а у идущего конвейера показывать нечего. Версия есть
/// только там, где текст строки её называет. Плоская структура с
/// полями-опциями выражала бы «проверяем 47 %» и «ещё не проверяли в
/// 12:30» — здесь они не компилируются.
///
/// **Куда смотрит `version`.** У `downloading`, `preparing` и
/// `readyWaiting` это версия-кандидат — та, которую ставят. У
/// `rollbackWaiting` направление обратное: там названа версия, **к
/// которой возвращаются** и которая станет активной на границе задач. У
/// `updated` — уже активная, у `rolledBack` версии две и обе названы
/// полями (`active`, `abandoned`). Сказано здесь, а не только у
/// вариантов, потому что doc вариантов в TS-зеркало не попадает вовсе
/// (ts-rs их отбрасывает), и по ту сторону границы это единственный
/// текст, который читатель увидит.
///
/// **Почему `at` называется не `checkedAt`.** Дизайн подставляет `{когда}`
/// в три разных смысла: время проверки (строки 3, 8, 9), время
/// переключения (строка 7), время возврата (строка 13). Одно имя на все —
/// «когда это состояние стало текущим»; `checkedAt` у `updated` врал бы
/// про то, чей это штамп. Формат — RFC 3339 UTC, как у
/// [`SidecarCheckResult::checked_at`] (`crate::clock::now_iso8601`);
/// «3 часа назад» считает UI, потому что это его формат, а не факт.
///
/// **Про `rename_all_fields`.** Сегодня он не меняет ни одного имени:
/// все поля вариантов односложные, и змеиный регистр совпадает с
/// верблюжьим. Атрибут стоит не по инерции и проверить его сейчас нечем —
/// первое же составное имя поля уехало бы на провод как `some_field`
/// посреди camelCase-объекта, потому что `rename_all` у enum
/// переименовывает **варианты**, а не поля внутри них. Ровно это ловили в
/// E3 у [`DownloadingState::WaitingRetry`] сравнением значения целиком,
/// и ловили не глазами.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(
    tag = "status",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum YtDlpUpdateStatus {
    /// Строка 1: обновления не проверялись ни разу.
    ///
    /// Значение бывает только начальным: событием не приезжает никогда —
    /// первое, что эмитит контур, это уже `checking`.
    NeverChecked,
    /// Строка 2: идёт проверка — плановая, ручная (С-12) или внеплановая
    /// по сломанному извлечению (С-13). Какая именно, блок не различает:
    /// текст один, и заводить различие ради него значило бы обещать
    /// разницу, которой на экране нет.
    Checking,
    /// Строка 3: проверили, новее нет (С-2). Активную версию строка
    /// показывает, но берёт её из `check_sidecar`, а не отсюда — дизайн
    /// прямо запрещает спрашивать её вторично.
    UpToDate { at: String },
    /// Строка 4: идёт скачивание архива версии `version`.
    ///
    /// Процент обязателен, а не опционален: знаменатель известен раньше
    /// первого принятого байта. Держится это на `UpdateAsset::size_bytes`
    /// — объявленном размере ассета, который эпик требует проверить
    /// против потолка **до** начала запроса (задача TL-56), а потому и
    /// делает обязательным полем: ассет без объявленного размера контур
    /// не устанавливает.
    ///
    /// Оговорка, важная для TL-56, чтобы не искать эту проверку не там.
    /// Потолок TL-18 — **другая** граница и на другом рубеже: он живёт
    /// внутри `crate::ytdlp::unpack`, складывается из заголовков уже
    /// скачанного архива и метаданных релиза не видит вовсе. Тот модуль
    /// прямо и говорит, что размер скачиваемого надо ограничивать
    /// снаружи, до вызова распаковки, — изнутри расход памяти на разбор
    /// центрального каталога уже не управляем. Скачивания с неизвестным
    /// размером в этом контуре не бывает именно поэтому, а не потому,
    /// что TL-18 умеет спросить апстрим.
    Downloading {
        version: String,
        percent: YtDlpUpdatePercent,
    },
    /// Строка 5: распаковка и прогрев версии `version` (Ф-4, Ф-6).
    /// Прогрев ждёт паузы между задачами скачивания (Н-3), и ожидание —
    /// часть этого же состояния: пользователю показывают одно и то же
    /// «Готовим обновление…», а различать внутри нечего.
    Preparing { version: String },
    /// Строка 6: версия готова и ждёт границы задач (Р-2, С-6).
    ReadyWaiting { version: String },
    /// Строка 14: возврат принят и ждёт границы задач — тем же
    /// механизмом переключения, что обычное обновление (Ф-7).
    ///
    /// **`version` — та, К КОТОРОЙ возвращаемся**: известно-хорошая
    /// установка, которая станет активной, когда закончится текущая
    /// задача. Не та, от которой уходим. Направление названо прямо,
    /// потому что у соседей оно противоположное — там версия всегда
    /// кандидат на установку, — а сам дизайн в этом месте нестрог: его
    /// легенда объявляет `X` активной, но строка 14 пишет «Возврат к
    /// {X}», где `X` активной ещё не стала.
    ///
    /// [`YtDlpUpdateSnapshot::rollback_target`] в этом состоянии равен
    /// этому же значению: местами версии меняются в момент применения
    /// (строка 13), а не принятия. Кнопка всё равно неактивна, пока
    /// возврат ждёт, — [`Self::busy`] здесь истинно.
    ///
    /// Отдельный вариант, а не [`Self::ReadyWaiting`] с флагом: тексты
    /// строк 6 и 14 говорят о разном («обновление применится» против
    /// «возврат применится»), а флаг рядом с версией позволил бы
    /// собрать состояние, которого нет.
    RollbackWaiting { version: String },
    /// Строка 7: переключение произошло, активна `version` (С-1).
    Updated { at: String, version: String },
    /// Строка 13: возврат выполнен (С-8, Р-3).
    ///
    /// Обе версии названы, потому что обе стоят в тексте: `active` — та,
    /// на которую вернулись и которая работает сейчас, `abandoned` — та,
    /// от которой отказались и которая не будет предложена автоматически
    /// до следующего релиза апстрима.
    ///
    /// `abandoned` и [`YtDlpUpdateSnapshot::rollback_target`] в этом
    /// состоянии совпадают — цель отката теперь ведёт обратно. Это не
    /// дублирование одного поля: первое — часть текста строки 13 и
    /// остаётся верным, даже если возвращаться станет некуда, второе —
    /// подпись кнопки и исчезает вместе с ней.
    RolledBack {
        at: String,
        active: String,
        abandoned: String,
    },
    /// Строки 8–12: конвейер отказал. Какая именно строка — решает класс
    /// (Ф-9); активная установка при любом из них цела и работает (Н-2).
    Failed {
        at: String,
        failure: YtDlpUpdateFailure,
    },
}

impl YtDlpUpdateStatus {
    /// Занят ли контур: конвейер идёт либо подготовленное ждёт границы
    /// задач.
    ///
    /// Ровно те пять состояний, при которых дизайн гасит обе кнопки блока
    /// («не плодим параллельные пробы поверх уже идущей»). Правило живёт
    /// здесь одно на всех: по нему ядро отклоняет команды
    /// ([`YtDlpUpdateCommandErrorKind::Busy`]), и его же проекция уезжает
    /// на провод полем [`YtDlpUpdateSnapshot::busy`] — фронтенд не держит
    /// собственной копии списка. `match` без ветки-заглушки: новый
    /// вариант обязан получить решение здесь, а не унаследовать чужое.
    pub fn busy(&self) -> bool {
        match self {
            Self::Checking
            | Self::Downloading { .. }
            | Self::Preparing { .. }
            | Self::ReadyWaiting { .. }
            | Self::RollbackWaiting { .. } => true,
            Self::NeverChecked
            | Self::UpToDate { .. }
            | Self::Updated { .. }
            | Self::RolledBack { .. }
            | Self::Failed { .. } => false,
        }
    }
}

/// Снимок состояния блока «Обновление yt-dlp»: ответ всех трёх команд
/// контура и полезная нагрузка события `ytdlp://update`.
///
/// Почему одно значение на снимок и на событие — см. шапку секции.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct YtDlpUpdateSnapshot {
    /// Разворачивается в те же поля объекта, что и сам вариант: `status`
    /// лежит рядом с `rollbackTarget`, а не вложенным объектом.
    #[serde(flatten)]
    pub status: YtDlpUpdateStatus,
    /// Версия известно-хорошей установки, если она отличается от
    /// активной, — подпись кнопки «Вернуться к …».
    ///
    /// Отсутствует, когда возвращаться некуда: до первого переключения
    /// установка на диске одна. Именно отсутствует, а не приезжает
    /// пустой строкой — кнопки в этом состоянии нет вовсе (дизайн E6).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub rollback_target: Option<String>,
    /// Проекция [`YtDlpUpdateStatus::busy`]: обе кнопки блока неактивны.
    ///
    /// Не второй источник правды, а именно проекция — по тому же
    /// образцу, что `retryable` у [`DownloadError`]. Единственный
    /// благословлённый конструктор — [`YtDlpUpdateSnapshot::new`], где
    /// значение берётся из статуса, а не из мнения на месте вызова.
    pub busy: bool,
}

impl YtDlpUpdateSnapshot {
    /// Собрать снимок, выведя `busy` из статуса.
    pub fn new(status: YtDlpUpdateStatus, rollback_target: Option<String>) -> Self {
        Self {
            busy: status.busy(),
            status,
            rollback_target,
        }
    }
}

/// Почему команда контура обновления отклонена.
///
/// Это **не** классы отказа обновления ([`YtDlpUpdateFailure`]): те
/// описывают судьбу конвейера и рисуются строкой блока, а эти — отказ
/// выполнить вызов, то есть состояние, до которого исправный фронтенд не
/// доводит (кнопки, которых нельзя нажать, он не показывает). Тем не
/// менее они типизированы, а не строки: защита на стороне ядра обязана
/// быть настоящей, а её срабатывание — различимым в логе (тот же довод,
/// что у [`DownloadCommandErrorKind`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum YtDlpUpdateCommandErrorKind {
    /// Контур занят: идёт проверка или подготовка, либо подготовленное
    /// ждёт границы задач ([`YtDlpUpdateStatus::busy`]). Обе команды
    /// отклоняются одинаково.
    Busy,
    /// Возврат запрошен, когда возвращаться некуда: известно-хорошей
    /// установки, отличной от активной, на диске нет
    /// ([`YtDlpUpdateSnapshot::rollback_target`] отсутствует).
    NothingToRollBackTo,
}

/// Отказ команды контура обновления в сериализуемом виде.
///
/// `message` — диагностика для лога, как и у [`DownloadCommandError`]:
/// решение принимается по `kind`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "update.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct YtDlpUpdateCommandError {
    pub kind: YtDlpUpdateCommandErrorKind,
    pub message: String,
}

// ─────────────────── очередь загрузок (TL-70, эпик E4) ───────────────────
//
// Контракт очереди: чем ядро отчитывается о её составе и что принимают её
// команды. Реализация — TL-71 (снимок очереди на диске), TL-72
// (канонический id ролика для сравнения дублей), TL-73 (планировщик,
// настоящие тела команд и эмит события); здесь только объявление типов и
// разрешение канала в `capabilities/main.json`.
//
// Глушители `#[allow(dead_code)]` в секции стояли по той же причине и с
// той же оговоркой, что были у секций E2, E3 и E6: контракт опережает
// реализацию на задачу и не должен исчезать из-за того, что конструирует
// его пока некому. Планировщик (TL-73) появился — и глушители сняты тем
// же изменением: переживший свою причину прячет следующий мёртвый код.
//
// # Три команды очереди
//
// Имена фиксируются здесь, а не в задаче планировщика, потому что на них
// опирается ui-задача TL-75: она стартует сразу после этой и работает на
// замоканном `invoke` задолго до появления настоящих тел (тот же приём,
// что в E6 с `ytdlp_update_state`).
//
// - `queue_state() -> QueueSnapshot` — снимок при монтировании экрана и
//   после перезагрузки webview (С-9), разовый запрос по образцу
//   `check_sidecar`, а не polling. Не отказывает ничем: пустая очередь —
//   это `tasks: []`, а не ошибка.
// - `resume_queue()` — «Продолжить очередь» (Р-3). **Без параметров**:
//   слот один и порядок строгий (Р-1, Р-4), поэтому продолжать можно
//   только очередь целиком, а не выбранную задачу — кнопка на второй
//   задаче списка означала бы ровно то же самое действие (дизайн,
//   «Продолжение после перезапуска»). Вызов при уже идущей очереди —
//   не ошибка, а ничего.
// - `dismiss_queue_task(taskId)` — «Скрыть» завершённую задачу. Команда
//   ядра, а не локальное состояние стора (каким «Скрыть» было в E3):
//   С-9 требует, чтобы перезагрузка webview восстанавливала список по
//   снимку ядра, и скрытие, живущее только во фронтенде, воскрешало бы
//   скрытые задачи. Отклоняется типизированно, если задача не дошла до
//   терминальной фазы, — см. [`DownloadCommandErrorKind::TaskNotFinished`].
//
// Три команды E3 (`start_download`, `cancel_download`, `retry_download`)
// остаются с теми же именами. Меняется не их форма, а поведение, и
// меняет его TL-73: старт встаёт в хвост вместо мгновенного отказа
// (Ф-2), отмена работает и для ожидающей задачи (Ф-4), повтор ставит ту
// же задачу в хвост (решение дизайна). Единственная правка формы —
// [`StartDownloadRequest::quality`], и её причина записана там же.
//
// # Одно значение и на снимок, и на событие
//
// Событие `queue://changed` (константа `CHANGED_EVENT` в `crate::queue`)
// несёт ровно [`QueueSnapshot`] — тот же тип, что возвращает
// `queue_state`. Довод тот же, что у `ytdlp://update` в E6: список
// рисуется одной таблицей состояний, и строка обязана получаться
// одинаково независимо от того, приехало состояние снимком при открытии
// экрана или событием по ходу очереди. Две формы — две проекции на одну
// таблицу, то есть две копии правила, которые разойдутся на первом же
// новом состоянии.
//
// Событие несёт **весь снимок**, а не дельту: список короткий (единицы —
// десятки задач, Н-2), и полный снимок снимает целый класс
// рассинхронизаций ценой чуть большего, но всё ещё маленького события.
// Эмитится он только на структурные изменения (добавление, старт,
// терминальный исход, скрытие, продолжение, начало и конец паузы) —
// поток событий не растёт с длиной очереди сам собой, без троттлинга.
// `download://progress` при этом не меняется ни строкой (Ф-6): ход
// активной задачи едет по-прежнему им, а не перерисовкой всего списка
// три раза в секунду.
//
// # Чего в контракте нет и почему
//
// - **Позиции ожидающей задачи.** Фронтенд считает её сам по порядку
//   присланного списка (дизайн, «Данные для API»): второе число рядом с
//   порядком было бы вторым источником истины, которому не с чем
//   сверяться, кроме самого порядка.
// - **Канонического id ролика.** Сравнение дублей (Ф-8) идёт по id,
//   извлечённому из `url` на стороне ядра (TL-72), и по уже
//   существующему полю [`StartDownloadRequest::streams`]. Наружу id не
//   выходит: фронтенду он не нужен ни для одного экрана, а выданное
//   поле контракта потом трудно забрать.
// - **Предиката «есть активная задача» и уведомления о границе задач**
//   (Ф-7). Это внутренний интерфейс ядра для контура обновления
//   (`QueueScheduler::is_active` и `wait_for_task_boundary` в
//   `crate::queue::scheduler`), границу окна он не пересекает. На проводе от Ф-7
//   есть ровно одно — [`QueueSnapshot::pause_reason`]: пользователю
//   видна пауза, а не механизм.

/// Пункт лестницы качеств в том виде, в каком подписана его строка.
///
/// Ровно два поля [`QualityItem`], из которых UI уже собирает подпись
/// пункта, — `kind` и `heightPx`. Готовой строки («1080p», «только
/// аудио») в контракте нет намеренно: тексты живут на стороне UI (правило
/// E2 и E3), и строка, собранная в ядре, была бы вторым форматтером той
/// же подписи, а строка, принятая от фронтенда, — свободным текстом,
/// который ядро обязано вернуть обратно на экран не глядя.
///
/// **Тип ходит в обе стороны границы**, как [`QualityStreams`] и
/// [`QualitySize`]: уезжает в [`StartDownloadRequest::quality`] вместе с
/// выбранным пунктом и приезжает обратно в каждой задаче снимка
/// ([`QueueTask::quality`]) и в отказе по дублю
/// ([`QueueTaskRef::quality`]). Без этого заголовок задачи, восстановленной
/// после перезапуска, собрать не из чего: разбор E2 к этому моменту не
/// повторялся, а `streams` — непрозрачные идентификаторы форматов, из
/// которых «1080p» не выводится.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "queue.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct SelectedQuality {
    /// Вид пункта: обычная ступень, максимальное доступное, только аудио.
    pub kind: QualityKind,
    /// Ступень качества, как её показывает YouTube. Отсутствует у
    /// `audioOnly` — ровно как у [`QualityItem::height_px`], откуда
    /// значение и приехало.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub height_px: Option<u32>,
}

/// Задача очереди в том объёме, в каком её называют пользователю.
///
/// Три поля, которых хватает на заголовок ««Название» — качество» и ни на
/// что больше. Отдельный тип, а не [`QueueTask`] целиком, потому что
/// единственный его потребитель — текст отказа по дублю
/// ([`DownloadCommandErrorKind::DuplicateTask`]), а прогресс, план и фаза
/// существующей задачи в этом тексте не участвуют: отказ называет
/// задачу, а не пересказывает её состояние.
///
/// Почему это структурные поля, а не свободная строка. Дизайн E3 отказал
/// текстам отказов в параметре `message` сознательно (ревью TL-45), чтобы
/// диагностика ядра не просочилась в интерфейс как есть. Дубль требует
/// назвать **конкретную** задачу, то есть динамические данные, — и
/// получает их полями того же рода, что уже безопасно показаны на экране
/// её собственной строкой списка. Шаблон текста остаётся на стороне UI.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "queue.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct QueueTaskRef {
    pub task_id: String,
    pub title: String,
    pub quality: SelectedQuality,
}

/// Одна задача снимка очереди.
///
/// Форма выбрана так, чтобы совпадать с [`DownloadProgressEvent`] в той
/// части, которая у них общая: `taskId` рядом с развёрнутым
/// [`DownloadProgress`], тег фазы — поле `phase` на верхнем уровне
/// объекта. Панель E3 не меняется ни строкой (обещание дизайна E3,
/// подтверждённое дизайном E4), и её вход обязан выглядеть одинаково
/// независимо от того, приехал он событием прогресса или снимком очереди.
///
/// `plan` лежит здесь, а не только в ответе `start_download`, по той же
/// причине: панель рисует степпер по плану, а после перезагрузки webview
/// ответа команды у неё уже нет (С-9).
///
/// Поля `taskId`, `title` и `quality` повторяют [`QueueTaskRef`] и
/// повторены явно, а не внесены им же через `flatten`: два `flatten` в
/// одной структуре (ссылка и размеченный по фазе прогресс) читаются на
/// проводе хуже, чем стоят. Согласованность держится не памятью автора, а
/// [`QueueTask::reference`] — единственным способом получить ссылку на
/// задачу из самой задачи.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "queue.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct QueueTask {
    /// Идентификатор задачи — тот же, которым ключуются события
    /// `download://progress` и которым зовут отмену, повтор и скрытие.
    pub task_id: String,
    /// Название ролика, как его показала карточка E2.
    pub title: String,
    /// Выбранный пункт лестницы — вторая половина заголовка.
    pub quality: SelectedQuality,
    /// Один поток или два, то есть будет ли шаг «Склейка».
    pub plan: DownloadPlan,
    /// Разворачивается в те же поля объекта, что и сам вариант: `phase`
    /// лежит рядом с `taskId`, а не вложенным объектом.
    #[serde(flatten)]
    pub progress: DownloadProgress,
}

impl QueueTask {
    /// Ссылка на эту же задачу для текста отказа по дублю.
    ///
    /// Единственный способ её получить: собранная руками на месте вызова,
    /// она разошлась бы с задачей ровно в том поле, которое там забыли
    /// обновить, — а видно это было бы только в тексте отказа, который
    /// показывают редко.
    pub fn reference(&self) -> QueueTaskRef {
        QueueTaskRef {
            task_id: self.task_id.clone(),
            title: self.title.clone(),
            quality: self.quality,
        }
    }
}

/// Почему планировщик держит паузу между задачами (Р-7).
///
/// Отдельное перечисление с одним вариантом, а не `bool`: пауза между
/// задачами — место, куда встанет любое будущее «очередь стоит и вот
/// почему», и различить причины на проводе тогда будет нечем. Один
/// вариант сегодня стоит ноль, а `pauseReason: true` завтра не расширить
/// без правки контракта на обеих сторонах.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "queue.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum QueuePauseReason {
    /// Между задачами ставится подготовленная установка yt-dlp: идёт
    /// прогрев и переключение, старт следующей задачи ждёт их окончания
    /// (Р-7, Ф-7 E6). Появляется редко — раз в релиз апстрима.
    YtDlpUpdate,
}

/// Снимок очереди: ответ команды `queue_state` и полезная нагрузка
/// события `queue://changed`.
///
/// Почему одно значение на снимок и на событие — см. шапку секции.
///
/// **Порядок `tasks` задаёт ядро и он значим**: строгий FIFO по времени
/// постановки (Р-4), терминальные задачи остаются на своих местах до
/// «Скрыть». UI рисует список как пришёл и не сортирует его сам — иначе
/// правило порядка оказалось бы в двух местах (то же правило, что у
/// `qualities` в [`ProbeResult`]).
///
/// Версионного поля у снимка нет намеренно, и это не упущение Ф-9:
/// версионируется **файл** снимка на диске (`crate::queue::snapshot`),
/// который переживает обновление приложения и потому обязан объявлять
/// свой формат. Снимок на проводе живёт миллисекунды и едет между двумя
/// половинами одного и того же бинарника — версия в нём была бы полем,
/// которое никто не читает и однажды прочтёт неверно.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "queue.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct QueueSnapshot {
    /// Все задачи очереди в порядке постановки — и нетерминальные, и ещё
    /// не скрытые терминальные.
    pub tasks: Vec<QueueTask>,
    /// Очередь восстановлена после перезапуска приостановленной (Р-3) и
    /// ни разу не запускалась в этом сеансе.
    ///
    /// Поле уровня очереди, а не задачи: продолжается очередь целиком
    /// (см. `resume_queue` в шапке секции). По нему рисуется банер
    /// «Продолжить очередь», меняется формулировка в строках ожидания и
    /// решается, показывать ли диалог выхода (Р-8): приостановленная
    /// очередь ничего не теряет при закрытии окна.
    ///
    /// `false`, а не отсутствие поля: «очередь идёт» — полноценное
    /// состояние, которое UI обязан различать с первого же снимка, а не
    /// выводить из того, что ключа не прислали.
    pub awaiting_continue: bool,
    /// Планировщик держит паузу между задачами. Присутствует только на
    /// время самой паузы — в подавляющем большинстве сеансов не
    /// появляется вовсе.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub pause_reason: Option<QueuePauseReason>,
}

// ─────────────────── история и настройки (TL-83, эпик E5) ───────────────────
//
// Контракт экрана истории, экрана настроек и папки в `Done` (дизайн E5,
// раздел «Данные для API»). Реализация — TL-85 (хранилище истории), TL-86
// (шаблон имени), TL-87 (хранилище настроек), TL-88 (показ в папке), TL-89
// (оркестрация), TL-90 и TL-91 (тела команд). Здесь только типы; команды —
// `crate::commands::history` и `crate::commands::settings`. Зеркало —
// `src/types/generated/history.ts` и `settings.ts`; `FolderDisplay` лежит в
// `download.ts` рядом с `Done`.
//
// Глушителей `#[allow(dead_code)]` в секции нет: модульные сняты TL-91 (после
// команд истории TL-90 и настроек типы конструирует продакшен-код), точечные
// на пути записи Done — TL-89 (запись ведёт оркестрация).
//
// # Семь команд
//
// - `history_page(cursor?) -> Result<HistoryPage, HistoryUnavailableError>`
// - `delete_history_record(id) -> Result<(), HistoryCommandError>`
// - `clear_history() -> Result<(), HistoryCommandError>`
// - `show_in_folder(id) -> Result<(), ShowInFolderError>`
// - `settings_get() -> SettingsView`
// - `settings_set(patch) -> Result<SettingsView, SettingsCommandError>`
// - `preview_name_template(template) -> Result<TemplatePreview, SettingsCommandError>`
//
// Новых событий нет: появление Done уже видно в `queue://changed`, а
// настройки меняет только этот же клиент (дизайн, «События»). Разрешений в
// `capabilities/main.json` команды приложения не требуют — пока у приложения
// нет собственного ACL-манифеста (сторож `app_commands_stay_outside_the_acl`
// в `tests/frontend_acl.rs`).
//
// # Где контракт отступил от буквы дизайна и почему
//
// Дизайн оставляет точные имена и формы контрактной задаче. Каждое отступление
// ниже закрывает место, где буквальная форма нарушила бы инвариант проекта.
//
// 1. **`folderDisplay` — объединение, а не строка** ([`FolderDisplay`]).
//    Строка «Загрузки» из ядра — это текст интерфейса в Rust (тексты живут
//    на стороне UI, см. [`SelectedQuality`]). Кроме того, панель различает
//    два случая оформлением: имя системной папки в кавычках, свой путь без
//    них. Со строкой ей пришлось бы сравнивать значение с магической
//    константой, которую не сторожит ни генератор, ни компилятор. Решение
//    «системная или своя» по-прежнему принимается в Rust один раз.
// 2. **Отдельного `HistoryAvailability` нет.** Три его состояния уже
//    выражены ответом `history_page`: `Err(HistoryUnavailableError)` —
//    недоступна, `Ok` с [`HistoryNotice::BaseRecreated`] в `notices` —
//    пересоздана, `Ok` без неё — в порядке. Отдельный тип стал бы вторым источником истины
//    о том же факте.
// 3. **Причины — перечисления, а не `reason: String`**
//    ([`TemplateProblem`], [`HistoryWriteFailure`]). Свободная строка —
//    либо текст интерфейса из ядра, либо диагностика, просочившаяся на
//    экран (Ф-17, Н-4 E2). Диагностика для лога едет в `message`, как у
//    соседних отказов команд.
// 4. **Классы сверх перечня Ф-17**, каждый — состояние, которое иначе
//    нечем назвать: у `show_in_folder` — `unknownRecord` и `unavailable`
//    (команда принимает `id`, записи может не быть, а базы — не открыться),
//    у `settings_set` — `writeFailed` (запись файла настроек может
//    отказать, Ф-9).
// 5. **`SettingsView::defaults`.** Кнопка «Сбросить» у шаблона и у числа
//    попыток иначе знала бы умолчания `{title}` и `8` только копией во
//    фронтенде — вторым местом, где их пришлось бы калибровать.

/// Какая папка назначения у готового файла — в той форме, в какой её
/// называет интерфейс.
///
/// Объединение, а не строка: см. пункт 1 шапки секции. На проводе тег —
/// поле `kind`.
///
/// Решение «это системная папка „Загрузки“» принимает ядро один раз для
/// всех потребителей: для панели задачи ([`DownloadProgress::Done`]), для
/// записи истории ([`HistoryEntry::folder_display`]) и для экрана настроек.
/// Фронтенд не угадывает его по абсолютному пути, то есть не знает, как
/// «Загрузки» устроены на macOS, Windows и Linux.
///
/// Решается по **фактической** папке, куда лёг файл, а не по настройке:
/// своя папка, совпавшая с системной, показывается как системная.
///
/// Правило сравнения (TL-89): покомпонентное равенство пути с резолвом
/// системной «Загрузок» (`download_dir()`) — хвостовой разделитель не важен,
/// — без `canonicalize` и без обращения к диску: папка через символьную
/// ссылку показывается своим путём. Функция одна —
/// `storage::history::folder_display` — и для записи истории, и для события
/// `Done`, на том же значении папки.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "download.ts", optional_fields))]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum FolderDisplay {
    /// Системная папка «Загрузки». Имени папки в контракте нет: подпись
    /// выбирает интерфейс.
    SystemDownloads,
    /// Своя папка пользователя. `path` — абсолютный путь целиком, без
    /// сокращений: путь — факт, который пользователь проверяет глазами
    /// (дизайн E5, пункты 3 и 4).
    Custom { path: String },
}

/// Есть ли на диске файл записи истории (Ф-5).
///
/// Вычисляется при каждом запросе страницы и в базе не хранится:
/// единственный источник — диск в момент запроса.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum HistoryFileStatus {
    /// Файл на месте — «Показать в папке» откроет его с выделением.
    Present,
    /// Файла нет. `folderExists` разводит два текста и два набора действий
    /// дизайна: папка есть — «Показать в папке» откроет её; папки нет —
    /// кнопки нет вовсе.
    Missing { folder_exists: bool },
}

/// Одна запись истории — то, что видит одна строка списка.
///
/// Состав — минимум из данных `Done` (Р-2): длительности, канала и превью
/// здесь нет и не будет без отдельного решения. **Сырого пути папки нет**:
/// «Показать в папке» принимает `id`, и путь ядро строит из собственной
/// копии записи (Ф-8). Фронтенду путь нужен только как текст, и этот текст —
/// [`Self::folder_display`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct HistoryEntry {
    /// Идентификатор записи. Для фронтенда непрозрачен: уходит обратно в
    /// `delete_history_record`, `show_in_folder` и в [`HistoryCursor`], но не
    /// разбирается и не сравнивается. Сравнение определяет ядро, и оно
    /// **числовое**: за строкой стоит целый ключ базы, и `"10"` больше `"9"`,
    /// хотя как строка меньше.
    ///
    /// **Уникален навсегда и никогда не переиспользуется**, в том числе после
    /// удаления записи и очистки истории. Это требование к схеме TL-85:
    /// `INTEGER PRIMARY KEY AUTOINCREMENT`, а не голый `INTEGER PRIMARY KEY`,
    /// который после удаления строки с наибольшим ключом выдаёт тот же ключ
    /// заново. Иначе `id` и курсор в руках открытого экрана указали бы на
    /// чужую запись, и «Удалить» стёрло бы не ту строку.
    pub id: String,
    /// Канонический id ролика (TL-72) — то же значение, по которому очередь
    /// сравнивает дубли.
    pub video_id: String,
    /// Ссылка в том виде, в каком её вставили. Показывается текстом, а не
    /// активной ссылкой (граница продукта).
    pub url: String,
    /// Название ролика, как его показала карточка E2.
    pub title: String,
    /// Выбранный пункт лестницы — вторая половина заголовка
    /// ««Название» — качество».
    pub quality: SelectedQuality,
    /// Имя готового файла с расширением, без пути.
    pub file_name: String,
    /// Папка на момент завершения — по тому же правилу, что у `Done`.
    pub folder_display: FolderDisplay,
    /// Размер файла в байтах, снятый с диска в момент записи (Ф-2).
    pub size_bytes: u64,
    /// Время завершения, Unix-секунды UTC. Относительное время
    /// («3 часа назад») строит интерфейс.
    pub finished_at_unix_secs: u64,
    /// Файл на месте или нет — на момент этого запроса.
    pub file_status: HistoryFileStatus,
}

/// Курсор постраничного чтения: последняя запись, которую уже показали.
///
/// Пара (время завершения, id), а не смещение: список растёт сверху, и
/// смещение пропускало бы или повторяло строку, если между двумя «Показать
/// ещё» завершилась загрузка (дизайн E5, пункт 2).
///
/// **Порядок строгий:** записи идут по убыванию пары `(finishedAt, id)`.
/// Сначала сравнивается время, при равенстве — `id` в числовом сравнении
/// ядра (см. [`HistoryEntry::id`]). Следующая страница — записи строго
/// меньше курсора в этом порядке. Пара уникальна, потому что уникален `id`:
/// на стыке страниц нет ни пропуска, ни повтора, даже если в одну секунду
/// завершилось больше записей, чем помещается на страницу.
///
/// Фронтенд значение не собирает: берёт [`HistoryPage::next_cursor`] и
/// отдаёт как есть. Отсюда `Deserialize` — тип ходит в обе стороны. Курсор,
/// которого ядро не выдавало (`id` не целое), — непроверенный ввод. Ответ на
/// него — пустая последняя страница без `nextCursor`, а не паника и не отказ
/// (реализация — TL-90).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct HistoryCursor {
    pub finished_at_unix_secs: u64,
    pub id: String,
}

/// Сколько записей отдаёт одна страница `history_page`.
///
/// **Константа ядра, а не параметр запроса** — решение неясности дизайна
/// («`limit` — стартовая точка калибровки, 30»). Причины:
///
/// - число калибруется на собранном приложении (Н-7), и калибровка правит
///   одно место, а не два;
/// - параметр был бы непроверенным вводом, который ядру пришлось бы
///   зажимать, чтобы `limit: 1e9` не отменил постраничность (Н-3);
/// - фронтенду число не нужно: конец списка он узнаёт по отсутствию
///   [`HistoryPage::next_cursor`], а не по неполной странице.
///
/// В TS-зеркало константа не попадает — и не должна.
pub const HISTORY_PAGE_SIZE: usize = 30;

/// Почему последняя запись в историю не сохранилась (Ф-3).
///
/// Перечисление, а не строка: см. пункт 3 шапки секции. Набор — кандидаты
/// дизайна за вычетом «база недоступна»: при недоступной базе
/// `history_page` отвечает отказом [`HistoryUnavailableError`], и страница
/// с этой пометкой не приходит вовсе.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum HistoryWriteFailure {
    /// На диске не хватило места.
    DiskFull,
    /// Нет прав на запись в каталог данных или в файл базы.
    NoAccess,
    /// База отказала по иной причине. Подробности — в логе ядра, на экран
    /// они не попадают.
    StorageFailed,
}

/// Однократная пометка на экране истории: случилось то, о чём
/// пользователь должен узнать (дизайн E5, пункт 2).
///
/// **«Выдано один раз» — свойство реализации, а не контракта.** Для
/// контракта это элемент обычного поля ответа [`HistoryPage::notices`].
/// Обещание ядра: пометка приходит в первом ответе `history_page` **без
/// курсора** после события и больше не повторяется, показал её фронтенд или
/// нет. Запрос следующей страницы (с курсором) пометок не выдаёт и не гасит:
/// «Показать ещё», нажатое до обновления первой страницы, пометку не съест.
/// Как ядро это держит, решает TL-90 вместе с хранилищем (TL-85).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum HistoryNotice {
    /// Файл базы был испорчен: он отложен рядом с меткой времени, начата
    /// новая пустая история (Ф-1 г). История работает — это баннер над
    /// списком, а не блокировка экрана.
    BaseRecreated,
    /// Загрузка завершилась, а строка истории не сохранилась.
    LastWriteFailed { cause: HistoryWriteFailure },
}

/// Ответ `history_page`: одна порция истории, новые записи сверху.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub struct HistoryPage {
    /// Не больше [`HISTORY_PAGE_SIZE`] записей, строго по убыванию пары
    /// `(finishedAt, id)`. Порядок и сравнение `id` задаёт ядро (doc
    /// [`HistoryCursor`]). UI не сортирует.
    pub entries: Vec<HistoryEntry>,
    /// Курсор следующей порции. Отсутствует, когда записей старше этих нет;
    /// по нему интерфейс и прячет «Показать ещё».
    #[serde(skip_serializing_if = "Option::is_none")]
    pub next_cursor: Option<HistoryCursor>,
    /// Однократные пометки ([`HistoryNotice`]). Пустой список — пометок нет,
    /// и так выглядит подавляющее большинство ответов.
    ///
    /// Список, а не одно значение: события независимы и могут совпасть.
    /// Например, база пересоздана при открытии (`baseRecreated`), и первая же
    /// запись в новую не сохранилась (`lastWriteFailed`). Пользователь обязан
    /// узнать об обоих, и ни одна пометка не вытесняет другую.
    ///
    /// Не больше одной пометки каждого вида, порядок не значим. У
    /// `lastWriteFailed` — причина последнего отказа. Непустым список бывает
    /// только в ответе без курсора, то есть на первой странице (doc
    /// [`HistoryNotice`]).
    pub notices: Vec<HistoryNotice>,
}

/// Почему история недоступна (Ф-1 б, в, д).
///
/// `newerVersion`, `noAccess` и `migrationFailed` — отказ открытия, история
/// недоступна на весь сеанс. `storageFailed` — отказ базы на чтении уже после
/// открытия: недоступен этот ответ, следующий запрос может пройти.
///
/// `corrupted` сюда не входит: порча базы не лишает сеанс истории, ядро
/// заводит новую (см. [`HistoryNotice::BaseRecreated`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[cfg_attr(test, derive(TS), ts(export_to = "history.ts", optional_fields))]
#[serde(rename_all = "camelCase")]
pub enum HistoryUnavailableReason {
    /// База создана более новой версией приложения. Файл не тронут и
    /// откроется на новой сборке (доктрина `ForeignVersion` TL-71).
    NewerVersion,
    /// Нет прав на каталог данных или на файл базы.
    NoAccess,
    /// Миграция схемы отказала. Транзакция откатила её, база осталась на
    /// прежней версии.
    MigrationFailed,
    /// База открылась, но отказала на чтении уже после открытия: страница
    /// истории, запись для «Показать в папке» или прерванное чтение.
    /// Подробности — в `message` и в логе ядра, на экран они не попадают.
    StorageFailed,
}

