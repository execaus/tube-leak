//! Формат файла-снимка очереди (Ф-9, Р-2 эпика E4).
//!
//! Здесь только **формат** и его версия. Атомарная запись через временный
//! файл с переименованием, чтение, разбор чужой версии и место файла в
//! каталоге данных лежат в [`super::store`] (TL-71); этот модуль не
//! открывает ни одного файла и не знает, где он лежит.
//!
//! Формат заведён раньше первой пишущей реализации сознательно — правило
//! CLAUDE.md о хранилище требует именно этого порядка, и Ф-9 повторяет
//! его дословно. Цена обратного порядка известна по чужим проектам: файл
//! без версии, который уже лежит у пользователей, меняется только ценой
//! молчаливой потери их данных.
//!
//! # Что попадает в снимок, а что нет
//!
//! Попадает то, чего хватает восстановить список приостановленным (Р-3):
//! версия формата, порядок задач, у каждой — её идентификатор и данные
//! постановки ([`StartDownloadRequest`], то же, что принимает команда
//! старта).
//!
//! Не попадает:
//!
//! - **прогресс и счётчики попыток** — докачку с места yt-dlp резолвит по
//!   частичным файлам сам, а сохранённый процент после перезапуска был бы
//!   числом, которому нечем соответствовать;
//! - **терминальные задачи** — они материал истории (E5), и хранить их
//!   здесь значило бы завести вторую историю раньше настоящей;
//! - **состояние «очередь продолжена»** — Р-3 требует, чтобы
//!   восстановленная очередь всегда была приостановленной, то есть это
//!   не переменная, а свойство самого факта восстановления. Поле для неё
//!   позволило бы записать «продолжена» и обойти Р-3 файлом.

use serde::{Deserialize, Serialize};

use crate::types::StartDownloadRequest;

/// Версия формата снимка.
///
/// Растёт на единицу при любом изменении, которое старый код прочтёт
/// неверно. Читатель ([`super::store::SnapshotStore::load`]) сверяет её и
/// **не** пытается понять незнакомое число: файл будущей версии — повод
/// начать с пустой очереди, а не угадывать. Обратное — тихая потеря
/// очереди пользователя, который однажды откатил приложение на версию
/// назад.
pub const SNAPSHOT_FORMAT_VERSION: u32 = 1;

/// Файл-снимок очереди целиком.
///
/// Версионное поле обязательное и первое — Р-2 требует его прямо. Оно
/// именно поле файла, а не имя файла и не расширение: имя переживает
/// переименование хуже, чем содержимое переживает запись.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct QueueSnapshotFile {
    /// Версия формата — [`SNAPSHOT_FORMAT_VERSION`] на момент записи.
    pub version: u32,
    /// Нетерминальные задачи в порядке постановки (Р-4, строгий FIFO).
    /// Порядок значим: он и есть порядок выполнения.
    pub tasks: Vec<QueueSnapshotEntry>,
}

/// Одна задача в файле-снимке.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct QueueSnapshotEntry {
    /// Идентификатор задачи. Сохраняется, потому что Ф-5 обещает
    /// **тот же** id после восстановления: панель, события и команды
    /// ключуются им, а новый id означал бы новую задачу для всех троих.
    pub task_id: String,
    /// Данные постановки — ровно то, что принимает команда старта.
    ///
    /// Хранится целиком, а не по полям: Ф-9 требует «то же, что
    /// принимает Ф-2», и второй набор полей рядом с первым разошёлся бы
    /// с ним на первой же правке команды. Так это уже случалось в
    /// проекте — зеркало контракта отставало от Rust, пока его писали
    /// руками (TL-51).
    pub request: StartDownloadRequest,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{QualityKind, QualitySize, QualityStreams, SelectedQuality};

    fn entry() -> QueueSnapshotEntry {
        QueueSnapshotEntry {
            task_id: "dl-1".to_string(),
            request: StartDownloadRequest {
                url: "https://www.youtube.com/watch?v=abc".to_string(),
                title: "Как приручить дракона".to_string(),
                quality: SelectedQuality {
                    kind: QualityKind::Standard,
                    height_px: Some(1080),
                },
                streams: QualityStreams {
                    video_format_id: Some("137".to_string()),
                    audio_format_id: Some("140".to_string()),
                },
                size: QualitySize::Known { bytes: 303_038_464 },
            },
        }
    }

    /// Снимок переживает круг «записали — прочитали» без потерь.
    ///
    /// Проверяется не форма JSON, а тождество значения: смысл файла в
    /// том, что задача после перезапуска — та же самая, включая
    /// идентификатор и все данные постановки.
    #[test]
    fn a_snapshot_survives_a_round_trip_unchanged() {
        let before = QueueSnapshotFile {
            version: SNAPSHOT_FORMAT_VERSION,
            tasks: vec![entry()],
        };

        let text = serde_json::to_string(&before).expect("снимок сериализуется");
        let after: QueueSnapshotFile = serde_json::from_str(&text).expect("снимок разбирается");

        assert_eq!(after, before);
    }

    /// Версия — обязательное поле, а не значение по умолчанию.
    ///
    /// Мутация, которую сторож обязан ловить: `#[serde(default)]` на
    /// версии превратил бы файл без неё в «версию 0» и увёл бы разбор в
    /// ветку, которой нет. Файл без версии обязан не разбираться вовсе —
    /// решение о нём принимает TL-71, а не молчаливый дефолт.
    #[test]
    fn a_snapshot_without_a_version_does_not_parse() {
        let text = serde_json::to_string(&serde_json::json!({ "tasks": [] }))
            .expect("фикстура сериализуется");

        assert!(
            serde_json::from_str::<QueueSnapshotFile>(&text).is_err(),
            "файл без версии формата разобрался — значит версия \
             необязательна, и старый читатель молча примет чужой формат"
        );
    }

    /// Порядок задач в файле — тот же, что записали.
    ///
    /// Он и есть порядок выполнения (Р-4), а не подсказка к сортировке:
    /// множество вместо списка стоило бы очереди её единственного
    /// правила.
    #[test]
    fn the_order_of_tasks_is_part_of_the_format() {
        let mut second = entry();
        second.task_id = "dl-2".to_string();
        let before = QueueSnapshotFile {
            version: SNAPSHOT_FORMAT_VERSION,
            tasks: vec![entry(), second],
        };

        let text = serde_json::to_string(&before).expect("снимок сериализуется");
        let after: QueueSnapshotFile = serde_json::from_str(&text).expect("снимок разбирается");

        let ids: Vec<&str> = after.tasks.iter().map(|t| t.task_id.as_str()).collect();
        assert_eq!(ids, ["dl-1", "dl-2"]);
    }
}
