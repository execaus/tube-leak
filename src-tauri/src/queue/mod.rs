//! Очередь загрузок (эпик E4).
//!
//! Здесь — контракт очереди со стороны ядра: имя канала событий и формат
//! файла-снимка, который переживает перезапуск приложения. Типы, которые
//! пересекают границу окна, объявлены в [`crate::types`] (секция «очередь
//! загрузок»); тела команд, планировщик и эмит события — TL-73, атомарные
//! запись и чтение снимка — TL-71.
//!
//! # Почему имя канала живёт здесь, а не в задаче планировщика
//!
//! Прецедент TL-24, повторённый в TL-53: разрешение канала обязано
//! появляться **раньше** первого подписчика. ACL в dev-режиме не
//! проверяется — подписка без разрешения молча отклоняется только на
//! собранном `.app`, и находит это человек, а не тест. Поэтому имя
//! объявляется вместе с контрактом, запись в `capabilities/main.json`
//! делается тем же изменением, а сторожем служит `tests/frontend_acl.rs`:
//! он сканирует исходники ядра на литералы вида `схема://сегмент` и
//! требует, чтобы у каждого найденного была запись в capability (и
//! наоборот — чтобы у каждой записи был эмитент).

pub mod snapshot;

/// Имя события состава очереди — `queue://changed`.
///
/// Эмитится на любое **структурное** изменение очереди: добавление
/// задачи, её старт, любой терминальный исход, скрытие, продолжение после
/// перезапуска, начало и конец паузы на обновление yt-dlp (Ф-6).
///
/// Несёт [`crate::types::QueueSnapshot`] целиком, а не дельту: список
/// короткий (единицы — десятки задач, Н-2), и полный снимок снимает целый
/// класс рассинхронизаций ценой чуть большего, но всё ещё маленького
/// события. Троттлинга у канала нет и не нужно: структурные изменения
/// редки по своей природе, в отличие от `download://progress`, который
/// этот канал не заменяет и не дублирует — ход активной задачи по-прежнему
/// едет им (Ф-6).
///
/// Константа объявлена контрактной задачей (TL-70), а эмитент появится в
/// TL-73. Глушитель стоит ровно поэтому и снимается вместе с ним.
#[allow(dead_code)]
pub const CHANGED_EVENT: &str = "queue://changed";
