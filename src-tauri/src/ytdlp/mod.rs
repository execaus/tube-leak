//! Домен `ytdlp`: поставка yt-dlp в каталог данных приложения (TL-12,
//! дефект #13 эпика E1).
//!
//! # Почему yt-dlp — не sidecar, в отличие от ffmpeg
//!
//! До TL-12 yt-dlp ехал в бандле однофайловой сборкой PyInstaller и
//! запускался как sidecar. Измерение (issue #13) показало, что **любой**
//! её запуск на macOS стоит 25–39 с: бутлоадер распаковывает ~130 файлов
//! (107 из них Mach-O) в новый `$TMPDIR/_MEIxxxxxx`, а macOS берёт ~0,42 с
//! за первую загрузку каждого только что созданного Mach-O — регистрация
//! подписи в `dyld4::Loader::mapSegments` → `fcntl`, запрос обслуживает
//! `syspolicyd`, результат кэшируется по inode. Inode при каждом запуске
//! новые, поэтому кэш не срабатывал никогда.
//!
//! Решение владельца (issue #13, вариант В-2): onedir-поставка в каталоге
//! данных. Архив (`yt-dlp_macos.zip` и аналоги под другие платформы) едет
//! в бандле ресурсом, при первом запуске распаковывается в каталог данных
//! приложения и один раз прогревается. Дальше inode стабильны, и запуск
//! стоит 0,30–0,35 с — как экрану, так и каждому скачиванию.
//!
//! ffmpeg остаётся sidecar-бинарником: он один файл, ему эта проблема не
//! свойственна (холодный запуск 1,58–2,52 с один раз на файл), и трогать
//! его поставку в TL-12 незачем.
//!
//! # Инвариант E6
//!
//! yt-dlp остаётся внешним бинарником, обновляемым отдельно от релизов
//! приложения. Выбранная раскладка это сохраняет и упрощает: установки
//! адресуются по `<версия>-<sha256>` и лежат рядом друг с другом в
//! каталоге данных, так что обновление — это распаковка ещё одного дерева
//! тем же кодом ([`unpack`]), а не замена файла внутри подписанного
//! бандла, которую пришлось бы делать при sidecar-поставке.
//!
//! # Состав
//!
//! - [`layout`] — где что лежит, манифест установки и её проверка;
//! - [`unpack`] — распаковка архива с проверкой целостности и атомарным
//!   появлением каталога установки;
//! - [`prepare`] — оркестрация подготовки, прогрев и события о ходе;
//! - [`error`] — типизированные причины отказа.

mod error;
mod layout;
mod prepare;
mod unpack;

pub use error::PrepareError;
pub use layout::BUNDLED_ARCHIVE_RESOURCE;
