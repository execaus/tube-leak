//! Домен `ytdlp`: поставка yt-dlp в каталог данных приложения (TL-12,
//! дефект #13 эпика E1).
//!
//! # Почему yt-dlp — не sidecar, в отличие от ffmpeg
//!
//! До TL-12 yt-dlp ехал в бандле однофайловой сборкой PyInstaller и
//! запускался как sidecar. Измерение (issue #13) показало, что **любой**
//! её запуск на macOS стоит 25–39 с: бутлоадер распаковывает ~130 файлов
//! (107 из них Mach-O) в новый `$TMPDIR/_MEIxxxxxx`, а macOS берёт ~0,42 с
//! за первую загрузку каждого только что созданного Mach-O — регистрация
//! подписи в `dyld4::Loader::mapSegments` → `fcntl`, запрос обслуживает
//! `syspolicyd`, результат кэшируется по inode. Inode при каждом запуске
//! новые, поэтому кэш не срабатывал никогда.
//!
//! Решение владельца (issue #13, вариант В-2): onedir-поставка в каталоге
//! данных. Архив (`yt-dlp_macos.zip` и аналоги под другие платформы) едет
//! в бандле ресурсом, при первом запуске распаковывается в каталог данных
//! приложения и один раз прогревается. Дальше inode стабильны, и запуск
//! стоит 0,30–0,35 с — как экрану, так и каждому скачиванию.
//!
//! ffmpeg остаётся sidecar-бинарником: он один файл, ему эта проблема не
//! свойственна (холодный запуск 1,58–2,52 с один раз на файл), и трогать
//! его поставку в TL-12 незачем.
//!
//! # Инвариант E6
//!
//! yt-dlp остаётся внешним бинарником, обновляемым отдельно от релизов
//! приложения. Выбранная раскладка это сохраняет и упрощает: установки
//! адресуются по `<версия>-<sha256>` и лежат рядом друг с другом в
//! каталоге данных, так что обновление — это распаковка ещё одного дерева
//! тем же кодом ([`unpack`]), а не замена файла внутри подписанного
//! бандла, которую пришлось бы делать при sidecar-поставке.
//!
//! Из этого же переиспользования следует, чего от [`unpack`] требовать
//! уже сейчас. Сегодня архив едет внутри подписанного бандла, и его
//! содержимое известно заранее; в E6 тот же код получает архив из сети,
//! где ни подписи, ни доверия к заголовкам нет. Поэтому границы объёма и
//! проверка свободного места заведены до E6, а не вместе с ним (TL-18).
//! Двух вещей они не закрывали, и обе закрыты в [`fetch`] (TL-56):
//! сверка sha256 архива с доверенным источником — **до** вызова
//! [`unpack`], и потолок на размер самого архива — снаружи, потому что
//! изнутри расход на разбор центрального каталога не виден.
//!
//! # Состав
//!
//! - [`layout`] — где что лежит, манифест установки и её проверка;
//! - [`unpack`] — распаковка архива с проверкой целостности, границами
//!   объёма и атомарным появлением каталога установки;
//! - [`prepare`] — оркестрация подготовки, прогрев и события о ходе;
//! - [`error`] — типизированные причины отказа;
//! - [`update`] — контур самообновления (E6): канал событий и типы,
//!   общие для шагов его конвейера;
//! - [`release`] — обнаружение новой версии по метаданным релиза: два
//!   запроса к GitHub, белый список разбора тега, описатель ассета (E6,
//!   TL-55);
//! - [`fetch`] — приём архива обновления, потолок на его размер, сверка
//!   sha256 и установка тем же [`unpack`] (E6, TL-56);
//! - [`smoke`] — запуск подготовленного кандидата (`--version`) и сверка
//!   ответа с ожидаемой версией до переключения, плюс запрет повторной
//!   установки провалившегося build id (E6, TL-57);
//! - [`state`] — какая установка активна, какая известно-хорошая, резолв
//!   пути через эту запись и уборка всего прочего (E6, TL-54);
//! - [`orchestrate`] — расписание, конвейер, граница задач, переключение
//!   и откат: единственное место, где все перечисленные выше шаги
//!   становятся обновлением (E6, TL-58);
//! - [`transport`] — сам HTTP-клиент контура, единственная сеть, которую
//!   инициирует приложение, а не yt-dlp (E6, TL-58, решение Р-7);
//! - [`session`] — память подготовки на время сеанса: один запуск yt-dlp на
//!   тёплом старте и один фоновый прогрев за раз (TL-23, TL-21).

