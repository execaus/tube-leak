//! Контур самообновления yt-dlp (эпик E6): имя канала событий и типы,
//! общие для шагов конвейера, но не пересекающие границу Rust↔TS.
//!
//! Что здесь есть и чего нет. Типы, которые видит фронтенд
//! (состояние блока, классы отказа Ф-9, отказы команд), объявлены в
//! [`crate::types`] и зеркалятся генератором TL-51 — здесь их нет
//! намеренно: адрес релизного ассета и его сумма фронтенду не нужны и
//! в TS-зеркале были бы лишним обещанием. Реализации здесь тоже нет:
//! проверка метаданных — TL-55, скачивание и проверка архива — TL-56,
//! smoke — TL-57, оркестрация и сами команды — TL-58. Эта задача (TL-53)
//! объявляет то, на что они опираются.
//!
//! Модуль лежит в домене `ytdlp`, а не рядом с будущим `updater` из
//! CLAUDE.md: то — второй контур, обновление самого приложения (E7,
//! Tauri updater, подпись). Смешивать их нельзя — у них разная частота,
//! разный риск и разный механизм.

/// Имя события хода обновления — Ф-11.
///
/// Отдельный канал от `ytdlp://prepare` и это не косметика: тот
/// зарезервирован за блокирующей подготовкой первого запуска, и поднятие
/// полноэкранного `YtDlpPrepareScreen` по событию фонового обновления
/// было бы прямой регрессией Р-1 («никаких прерывающих уведомлений»).
///
/// Полезная нагрузка — [`crate::types::YtDlpUpdateSnapshot`].
///
/// Канал объявлен в `capabilities/main.json` тем же изменением, что
/// заводит эту константу, и сторож `tests/frontend_acl.rs` держит их
/// вместе. Порядок обратный TL-24, где подписка появилась раньше
/// разрешения и отказ ACL вылез только в собранном `.app`.
#[allow(dead_code)] // Эмитить его начнёт оркестрация (TL-58).
pub const UPDATE_EVENT: &str = "ytdlp://update";

/// Релизный ассет, который контур скачает и установит.
///
/// Живёт в общем месте, а не внутри проверки (TL-55), ровно затем, чтобы
/// проверка и скачивание не зависели друг от друга: TL-56 потребляет этот
/// тип, но кода TL-55 не вызывает. Тот же приём развёл разбор прогресса и
/// склейку в E3 через общий контракт.
///
/// Источник — официальные GitHub Releases `yt-dlp/yt-dlp` (Ф-1): те же
/// платформенные onedir-ассеты, что зафиксированы пином E1. Каналов, кроме
/// стабильных релизов, у контура нет.
#[allow(dead_code)] // Конструирует TL-55, потребляет TL-56.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UpdateAsset {
    /// Версия релиза в апстримном формате `YYYY.MM.DD`.
    pub version: String,
    /// Прямой адрес платформенного onedir-архива этого релиза.
    pub url: String,
    /// Ожидаемая сумма архива, шестнадцатеричная, из файла сумм **того
    /// же** релиза (Ф-3). Распаковка — только после совпадения.
    pub sha256: String,
    /// Объявленный метаданными размер архива в байтах.
    ///
    /// Обязателен, а не опционален: по нему проверяется потолок **до**
    /// начала запроса (Ф-3, задача TL-56 — «по объявленному в метаданных
    /// размеру, до начала запроса, и по фактически принятым байтам, по
    /// ходу скачивания»), и скачивание без известного размера начинать
    /// нечем. Ассет, у которого апстрим размера не назвал, — не пригодный
    /// к установке ассет, а не ассет с пробелом в поле.
    ///
    /// С потолком TL-18 не путать: тот стоит внутри
    /// [`crate::ytdlp::unpack`], складывается из заголовков уже
    /// скачанного архива и метаданных релиза не видит. Он и просит
    /// ограничить размер снаружи — этим полем.
    pub size_bytes: u64,
}

/// Исход проверки обновления по метаданным релиза (Ф-2) — то, чем
/// отвечает TL-55.
///
/// Архив на этом шаге не скачивается и диск не трогается: «есть
/// обновление» — это метаданные, а не байты. Та же версия с другой суммой
/// обновлением не считается (Ф-1), поэтому третьего варианта нет.
#[allow(dead_code)] // Конструирует TL-55, потребляет оркестрация TL-58.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum UpdateCheck {
    /// Активная установка не старее последнего стабильного релиза (С-2).
    UpToDate,
    /// Апстрим выпустил версию новее активной.
    Available(UpdateAsset),
}
