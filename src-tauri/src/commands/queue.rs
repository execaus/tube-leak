//! Три команды очереди загрузок (контракт TL-70, эпик E4).
//!
//! Тонкий слой над доменом, как и остальные команды: ни одного решения о
//! том, что и когда выполнять, здесь нет.
//!
//! # Что здесь уже настоящее, а что ждёт планировщика
//!
//! Контрактная задача объявляет имена, формы и разрешение канала —
//! опираться на них ui-задача TL-75 начинает раньше, чем появится
//! очередь (тот же порядок, что в E6 с `ytdlp_update_state`). Очередь
//! как структуру данных ставит TL-73, и до неё «очередь» ядра — это один
//! слот E3. Поэтому:
//!
//! - `queue_state` отдаёт **настоящую** проекцию слота
//!   ([`download::queue_snapshot`]), а не пустой список: снимок,
//!   умалчивающий о живой задаче, был бы неправдой на проводе;
//! - `dismiss_queue_task` работает по-настоящему для того единственного
//!   случая, который сегодня достижим, и типизированно отказывает в
//!   остальных;
//! - `resume_queue` не делает ничего и это не заглушка, а контракт:
//!   продолжать нечего, пока очередь не восстанавливается с диска
//!   (Р-3, TL-71), а вызов при неприостановленной очереди по контракту и
//!   есть «ничего», а не ошибка.
//!
//! Событие `queue://changed` (`crate::queue::CHANGED_EVENT`) отсюда пока
//! не эмитится: эмитить его на каждое структурное изменение очереди
//! умеет только тот, кто эту очередь ведёт, — планировщик TL-73.
//! Разрешение канала выдано этой задачей и раньше первого подписчика
//! (урок TL-24), сторож — `tests/frontend_acl.rs`.

use std::sync::Arc;

use tauri::State;

use crate::download::{self, DownloadSession};
use crate::types::{DownloadCommandError, QueueSnapshot};

/// Снимок очереди — то, что экран запрашивает при монтировании и после
/// перезагрузки webview (С-9).
///
/// Не отказывает ничем: пустая очередь — это `tasks: []`, а не ошибка.
/// `Result` здесь по той же причине, что у `check_sidecar` и
/// `ytdlp_update_state`: async-команда, принимающая `State<'_, …>`,
/// обязана возвращать `Result`, иначе её future не `'static`.
#[tauri::command]
pub async fn queue_state(session: State<'_, Arc<DownloadSession>>) -> Result<QueueSnapshot, ()> {
    Ok(download::queue_snapshot(&session))
}

/// «Продолжить очередь» — снимает приостановку после перезапуска (Р-3).
///
/// Без параметров: слот один и порядок строгий, поэтому продолжается
/// очередь целиком, а не выбранная задача. Вызов при уже идущей очереди —
/// не ошибка, а ничего; сегодня это единственный достижимый случай,
/// потому что приостановленной очередь становится только при
/// восстановлении с диска (TL-71).
#[tauri::command]
pub async fn resume_queue(session: State<'_, Arc<DownloadSession>>) -> Result<(), ()> {
    // Состояние читается, а не игнорируется: продолжать нечего ровно
    // потому, что приостановленной очередь сейчас не бывает, и это
    // видно из её же снимка, а не из комментария.
    let snapshot = download::queue_snapshot(&session);
    if snapshot.awaiting_continue {
        eprintln!("queue: продолжение приостановленной очереди появится вместе с планировщиком");
    }
    Ok(())
}

/// «Скрыть» — убирает завершённую задачу из списка.
///
/// Команда ядра, а не локальное состояние стора: иначе перезагрузка
/// webview воскрешала бы скрытое (С-9).
#[tauri::command]
pub async fn dismiss_queue_task(
    task_id: String,
    session: State<'_, Arc<DownloadSession>>,
) -> Result<(), DownloadCommandError> {
    download::dismiss_queue_task(&session, &task_id).map_err(|rejection| {
        eprintln!("queue: скрытие отклонено: {rejection}");
        rejection.to_contract()
    })
}
