/// Бюджет длины основы имени **частичного** файла, в байтах.
///
/// Своя величина, а не [`crate::download::filename::MAX_STEM_BYTES`], и
/// это не дубль. Финальному имени дописывают расширение, суффикс
/// коллизии и метку склейки; частичному — другое и больше: `.f` плюс
/// идентификатор формата ([`MAX_FORMAT_ID_BYTES`]), расширение и `.part`,
/// который yt-dlp дописывает сам. Возьми мы чужой бюджет — предельно
/// длинное название дало бы корректное финальное имя и слишком длинное
/// частичное, то есть отказ ровно на длинных названиях и только на них.
fn download_stem_budget() -> usize {
    const NAME_MAX: usize = crate::download::filename::MAX_FILE_NAME_BYTES;
    // `.f` + идентификатор + `.` + расширение (до 8) + `.part`
    NAME_MAX - (2 + MAX_FORMAT_ID_BYTES) - 9 - 5
}

/// Символы, которые ядро согласно отдать в шаблон вывода yt-dlp.
///
/// Список **разрешённых**, а не запрещённых, и это не стиль. Шаблон имени
/// у yt-dlp — не просто строка: перед подстановкой полей значение
/// проходит раскрытие переменных окружения и домашнего каталога. Что
/// именно раскрывается, измерено прямыми запусками вложенного бинарника
/// (macOS, пин 2026.08.19, 2026-08-27, `--print filename`):
///
/// | В шаблоне | Что вышло |
/// |---|---|
/// | `A$HOME B` | `…/A/Users/execaus B` — в имени появились разделители пути |
/// | `$HOME-leading` | `/Users/execaus-leading` — **путь стал абсолютным**, папка назначения потеряна |
/// | `${HOME}` | раскрывается так же |
/// | `$$HOME` | раскрывается: **удвоение доллара экранированием не является** |
/// | `~/leading` | `/Users/execaus/leading` — **тоже уводит из папки назначения** |
/// | `%(ext)s` | поле подставляется |
/// | `%%(ext)s` | остаётся текстом: удвоение процента экранированием является |
/// | `$TL_NO_SUCH_VAR`, `%HOME%`, `~` в середине, `\` | остаются текстом |
///
/// Список опасного здесь уже подводил дважды: сперва в шаблоне
/// экранировался только процент, и мимо прошёл доллар; при разборе
/// доллара нашёлся ещё и ведущий тильда-путь. Третьего раза не будет:
/// перечисляется безопасное. Ошибка перечисления в эту сторону стоит
/// некрасивого имени **частичного** файла, ошибка в ту — файла за
/// пределами папки назначения, собранного из названия, которое пришло от
/// YouTube.
///
/// Финального имени это не касается: его строит [`finalize_in_dir`] уже
/// после того, как yt-dlp сделал своё дело, и в нём название сохраняется
/// целиком — с долларом, процентом и чем угодно ещё.
fn template_safe(ch: char) -> bool {
    ch.is_alphanumeric()
        || matches!(
            ch,
            ' ' | '-' | '_' | '.' | ',' | '(' | ')' | '[' | ']' | '\'' | '!'
        )
}

/// Чем заменяется всё, что в шаблон не пускают.
const TEMPLATE_REPLACEMENT: char = '_';

/// Основа имени частичных файлов: финальная основа, пропущенная через
/// белый список [`template_safe`] и укороченная под свой бюджет.
///
/// Выводится из финальной, а не считается заново, потому что на этом
/// стоит обещание Р-2: после выхода из приложения пользователь вставляет
/// ту же ссылку, ядро строит **то же** имя частичного файла, и yt-dlp
/// продолжает с места своим штатным механизмом. Любая
/// недетерминированная часть имени это обещание отменяет — а вот
/// совпадать с финальным именем оно не обязано.
///
/// Цена белого списка названа прямо: два разных названия, отличающихся
/// только непропущенными символами, дают одну основу частичного файла.
/// Столкнуться они могут лишь через сохранённое частичное от **другой**
/// задачи — активная в E3 одна, а штатный исход частичных не оставляет.
/// Финальные имена при этом не сталкиваются никогда: их разводит суффикс
/// коллизии (Ф-7).
fn download_stem(stem: &str) -> String {
    let allowed: String = stem
        .chars()
        .map(|ch| {
            if template_safe(ch) {
                ch
            } else {
                TEMPLATE_REPLACEMENT
            }
        })
        .collect();

    let budget = download_stem_budget();
    let mut cut = budget.min(allowed.len());
    while cut > 0 && !allowed.is_char_boundary(cut) {
        cut -= 1;
    }
    // Точка и пробел на конце: первую Windows молча срезает, второй —
    // тоже. Обрезка легко оставляет и то и другое посреди слова.
    let fitted = allowed[..cut].trim_end_matches(['.', ' ']);

    if fitted.is_empty() {
        // Недостижимо на выходе `sanitized_stem` (пустой основы он не
        // отдаёт), но имя частичного файла обязано быть непустым при
        // любом входе, а не при том, который мы ожидаем.
        return TEMPLATE_REPLACEMENT.to_string();
    }
    fitted.to_string()
}

/// Идентификатор формата, который ядро согласно передать процессу (Ф-1).
///
/// Белый список, а не чистка: идентификаторы yt-dlp состоят из букв,
/// цифр, дефиса, подчёркивания и точки, и всё остальное — не
/// идентификатор, а чужая строка в аргументах чужой программы. Чистить её
/// («выбросить лишнее и попробовать») значило бы скачать не то, что
/// выбрал пользователь, — тот же обман, что и подмена качества
/// «ближайшим», которую С-10 запрещает прямым текстом.
///
/// Плюс (`+`) отвергается отдельно и намеренно: у `-f` это оператор
/// объединения потоков, и `137+140` в одном поле означало бы запуск, где
/// склейку снова ведёт yt-dlp.
///
/// Ведущий дефис отвергается тоже, хотя дефис внутри разрешён
/// (`140-drc` — настоящий идентификатор): строка, начинающаяся с него,
/// это флаг, а не значение. Сегодня она стоит в позиции значения `-f` и
/// флагом стать не может, но правило «пользовательский ввод не начинается
/// с дефиса» дешевле держать здесь, чем полагаться на то, что позиция
/// аргумента никогда не изменится. Ведущая точка — по той же причине:
/// имя частичного файла строится из идентификатора, а имя, начинающееся
/// с точки, на двух из трёх ОС скрытое.
fn usable_format_id(format_id: &str) -> bool {
    !format_id.is_empty()
        && format_id.len() <= MAX_FORMAT_ID_BYTES
        && !format_id.starts_with(['-', '.'])
        && format_id
            .chars()
            .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '-' | '_' | '.'))
}

// ────────────────────────── Приёмник событий ──────────────────────────

/// Куда уходят события хода задачи.
///
/// Шов ровно ради тестов — тот же приём и та же причина, что у
/// [`crate::ytdlp::prepare::ProgressSink`]: автомат фаз нельзя проверить,
/// поднимая настоящее Tauri-приложение, а проверить его надо.
pub trait ProgressSink: Send + Sync {
    fn emit(&self, event: DownloadProgressEvent);
}

/// Боевой приёмник: Tauri-событие [`PROGRESS_EVENT`] всем окнам.
pub struct AppSink(pub tauri::AppHandle);

impl ProgressSink for AppSink {
    fn emit(&self, event: DownloadProgressEvent) {
        use tauri::Emitter as _;

        // Неотправленное событие — не повод бросать загрузку: работа
        // важнее индикатора (то же решение, что в подготовке yt-dlp).
        if let Err(err) = self.0.emit(PROGRESS_EVENT, event) {
            eprintln!("download: не удалось отправить событие прогресса: {err}");
        }
    }
}

/// Троттлинг и запись последнего состояния задачи в одном месте.
///
/// Через него проходит **каждое** изменение фазы: он и отправляет
/// событие, и обновляет снимок, по которому очередь решает, что случилось
/// с задачей и можно ли её повторить. Двух путей к этим двум действиям
/// нет намеренно — разойдясь, они дали бы задачу, о состоянии которой
/// экран и ядро думают разное.
struct Emitter<'a> {
    task: &'a Arc<DownloadTask>,
    sink: &'a dyn ProgressSink,
    last_emit: Option<Instant>,
}

impl<'a> Emitter<'a> {
    fn new(task: &'a Arc<DownloadTask>, sink: &'a dyn ProgressSink) -> Self {
        Self {
            task,
            sink,
            last_emit: None,
        }
    }

    /// Записать состояние и, если можно, отправить событие.
    ///
    /// Троттлинг пропускает вперёд всё, что меняет **вид** состояния:
    /// смену фазы, смену состояния внутри `downloading`
    /// (`running` ⇄ `waitingRetry`) и любой терминальный переход.
    /// Придерживается он только частых обновлений одного и того же вида —
    /// то есть ровно того, ради чего заведён.
    ///
    /// Снимок задачи обновляется **всегда**, даже когда событие
    /// проглочено: он не для экрана, а для команд, и отставший снимок
    /// означал бы отказ `retry_download` по причине, которой уже нет.
    fn emit(&mut self, progress: DownloadProgress) {
        self.emit_with(progress, false);
    }

    /// То же, но мимо троттлинга.
    ///
    /// Нужно ровно одному месту — последнему обновлению перед уходом из
    /// «Скачивания». Вид состояния там не меняется (`running` остаётся
    /// `running`), значит троттлинг вправе его проглотить, и шаг
    /// «Скачивание» закончился бы на том проценте, который случайно
    /// успел проехать, — 43 % вместо ста. Смены фазы это не спасает:
    /// она приезжает следующим событием и рисует уже другой шаг.
    fn force(&mut self, progress: DownloadProgress) {
        self.emit_with(progress, true);
    }

    fn emit_with(&mut self, progress: DownloadProgress, force: bool) {
        let previous = self.task.snapshot();
        let now = monotonic_now();

        let shape_changed = previous.phase() != progress.phase()
            || downloading_shape(&previous) != downloading_shape(&progress);
        // `Option::is_none_or` подошёл бы лучше, но он стабилен с 1.82,
        // а нижняя граница проекта — 1.77.
        let due = match self.last_emit {
            None => true,
            Some(last) => now.duration_since(last) >= PROGRESS_THROTTLE,
        };

        self.task.set_progress(progress.clone());

        if !(force || shape_changed || progress.is_terminal() || due) {
            return;
        }

        self.last_emit = Some(now);
        self.sink.emit(DownloadProgressEvent {
            task_id: self.task.id.clone(),
            progress,
        });
    }
}

/// Вид состояния внутри фазы `downloading`; `None` — фаза другая.
fn downloading_shape(progress: &DownloadProgress) -> Option<&'static str> {
    match progress {
        DownloadProgress::Downloading(DownloadingState::Running { .. }) => Some("running"),
        DownloadProgress::Downloading(DownloadingState::WaitingRetry { .. }) => {
            Some("waitingRetry")
        }
        _ => None,
    }
}

// ────────────────────────── Запуск yt-dlp ──────────────────────────

/// Запускатель yt-dlp, отдающий stdout построчно, — единственный шов
/// между автоматом фаз и настоящим процессом.
///
/// `on_line` возвращает момент, до которого обязана прийти следующая
/// строка; `None` снимает срок. Так сторож «нет продвижения» получается
/// **таймером, а не счётчиком строк**, чего и требует находка TL-41:
/// замерший поток либо не печатает ничего, либо печатает «Read timed out»,
/// ничего не принимая, — счётчик строк обманулся бы в обе стороны.
pub trait DownloadLauncher: Send + Sync {
    fn launch<'a>(
        &'a self,
        args: &'a [&'a str],
        handle: &'a RunHandle,
        first_deadline: Instant,
        on_line: &'a mut (dyn FnMut(&str) -> Option<Instant> + Send),
    ) -> Pin<Box<dyn Future<Output = Result<StreamedRun, SidecarError>> + Send + 'a>>;
}

/// Продакшен-реализация: запуск через домен `sidecar` (E1) — реестр
/// процессов, группа процессов и убийство по сроку живут в
/// [`crate::sidecar::run_streaming`].
pub struct SidecarDownloader<'a> {
    /// `None` — готовой установки yt-dlp нет вовсе (подготовка не
    /// выполнялась, дерево не сошлось с манифестом).
    ///
    /// Отсутствие пути выражено здесь, а не отдельной веткой у
    /// вызывающего, ради единственности терминального пути: задача,
    /// которой не на чем работать, обязана кончиться тем же событием
    /// `failed` и той же подчисткой, что и любая другая, — и так же
    /// вернуть управление очереди. Подменять недостающий путь относительным именем
    /// (`"yt-dlp"`) нельзя: относительное имя ОС ищет в `PATH`, то есть
    /// приложение запустило бы **чужой** yt-dlp с машины пользователя.
    executable: Option<PathBuf>,
    registry: &'a ChildRegistry,
}

impl<'a> SidecarDownloader<'a> {
    pub fn new(executable: Option<PathBuf>, registry: &'a ChildRegistry) -> Self {
        Self {
            executable,
            registry,
        }
    }
}

impl DownloadLauncher for SidecarDownloader<'_> {
    fn launch<'a>(
        &'a self,
        args: &'a [&'a str],
        handle: &'a RunHandle,
        first_deadline: Instant,
        on_line: &'a mut (dyn FnMut(&str) -> Option<Instant> + Send),
    ) -> Pin<Box<dyn Future<Output = Result<StreamedRun, SidecarError>> + Send + 'a>> {
        let Some(executable) = self.executable.as_deref() else {
            return Box::pin(std::future::ready(Err(SidecarError::NotFound)));
        };

        Box::pin(run_streaming(
            executable,
            args,
            self.registry,
            handle,
            first_deadline,
            on_line,
        ))
    }
}

// ─────────────────────────── Состояние ───────────────────────────

/// Отмена задачи: флаг плюс побудка ждущих.
///
/// Флаг нужен потому, что отмена приходит в любой момент, а проверяется в
/// нескольких; побудка — потому, что пауза перед повтором длится до
/// минуты, и просыпаться от неё по таймеру значило бы отвечать на
/// «Отменить» через сорок секунд (Н-3 требует секунд).
#[derive(Debug, Default)]
struct CancelToken {
    flag: AtomicBool,
    notify: tokio::sync::Notify,
}

impl CancelToken {
    fn cancel(&self) {
        self.flag.store(true, Ordering::SeqCst);
        self.notify.notify_waiters();
    }

    fn is_cancelled(&self) -> bool {
        self.flag.load(Ordering::SeqCst)
    }

    /// Ждёт отмены. Регистрация в [`tokio::sync::Notify`] делается **до**
    /// проверки флага — иначе отмена, случившаяся между проверкой и
    /// ожиданием, была бы потеряна навсегда (та же ловушка и то же её
    /// закрытие, что в [`RunHandle`]).
    async fn cancelled(&self) {
        loop {
            let notified = self.notify.notified();
            if self.is_cancelled() {
                return;
            }
            notified.await;
            if self.is_cancelled() {
                return;
            }
        }
    }
}

/// Один поток задачи.
#[derive(Debug, Clone)]
struct StreamJob {
    stream: DownloadStream,
    format_id: String,
    /// Путь к файлу потока, как только его назвал сам yt-dlp
    /// (`[download] Destination: …` или `… has already been downloaded`).
    file: Option<PathBuf>,
    /// Поток забран целиком — качать его в следующей попытке не нужно.
    done: bool,
}

/// Состояние работы, живущее между попытками и повторами задачи.
///
/// Переживает и автоматические повторы, и ручной `retry_download`, и
/// именно поэтому процент не откатывается к нулю (К-6): агрегатор
/// помнит принятые байты, а не начинает считать заново.
struct TaskWork {
    aggregator: ProgressAggregator,
    jobs: Vec<StreamJob>,
    /// Основа финального имени (санитизация названия, TL-40).
    stem: String,
    /// Основа имени частичных файлов.
    download_stem: String,
    /// Детали последней прерванной попытки.
    ///
    /// Хранятся здесь, потому что понадобятся не там, где получены:
    /// решение сдаться принимает политика повторов, а деталей она не
    /// несёт (её собственная документация говорит об этом прямо), и без
    /// этого поля в «Подробнее» у исчерпания попыток не было бы ничего.
    last_interrupt: Option<DownloadErrorDetails>,
}

/// Изменяемая часть задачи, к которой ходят и воркер, и команды.
#[derive(Debug)]
struct TaskState {
    progress: DownloadProgress,
    /// Класс последнего отказа — по нему `retry_download` решает, есть ли
    /// смысл в повторе. Держится отдельно от `progress` потому, что
    /// доставать его из варианта пришлось бы в двух местах.
    failure: Option<DownloadErrorKind>,
    /// Дескриптор процесса, идущего прямо сейчас (yt-dlp или ffmpeg).
    child: Option<Arc<RunHandle>>,
}

/// Задача скачивания: то, что живёт между вызовами трёх команд.
pub struct DownloadTask {
    pub id: String,
    pub plan: DownloadPlan,
    request: StartDownloadRequest,
    state: StdMutex<TaskState>,
    cancel: CancelToken,
    work: tokio::sync::Mutex<TaskWork>,
}

impl DownloadTask {
    fn lock(&self) -> std::sync::MutexGuard<'_, TaskState> {
        self.state
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Последнее известное состояние задачи.
    pub fn snapshot(&self) -> DownloadProgress {
        self.lock().progress.clone()
    }

    /// Данные постановки — то, с чем задача создана.
    ///
    /// Планировщику они нужны целиком: заголовок и пункт качества едут в
    /// снимок очереди (Ф-1), ссылка и `streams` — в сравнение дублей
    /// (Ф-8), а весь запрос как есть — в файл-снимок на диске (Ф-9).
    /// Отдаётся ссылкой, а не копией: запрос неизменяем с момента
    /// создания задачи.
    pub fn request(&self) -> &StartDownloadRequest {
        &self.request
    }

    /// Класс последнего отказа — по нему решается, есть ли смысл в
    /// повторе (Ф-5).
    ///
    /// Отдельно от [`Self::snapshot`], потому что доставать его из
    /// варианта пришлось бы в двух местах; здесь то же поле, что читал
    /// `retry_download` E3 до переезда в очередь.
    pub fn failure(&self) -> Option<DownloadErrorKind> {
        self.lock().failure
    }

    /// Ставит состояние задачи, минуя события.
    ///
    /// Зовут двое: [`Emitter`] (и он же шлёт событие) и планировщик
    /// очереди — на переходах, у которых события прогресса нет по
    /// построению. Их ровно два, и оба про ожидающую задачу: повтор
    /// возвращает её в `Queued` (Ф-5), отмена ожидающей — в `Cancelled`
    /// без единого побочного действия (Ф-4, С-2). Ожидающие задачи
    /// молчат в `download://progress` (Ф-6), а изменение состава очереди
    /// уезжает `queue://changed`.
    pub fn set_progress(&self, progress: DownloadProgress) {
        let mut state = self.lock();
        if let DownloadProgress::Failed { error } = &progress {
            state.failure = Some(error.kind);
        }
        state.progress = progress;
    }

    fn set_child(&self, child: Option<Arc<RunHandle>>) {
        self.lock().child = child;
    }

    /// Отменяет задачу: поднимает флаг, будит ждущих паузу и убивает
    /// процесс, если он сейчас есть.
    ///
    /// Возврат означает, что убийство уже отправлено, — то есть новую
    /// загрузку можно начинать, не рискуя оставить два живых процесса
    /// (то же обещание, что у [`RunHandle::cancel`]).
    pub async fn cancel(&self) {
        self.cancel.cancel();
        let child = self.lock().child.clone();
        if let Some(child) = child {
            child.cancel().await;
        }
    }
}

// ─────────────────────── Создание задачи ───────────────────────

/// Проверяет запрос и собирает задачу — всё, что делается **до** того,
/// как её возьмёт планировщик очереди (`crate::queue::scheduler`).
///
/// Слота здесь больше нет, и это главное отличие от E3: где задача
/// встанет, когда стартует и что случится с её предшественницей, решает
/// очередь (Ф-2, Ф-3 эпика E4), а этот модуль ведёт **одну** задачу от
/// `Queued` до терминальной фазы и ничего не знает о соседях. Раньше обе
/// обязанности жили в одной функции `start_download`, и цена этого была
/// названа прямо: второй старт вытеснял идущую загрузку.
///
/// Идентификатор выдаёт вызывающий, а не эта функция: он же ведёт
/// очередь, он же восстанавливает её с диска — а восстановленная задача
/// обязана получить **тот же** id, что был в снимке (Ф-5, Ф-9), и новый
/// счётчик здесь этого не дал бы.
///
/// # Что здесь проверяется и почему заново
///
/// Ссылка проверяется той же функцией, что и в разборе
/// ([`crate::probe::validate_url`]): её уже разбирал E2, но между разбором
/// и стартом лежит граница IPC, а через неё приезжает то, что прислали, а
/// не то, что показывали. Идентификаторы потоков — [`usable_format_id`].
///
/// Отказ непригодного идентификатора носит класс `noStreamsSelected`, и
/// это решение, а не совпадение. Своего класса у него нет: список отказов
/// команд зафиксирован контрактом (TL-38, правка TL-70), а лишний класс
/// стоил бы правки в трёх областях ради состояния, до которого исправный
/// фронтенд не доводит — идентификаторы он берёт из нашей же выдачи
/// разбора. Из существующих подходит ровно этот: строка, которую ядро
/// отказывается передать процессу, идентификатором потока не является,
/// то есть пригодных потоков в запросе нет. Молча выбросить негодный и
/// скачать оставшийся — путь, отвергнутый прямо: пользователь получил бы
/// не то качество, которое выбрал. Настоящая причина при этом уезжает в
/// лог, где на неё есть место.
pub fn build_task(
    id: String,
    request: StartDownloadRequest,
) -> Result<Arc<DownloadTask>, DownloadCommandRejection> {
    crate::probe::validate_url(&request.url).map_err(|_| {
        eprintln!("download: ссылка не является http(s)-адресом — yt-dlp не запускался");
        DownloadCommandRejection::InvalidUrl
    })?;

    if !request.streams.has_any() {
        return Err(DownloadCommandRejection::NoStreamsSelected);
    }
    for format_id in format_ids(&request.streams) {
        if !usable_format_id(format_id) {
            eprintln!(
                "download: идентификатор потока «{format_id}» не является \
                 идентификатором формата yt-dlp — запуска не будет"
            );
            return Err(DownloadCommandRejection::NoStreamsSelected);
        }
    }

    let aggregator = ProgressAggregator::new(&request.streams, request.size)
        .ok_or(DownloadCommandRejection::NoStreamsSelected)?;
    let plan = aggregator.plan();

    let stem = sanitized_stem(&request.title, &video_id_of(&request.url));
    let download_stem = download_stem(&stem);
    let jobs = jobs_of(&request.streams);

    eprintln!(
        "download: задача {id} создана, потоков {}, план {plan:?}",
        format_ids(&request.streams).count()
    );

    Ok(Arc::new(DownloadTask {
        id,
        plan,
        request,
        state: StdMutex::new(TaskState {
            progress: DownloadProgress::Queued,
            failure: None,
            child: None,
        }),
        cancel: CancelToken::default(),
        work: tokio::sync::Mutex::new(TaskWork {
            aggregator,
            jobs,
            stem,
            download_stem,
            last_interrupt: None,
        }),
    }))
}

/// Идентификаторы потоков запроса — в том порядке, в каком они
/// скачиваются.
fn format_ids(streams: &QualityStreams) -> impl Iterator<Item = &str> {
    [
        streams.video_format_id.as_deref(),
        streams.audio_format_id.as_deref(),
    ]
    .into_iter()
    .flatten()
}

fn jobs_of(streams: &QualityStreams) -> Vec<StreamJob> {
    let job = |stream, format_id: &Option<String>| {
        format_id.as_ref().map(|format_id| StreamJob {
            stream,
            format_id: format_id.clone(),
            file: None,
            done: false,
        })
    };

    [
        job(DownloadStream::Video, &streams.video_format_id),
        job(DownloadStream::Audio, &streams.audio_format_id),
    ]
    .into_iter()
    .flatten()
    .collect()
}

/// Идентификатор ролика из ссылки — только для запасного имени файла,
/// когда от названия после санитизации не осталось ничего (Ф-6).
///
/// Разбором ссылок YouTube это не является и являться не должно
/// (инвариант проекта: адреса — дело yt-dlp). Берётся значение `v=`,
/// иначе — последний непустой сегмент пути; доверия ему не больше, чем
/// названию, и [`sanitized_stem`] пропускает его через собственный белый
/// список.
fn video_id_of(url: &str) -> String {
    let after_scheme = url.split_once("://").map_or(url, |(_, rest)| rest);
    let (path, query) = match after_scheme.split_once('?') {
        Some((path, query)) => (path, query),
        None => (after_scheme, ""),
    };

    for pair in query.split('&') {
        if let Some(value) = pair.strip_prefix("v=") {
            return value.split('#').next().unwrap_or_default().to_string();
        }
    }

    path.rsplit('/')
        .find(|segment| !segment.is_empty())
        .unwrap_or_default()
        .to_string()
}

// ──────────────────────────── Воркер ────────────────────────────

/// Чем кончилась задача.
enum TaskEnd {
    Done { file_name: String },
    Failed(DownloadFailure),
    Cancelled,
}

/// Ведёт задачу от `Queued` до одной из трёх терминальных фаз.
///
/// Функция ведёт **одну** задачу и о существовании соседей не знает:
/// единственность активной держит очередь (`crate::queue::scheduler`),
/// которая зовёт воркера следующей только после возврата отсюда. В E3
/// здесь стояли два шага, которых больше нет, — «добить предшественника»
/// и «встать в шлюз»: они были платой за вытеснение, а вытеснения в
/// очереди не бывает (Ф-3, строгий FIFO). Двух yt-dlp во времени это
/// по-прежнему не допускает, но держится это теперь на планировщике, а
/// не на шлюзе внутри воркера.
pub async fn run_task(
    task: &Arc<DownloadTask>,
    launcher: &dyn DownloadLauncher,
    ffmpeg: &dyn FfmpegLauncher,
    sink: &dyn ProgressSink,
    destination: &Path,
) {
    let mut emitter = Emitter::new(task, sink);
    let started = monotonic_now();
    let end = execute(task, launcher, ffmpeg, &mut emitter, destination).await;
    let elapsed = started.elapsed();

    // Подчистка и терминальное событие — в одном месте на все ветки:
    // «что осталось на диске» уезжает на провод фактом, а не догадкой по
    // классу (doc [`crate::types::PartialData`]), и узнаётся он ровно тем,
    // что подчистка сделала.
    let mut work = task.work.lock().await;
    let progress = match end {
        TaskEnd::Done { file_name } => {
            // Готовый файл лежит под финальным именем; всё, что от задачи
            // могло остаться рядом (потоки после склейки, хвосты
            // фрагментов), — мусор, а Н-4 требует, чтобы штатные исходы
            // его не оставляли.
            Cleanup::Remove.apply(destination, &work);
            eprintln!(
                "download: задача {} готова за {} мс: «{file_name}»",
                task.id,
                elapsed.as_millis()
            );
            DownloadProgress::Done { file_name }
        }
        TaskEnd::Cancelled => {
            let partial_data = Cleanup::Remove.apply(destination, &work);
            eprintln!(
                "download: задача {} отменена за {} мс, частичное: {partial_data:?}",
                task.id,
                elapsed.as_millis()
            );
            DownloadProgress::Cancelled { partial_data }
        }
        TaskEnd::Failed(failure) => {
            let kind = failure.kind();
            let partial_data = Cleanup::for_failure(kind).apply(destination, &work);
            eprintln!(
                "download: задача {} провалена за {} мс, класс {kind:?} ({failure}), \
                 частичное: {partial_data:?}",
                task.id,
                elapsed.as_millis()
            );
            DownloadProgress::Failed {
                error: failure.to_contract(partial_data),
            }
        }
    };
    // Снимаем ссылку на процесс до терминального события: после него
    // задача кончилась, и убивать по чужому дескриптору уже нечего.
    task.set_child(None);
    work.last_interrupt = None;
    drop(work);

    emitter.emit(progress);

    // Границу задач (Ф-7, Р-2 эпика E6) объявляет не воркер, а очередь —
    // после возврата отсюда. Причина в определении самой границы: «задач
    // нет» — свойство очереди, а не одной задачи, и объявить его тому,
    // кто видит одну, было бы неправдой ровно тогда, когда за этой
    // задачей стоит следующая.
}

/// Автомат фаз: подготовка → скачивание (с повторами) → склейка →
/// финализация.
async fn execute(
    task: &Arc<DownloadTask>,
    launcher: &dyn DownloadLauncher,
    ffmpeg: &dyn FfmpegLauncher,
    emitter: &mut Emitter<'_>,
    destination: &Path,
) -> TaskEnd {
    if task.cancel.is_cancelled() {
        return TaskEnd::Cancelled;
    }

    if let Err(failure) = ensure_destination(destination) {
        return TaskEnd::Failed(failure);
    }
    let Some(destination_arg) = destination_arg(destination) else {
        // Путь, не представимый в UTF-8: аргументы процесса домен
        // `sidecar` принимает строками. На macOS и Windows не возникает
        // вовсе (там имена и так Unicode).
        return TaskEnd::Failed(DownloadFailure::DestinationUnavailable {
            reason: "путь к папке назначения не представим в UTF-8".to_string(),
            details: no_details(),
        });
    };

    let mut work = task.work.lock().await;
    let mut policy = RetryPolicy::new(monotonic_now());

    emitter.emit(DownloadProgress::Fetching);

    // ── Скачивание с повторами ──
    loop {
        if task.cancel.is_cancelled() {
            return TaskEnd::Cancelled;
        }

        policy.attempt_started(monotonic_now());
        let mut interrupted = None;

        for index in 0..work.jobs.len() {
            if work.jobs[index].done {
                continue;
            }
            if task.cancel.is_cancelled() {
                return TaskEnd::Cancelled;
            }

            match download_stream(
                task,
                &mut work,
                index,
                &mut policy,
                launcher,
                emitter,
                &destination_arg,
            )
            .await
            {
                StreamRun::Completed => {
                    work.jobs[index].done = true;
                    let format_id = work.jobs[index].format_id.clone();
                    // Поток, который качать не пришлось, не присылает ни
                    // одной строки прогресса — включая `finished`. Без
                    // этой отметки повтор после неудачной склейки навсегда
                    // упирался бы в неполный процент.
                    work.aggregator.mark_complete(&format_id);
                }
                StreamRun::Interrupted(details) => {
                    interrupted = Some(details);
                    break;
                }
                StreamRun::Failed(failure) => return TaskEnd::Failed(failure),
                StreamRun::Cancelled => return TaskEnd::Cancelled,
            }
        }

        let Some(details) = interrupted else {
            // Шаг «Скачивание» заканчивается на своих ста процентах, а не
            // на том, что успело проехать сквозь троттлинг.
            emitter.force(DownloadProgress::Downloading(
                work.aggregator.running(Some(policy.attempt())),
            ));
            break;
        };
        work.last_interrupt = Some(details);

        match policy.attempt_failed() {
            RetryDecision::Retry { attempt, delay } => {
                let state = work.aggregator.waiting_retry(attempt, 0, 0);
                let percent = frozen_percent(&state);
                if !wait_before_retry(task, emitter, attempt, delay, percent).await {
                    return TaskEnd::Cancelled;
                }
            }
            RetryDecision::GiveUp { attempts } => {
                // Класс «соединение потеряно» собирается здесь из двух
                // половин: решение сдаться даёт политика, детали — та
                // самая последняя прерванная попытка. Политика деталей не
                // несёт по своей же документации.
                return TaskEnd::Failed(DownloadFailure::ConnectionLost {
                    attempts,
                    details: work.last_interrupt.clone().unwrap_or_else(no_details),
                });
            }
        }
    }

    // ── Склейка либо единственный поток ──
    let ready = match task.plan {
        DownloadPlan::VideoAndAudio => {
            emitter.emit(DownloadProgress::Merging);

            let (Some(video), Some(audio)) = (
                stream_file(&work, DownloadStream::Video),
                stream_file(&work, DownloadStream::Audio),
            ) else {
                // Оба потока объявлены скачанными, а файла нет: верить
                // коду завершения больше, чем файловой системе, здесь
                // не за что.
                eprintln!("download: потоки скачаны, но файла одного из них нет на диске");
                return TaskEnd::Failed(DownloadFailure::MergeFailed {
                    details: no_details(),
                });
            };

            let handle = Arc::new(RunHandle::new());
            task.set_child(Some(Arc::clone(&handle)));
            // Отмена, пришедшая между проверкой и установкой дескриптора,
            // иначе никого не убила бы: процесс запускается уже после неё.
            if task.cancel.is_cancelled() {
                handle.cancel().await;
            }
            let verdict = merge_streams(
                ffmpeg,
                &MergeRequest {
                    video: &video,
                    audio: &audio,
                    destination_dir: destination,
                    stem: &work.stem,
                },
                &handle,
            )
            .await;
            task.set_child(None);

            match verdict {
                MergeVerdict::Merged(merged) => {
                    (merged.path, merged.container.extension().to_string())
                }
                MergeVerdict::Cancelled => return TaskEnd::Cancelled,
                MergeVerdict::Failed(failure) => return TaskEnd::Failed(failure),
            }
        }
        DownloadPlan::SingleStream => {
            // Ни склейки, ни перекодирования (С-2, С-3): фазы `merging` в
            // жизни такой задачи не бывает вовсе, и расширение берётся
            // фактическое — то, которое дал скачанному файлу yt-dlp.
            let Some(file) = work.jobs.first().and_then(|job| job.file.clone()) else {
                eprintln!("download: поток скачан, но файла нет на диске");
                return TaskEnd::Failed(DownloadFailure::YtDlpFailure {
                    reason: YtDlpFailureReason::Generic,
                    details: no_details(),
                });
            };
            let extension = file
                .extension()
                .map(|ext| ext.to_string_lossy().into_owned())
                .unwrap_or_default();
            (file, extension)
        }
    };

    if task.cancel.is_cancelled() {
        return TaskEnd::Cancelled;
    }

    // ── Финализация имени ──
    //
    // Ровно один вызов, и он же переименование: занять имя и переименовать
    // внутри одной операции — требование TL-40, между ними не должно быть
    // ни строки нашего кода.
    let (ready_file, extension) = ready;
    match finalize_in_dir(destination, &ready_file, &work.stem, &extension) {
        Ok(file_name) => TaskEnd::Done { file_name },
        Err(error) => {
            eprintln!("download: не удалось положить готовый файл в папку назначения: {error}");
            TaskEnd::Failed(DownloadFailure::DestinationUnavailable {
                reason: error.to_string(),
                details: no_details(),
            })
        }
    }
}

/// Путь файла потока, если он известен.
fn stream_file(work: &TaskWork, stream: DownloadStream) -> Option<PathBuf> {
    work.jobs
        .iter()
        .find(|job| job.stream == stream)
        .and_then(|job| job.file.clone())
}

/// Замороженный процент из состояния паузы — чтобы не доставать его из
/// агрегатора вторым способом.
fn frozen_percent(state: &DownloadingState) -> Option<DownloadPercent> {
    match state {
        DownloadingState::WaitingRetry { percent, .. } => *percent,
        DownloadingState::Running { percent, .. } => *percent,
    }
}

fn no_details() -> DownloadErrorDetails {
    DownloadErrorDetails {
        stderr_tail: None,
        exit_code: None,
    }
}

/// Проверяет папку назначения до всякого запуска.
///
/// # Где ловится «папка назначения недоступна» (решение реализации)
///
/// Дизайн оставил момент обнаружения на усмотрение исполнителя. Выбрано
/// **раздельно**, по природе двух разных бед:
///
/// - **папки нет** — проверкой здесь, до запуска процесса. Дёшево,
///   достоверно (существование каталога — не гонка того же рода, что
///   права) и избавляет пользователя от трёхсекундного «Подготовка» перед
///   отказом, причина которого известна сразу;
/// - **нет прав на запись** — по факту, из ошибки того, кто писал.
///   Пробное создание файла было бы гаданием дважды: права на запись
///   каталога не гарантируют записи (квота, ACL, том только для чтения),
///   а сам пробный файл пришлось бы за собой убирать — и он остался бы
///   мусором ровно в том случае, когда убирать некому. Настоящих
///   писателей двое, и оба уже отвечают за свою ошибку: yt-dlp
///   (`classify_attempt` относит «Permission denied» к
///   `destinationUnavailable` по снятой живьём фикстуре
///   `destination-read-only`) и финализация имени (её `io::Error` тем же
///   классом приезжает выше).
///
/// Класс один и тот же, панель одна и та же — расходится только момент,
/// и расходится он в пользу пользователя.
fn ensure_destination(destination: &Path) -> Result<(), DownloadFailure> {
    match std::fs::metadata(destination) {
        Ok(meta) if meta.is_dir() => Ok(()),
        Ok(_) => Err(DownloadFailure::DestinationUnavailable {
            reason: format!("{} — не папка", destination.display()),
            details: no_details(),
        }),
        Err(error) => Err(DownloadFailure::DestinationUnavailable {
            reason: format!("{}: {error}", destination.display()),
            details: no_details(),
        }),
    }
}

// ──────────────────────── Один поток ────────────────────────

/// Чем кончился запуск одного потока.
enum StreamRun {
    Completed,
    Interrupted(DownloadErrorDetails),
    Failed(DownloadFailure),
    Cancelled,
}

/// Запускает yt-dlp на один поток и ведёт его до конца процесса.
///
/// Здесь же живёт сторож продвижения: срок, до которого обязана прийти
/// следующая строка, пересчитывается **на каждой строке** и уходит в
/// запуск, который по нему и убивает процесс. До первой строки прогресса
/// срок держит [`FETCH_SILENCE_TIMEOUT`] («Подготовка»), после — политика
/// повторов ([`RetryPolicy::stall_deadline`], С-8).
#[allow(clippy::too_many_arguments)]
async fn download_stream(
    task: &Arc<DownloadTask>,
    work: &mut TaskWork,
    index: usize,
    policy: &mut RetryPolicy,
    launcher: &dyn DownloadLauncher,
    emitter: &mut Emitter<'_>,
    destination_arg: &str,
) -> StreamRun {
    let format_id = work.jobs[index].format_id.clone();
    let template = output_template(&work.download_stem);
    let args = download_args(&format_id, destination_arg, &template, &task.request.url);

    let handle = Arc::new(RunHandle::new());
    task.set_child(Some(Arc::clone(&handle)));
    if task.cancel.is_cancelled() {
        handle.cancel().await;
    }

    eprintln!(
        "download: запуск yt-dlp для потока {format_id}: {}",
        args.join(" ")
    );

    let mut destination_file: Option<PathBuf> = None;
    let mut already_downloaded = false;
    // Видел ли этот запуск хоть одну строку прогресса. От него зависит,
    // какой из двух сторожей держит срок, и он же решает, чем стал
    // истёкший срок: зависшей подготовкой или зависшим потоком.
    let mut saw_progress = false;

    let outcome = {
        let mut on_line = |line: &str| -> Option<Instant> {
            let now = monotonic_now();

            match crate::download::progress::parse_line(line) {
                StdoutLine::Progress(sample) => {
                    saw_progress = true;
                    match work.aggregator.apply(&sample) {
                        SampleOutcome::Applied { .. } => {
                            policy.observe(work.aggregator.received_bytes(), now);
                            emitter.emit(DownloadProgress::Downloading(
                                work.aggregator.running(Some(policy.attempt())),
                            ));
                        }
                        SampleOutcome::UnknownFormat => {
                            // yt-dlp качает не тот формат, который заказан.
                            // Строка не идёт ни в процент, ни в сторож —
                            // но и убивать по ней живой процесс не за что:
                            // цена ошибки несимметрична (пропавший процент
                            // против оборванной здоровой загрузки),
                            // поэтому срок продлевается по факту вывода.
                            eprintln!(
                                "download: строка прогресса формата «{}» не относится ни к \
                                 одному потоку задачи",
                                sample.format_id
                            );
                            return Some(now + FETCH_SILENCE_TIMEOUT);
                        }
                    }
                }
                StdoutLine::MalformedProgress(line) => {
                    // Маркер наш, а форма не читается: yt-dlp сменил вывод
                    // полей шаблона. Проглотить молча значило бы показывать
                    // замерший процент вместо честного отказа, поэтому
                    // строка идёт в лог целиком, а решение принимает
                    // сторож — продвижения по ней нет.
                    eprintln!("download: строка прогресса не разобрана: {line}");
                }
                StdoutLine::Destination { path } => {
                    destination_file = Some(PathBuf::from(path));
                }
                StdoutLine::AlreadyDownloaded { path } => {
                    // Идентификатор формата берётся не из строки, а из
                    // запуска: процесс качает ровно один формат, и
                    // сопоставлять путь с чем бы то ни было не нужно.
                    already_downloaded = true;
                    destination_file = Some(PathBuf::from(path));
                }
                StdoutLine::Resuming { byte_offset } => {
                    eprintln!("download: поток {format_id} продолжается с байта {byte_offset}");
                }
                StdoutLine::Other => {}
            }

            if saw_progress {
                policy.stall_deadline()
            } else {
                Some(now + FETCH_SILENCE_TIMEOUT)
            }
        };

        launcher
            .launch(
                &args,
                &handle,
                monotonic_now() + FETCH_SILENCE_TIMEOUT,
                &mut on_line,
            )
            .await
    };

    task.set_child(None);
    if let Some(file) = destination_file {
        work.jobs[index].file = Some(file);
    }

    // Отмена отсекается раньше цикла повторов и раньше классификации:
    // убитый нами процесс возвращает ровно то же, что процесс,
    // оборвавшийся сам, и не отсеки её здесь — отмена ушла бы в повторы.
    if task.cancel.is_cancelled() || handle.was_cancelled() {
        return StreamRun::Cancelled;
    }

    let run = match outcome {
        Ok(run) => run,
        Err(error) => {
            // Процесса не случилось вовсе: yt-dlp пропал из каталога
            // данных, нет прав на запуск, битый файл. Класс — честный
            // catch-all девятки.
            eprintln!("download: yt-dlp не запустился: {error}");
            return StreamRun::Failed(DownloadFailure::YtDlpFailure {
                reason: YtDlpFailureReason::Generic,
                details: no_details(),
            });
        }
    };

    if run.deadline_expired {
        let details = DownloadErrorDetails {
            stderr_tail: stderr_tail(&run.stderr),
            // Убитый нами процесс своего кода завершения не оставил.
            exit_code: None,
        };
        return if saw_progress {
            // С-8: поток замер, явного обрыва нет. Попытка признаётся
            // неудавшейся и уходит в тот же цикл повторов, что и обрыв, —
            // отдельного «поток завис» пользователю не показывается.
            eprintln!("download: поток {format_id} замер — попытка снята сторожем продвижения");
            StreamRun::Interrupted(details)
        } else {
            // yt-dlp не сказал ничего за весь отпущенный срок. Мёртвая
            // сеть так себя не ведёт (см. doc [`FETCH_SILENCE_TIMEOUT`]),
            // значит завис сам процесс.
            eprintln!(
                "download: yt-dlp молчал {FETCH_SILENCE_TIMEOUT_SECS} с на подготовке — снят"
            );
            StreamRun::Failed(DownloadFailure::YtDlpFailure {
                reason: YtDlpFailureReason::Generic,
                details,
            })
        };
    }

    match classify_attempt(&AttemptOutcome {
        exit_code: run.exit_code,
        stderr: &run.stderr,
    }) {
        AttemptVerdict::Completed => {
            if already_downloaded {
                eprintln!("download: поток {format_id} уже был скачан целиком");
            }
            StreamRun::Completed
        }
        AttemptVerdict::Interrupted { details } => StreamRun::Interrupted(details),
        AttemptVerdict::Failed(failure) => StreamRun::Failed(failure),
    }
}

// ──────────────────────── Пауза перед повтором ────────────────────────

/// Выдерживает паузу перед следующей попыткой, показывая обратный отсчёт.
///
/// `false` — задачу отменили во время паузы. Ожидание прерывается
/// побудкой, а не истечением тика: «Отменить» в паузе обязано отвечать
/// секундами (Н-3), а пауза длится до минуты.
async fn wait_before_retry(
    task: &Arc<DownloadTask>,
    emitter: &mut Emitter<'_>,
    attempt: crate::types::DownloadAttempt,
    delay: Duration,
    percent: Option<DownloadPercent>,
) -> bool {
    let delay_secs = delay.as_secs();
    eprintln!(
        "download: попытка {} из {} через {delay_secs} с",
        attempt.number, attempt.total
    );

    // Момент отсчёта берётся у **того же** таймера, который потом спит:
    // разойдись они — отсчёт на экране шёл бы по одним часам, а сон по
    // другим. Побочная польза: набор тестов вправе сдвинуть эти часы и не
    // ждать полторы минуты пауз по-настоящему.
    let deadline = tokio::time::Instant::now() + delay;
    loop {
        let remaining = deadline.saturating_duration_since(tokio::time::Instant::now());
        emitter.emit(DownloadProgress::Downloading(
            DownloadingState::WaitingRetry {
                percent,
                attempt,
                delay_secs,
                // Округление вверх: «через 0 с…» на экране, за которым
                // ещё что-то происходит, — та же маленькая ложь, что
                // застывшая скорость.
                remaining_secs: remaining.as_millis().div_ceil(1_000) as u64,
            },
        ));

        if remaining.is_zero() {
            return true;
        }

        let tick = remaining.min(RETRY_COUNTDOWN_TICK);
        tokio::select! {
            () = task.cancel.cancelled() => return false,
            () = tokio::time::sleep(tick) => {}
        }
    }
}

// ──────────────────────────── Подчистка ────────────────────────────

/// Что делать с частично скачанным на терминальном переходе.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Cleanup {
    /// Удалить всё, что задача оставила в папке назначения.
    Remove,
    /// Оставить как есть: повтор продолжит с места.
    Keep,
}

impl Cleanup {
    /// Судьба частичного по классу отказа — колонка «Частичное на диске»
    /// таблицы Ф-10.
    ///
    /// Удаляется только там, где докачивать нечего или нечем: формат
    /// больше не отдаётся, ролика нет, нужен вход, регион. Всё остальное
    /// сохраняется — включая `ytDlpFailure`, про который неизвестно,
    /// поможет ли повтор: удалять вслепую опаснее.
    fn for_failure(kind: DownloadErrorKind) -> Self {
        match kind {
            DownloadErrorKind::StaleFormat
            | DownloadErrorKind::VideoUnavailable
            | DownloadErrorKind::SignInRequired
            | DownloadErrorKind::RegionBlocked => Self::Remove,
            DownloadErrorKind::ConnectionLost
            | DownloadErrorKind::DiskFull
            | DownloadErrorKind::MergeFailed
            | DownloadErrorKind::DestinationUnavailable
            | DownloadErrorKind::YtDlpFailure => Self::Keep,
        }
    }

    /// Выполняет решение и отчитывается о том, **что получилось**, а не о
    /// том, что задумывалось.
    ///
    /// Разница видна на классах, всплывающих ещё в подготовке: удалять там
    /// нечего, и сказать пользователю «данные удалены» было бы неправдой —
    /// поэтому пустая папка даёт [`PartialData::NothingCreated`] при
    /// обоих решениях.
    fn apply(self, destination: &Path, work: &TaskWork) -> PartialData {
        let prefixes = prefixes_of(work);

        match self {
            Self::Remove => {
                let removed = remove_by_prefix(destination, &prefixes);
                if removed == 0 {
                    PartialData::NothingCreated
                } else {
                    PartialData::Removed
                }
            }
            Self::Keep => {
                if exists_by_prefix(destination, &prefixes) {
                    PartialData::Kept
                } else {
                    PartialData::NothingCreated
                }
            }
        }
    }
}

/// Все префиксы, под которыми задача могла оставить файлы.
fn prefixes_of(work: &TaskWork) -> Vec<String> {
    let mut prefixes: Vec<String> = work
        .jobs
        .iter()
        .map(|job| stream_prefix(&work.download_stem, &job.format_id))
        .collect();
    prefixes.push(merge_prefix(&work.stem));
    prefixes
}

/// Удаляет из папки всё, что начинается с одного из префиксов, и
/// возвращает число удалённого.
///
/// Обходом каталога, а не перечислением известных путей: yt-dlp
/// дописывает к имени `.part`, `.ytdl` и хвосты фрагментов, и держать их
/// список у себя значило бы отставать от него на каждую его правку. Зато
/// префикс задаётся нами целиком и содержит название ролика,
/// идентификатор формата и точку — совпасть с чужим файлом ему нечем.
fn remove_by_prefix(destination: &Path, prefixes: &[String]) -> usize {
    let mut removed = 0;

    for path in entries_by_prefix(destination, prefixes) {
        match std::fs::remove_file(&path) {
            Ok(()) => {
                removed += 1;
                eprintln!("download: удалён частичный файл {}", path.display());
            }
            // Файл мог исчезнуть сам (yt-dlp переименовал `.part` ровно
            // между обходом и удалением) — это не отказ подчистки.
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Err(error) => {
                eprintln!("download: не удалось удалить {}: {error}", path.display());
            }
        }
    }

    removed
}

fn exists_by_prefix(destination: &Path, prefixes: &[String]) -> bool {
    !entries_by_prefix(destination, prefixes).is_empty()
}

fn entries_by_prefix(destination: &Path, prefixes: &[String]) -> Vec<PathBuf> {
    let Ok(entries) = std::fs::read_dir(destination) else {
        // Папка исчезла или недоступна: удалять и нечего, и нечем.
        return Vec::new();
    };

    entries
        .flatten()
        .filter(|entry| {
            let name = entry.file_name();
            let name = name.to_string_lossy();
            prefixes
                .iter()
                .any(|prefix| name.starts_with(prefix.as_str()))
        })
        .map(|entry| entry.path())
        .collect()
}

