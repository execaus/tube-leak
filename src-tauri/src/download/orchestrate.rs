//! Оркестрация задачи скачивания (Ф-1, Ф-3, Ф-4, Ф-8) — TL-44.
//!
//! Сходящийся узел области core. Своей логики скачивания здесь нет —
//! есть автомат фаз и порядок вызовов уже готовых кусков: разбор строк
//! прогресса ([`progress`]), агрегация двух потоков в один процент
//! ([`aggregate`]), классификация исхода попытки ([`classify`]), политика
//! повторов ([`retry`]), склейка ([`merge`]) и финализация имени
//! ([`filename`]). Плюс то, чего не делает ни один из них: запуск
//! процессов, эмиссия событий, отмена с подчисткой по фазам и решение,
//! что осталось на диске.
//!
//! [`progress`]: crate::download::progress
//! [`aggregate`]: crate::download::aggregate
//! [`classify`]: crate::download::classify
//! [`retry`]: crate::download::retry
//! [`merge`]: crate::download::merge
//! [`filename`]: crate::download::filename
//!
//! # Один процесс на попытку, потоки — через запятую (TL-48)
//!
//! Оператор сложения в `-f` (`133+139`) включает **чужую** склейку: yt-dlp
//! сам зовёт ffmpeg, если найдёт его в `PATH`. Снятая живьём фикстура
//! `video-and-audio.json` этим и кончается: `[Merger] Merging formats
//! into "./a.mp4"`, а следом `Deleting original file …`. Решение дизайна
//! по Ф-9 требует, чтобы склейку вёл наш ffmpeg, запущенный ядром.
//!
//! Запятая — не то же самое, что плюс: `-f 133,139` — документированный
//! селектор «скачать оба формата по отдельности». Один процесс, **одно
//! извлечение адреса**, две загрузки, каждая под своим именем. До TL-48
//! здесь стоял процесс на каждый поток, то есть два извлечения и вдвое
//! больше обращений к YouTube на одну загрузку — против инварианта «вести
//! себя как обычный пользователь».
//!
//! Что запятая не включает склейку, измерено на вложенном бинарнике
//! (macOS, пин 2026.08.19, 2026-09-13) без обращения к YouTube: метаданные
//! ролика — снятая живьём фикстура разбора `4k-full-ladder.json`, адреса
//! форматов — мёртвый порт на `127.0.0.1`, ffmpeg при этом лежит в `PATH`.
//! Склейку yt-dlp планирует тогда и только тогда, когда у результата
//! выбора есть `requested_formats`:
//!
//! | `-f` | Что отдал выбор (`--simulate --print`) |
//! |---|---|
//! | `133+139` | один результат, `requested_formats=['133', '139']` — склейка |
//! | `133,139` | два результата, у каждого `requested_formats=[]` |
//! | `160+251` | один результат, `requested_formats=['160', '251']` — склейка |
//! | `160,251` | два результата, у каждого `requested_formats=[]` |
//! | `140`, `133` | один результат, `requested_formats=[]` |
//!
//! Тот же замер показал второе, на чём стоит атрибуция ниже: **отказ
//! первого формата не останавливает второй**. У `-f 133,139` оба формата
//! получили свой `ERROR`, код выхода — 1. Значит один запуск может забрать
//! один поток и не забрать другой, и «поток готов» решается по каждому
//! потоку отдельно, а не по коду выхода процесса.
//!
//! # К какому потоку относится строка
//!
//! Процесс один, потоков два — факт запуска больше ничего не говорит о
//! том, чей это вывод. Поэтому:
//!
//! - **строка прогресса** — по идентификатору формата, который несёт сам
//!   шаблон ([`PROGRESS_TEMPLATE`], поле `info.format_id`); это делала
//!   агрегация и раньше;
//! - **`Destination` и `has already been downloaded`** — по **имени
//!   файла** ([`is_file_of_stream`]): имя строим мы (`-o`), и в нём стоят
//!   основа, `.f`, идентификатор формата, точка и расширение без точек.
//!   Путь, не совпавший ни с одним заказанным потоком, не приписывается
//!   никому — белый список, а не «первому потоку без файла».
//!
//! Поток считается забранным ([`settle_streams`]), когда известен его
//! файл **и** есть доказательство конца: нулевой код выхода всего запуска,
//! строка `finished` этого формата или `has already been downloaded` с его
//! именем. Повтор (автоматический и ручной) заказывает только незабранные
//! потоки, а повтор после неудачной склейки не запускает yt-dlp вовсе.
//! Отметка «забран» сверяется с диском на старте задачи и перед склейкой
//! ([`forget_streams_missing_on_disk`], TL-105): поток, файла которого нет,
//! заказывается снова.
//!
//! Строка `[info] … Downloading N format(s): a, b` — перечень форматов,
//! которые yt-dlp **выбрал**. Заказанный формат, которого нет в метаданных,
//! из него молча выпадает, а процесс выходит с кодом 0 и пустым stderr
//! (фикстура `single-launch/one-format-missing.json`). Такой поток — класс
//! `staleFormat`, тот же, что давал до TL-48 отдельный запуск на этот
//! формат ([`missing_from_selection`]). Сторож держится на тексте чужой
//! строки: если её не было, а поток из нескольких заказанных остался без
//! файла, исход — `ytDlpFailure`, а не «склейка не удалась» с текстом
//! «оба потока скачались» ([`unlisted_selection`], TL-97).
//!
//! Сторож продвижения на стыке потоков одного запуска заводится заново на
//! первой строке, назвавшей файл очередного потока (`Destination` или
//! `has already been downloaded`), — см. doc
//! [`RetryPolicy::stream_started`].
//!
//! # Что видит диск, пока задача идёт
//!
//! Потоки качаются **в папку назначения**, под именами вида
//! `<id ролика>.<название>.f<формат>.<расширение>` (yt-dlp дописывает к ним
//! `.part`, пока файл не дописан). Требование Ф-8 «под финальным именем ничего не
//! появляется до полной готовности» выполняется этим по построению:
//! финальное имя — `<основа>.<расширение контейнера>`, и совпасть с ним
//! рабочее не может.
//!
//! Служебного каталога нет намеренно. Он дал бы вторую точку подчистки и
//! разъехался бы с обещанием Р-2: «вставьте ту же ссылку ещё раз, и
//! загрузка продолжится с места» держится ровно на том, что путь
//! частичного файла выводится из запроса (название и ссылка) и папки
//! назначения, а не из состояния, которого приложение между запусками не
//! помнит.
//!
//! # Настройки снимаются на старте задачи (TL-89, Р-4 эпика E5)
//!
//! Папка назначения, шаблон имени и предел попыток читаются **один раз** —
//! первой строкой [`run_task`], из живого хранилища настроек ([`TaskEnv`]),
//! а не при постановке и не при старте очереди. Отсюда два следствия Ф-14:
//! ожидающая задача получает значения, действующие к её собственному
//! старту, а идущая держит свои до терминального исхода, включая
//! автоматические повторы. «Повторить» после отказа — новый вызов
//! [`run_task`], то есть новый старт с текущими значениями.
//!
//! Если на новом старте **папка** не та, что на прошлом, всё, что задача
//! знала о забранных потоках, забывается: они лежат в прежней папке, и
//! докачивать их некуда. Задача качается с нуля, прежние частичные файлы
//! остаются, где лежали, — цена, названная в Р-4 и в тексте экрана настроек.
//! Смена шаблона докачке не мешает (решение ведущего по ревью TL-89, B1).
//!
//! # Две основы имени: рабочая и финальная (ревью TL-89, B1)
//!
//! **Рабочая** — основа частичных файлов потоков и рабочего файла склейки —
//! [`download_stem`]: `<id ролика>.<название>`, где название — основа E3
//! `sanitized_stem(название, video_id_of(ссылка))` под белым списком
//! шаблона, а id — [`PartialId`] (TL-104). Она выводится из запроса задачи и
//! **не зависит ни от шаблона, ни от даты**: строится один раз в
//! [`build_task`] и живёт столько же, сколько задача.
//!
//! Id в рабочей основе нужен потому, что одного названия мало: два разных
//! ролика с одинаковым названием в одной папке давали одни и те же рабочие
//! имена, и частичные файлы, сохранённые отказом или паузой одной задачи,
//! другая докачивала, принимала за свои и удаляла подчисткой. Id берётся
//! только из белого списка форм ссылки, иначе — хеш ссылки; сырой строки
//! из ссылки в имени нет.
//! На этом стоит докачка через полночь по UTC и через перезапуск: до B1 в
//! рабочую основу входил `{date}`, и старт в другой день качал потоки
//! заново, а вчерашние частичные файлы оставались в папке навсегда —
//! подчистка их больше не узнавала.
//!
//! **Финальная** — имя готового файла — строит только `Settings::file_stem`
//! (шаблон целиком уходит в санитизацию E3) перед финализацией. `{id}` —
//! [`video_id_of`], тот же id, что E3 брал для запасного имени, а не
//! канонический id очереди (решение ведущего по ревью TL-86). `{date}` —
//! дата **завершения** по UTC (Ф-12).
//!
//! Раз основы независимы, финальное имя может начинаться с префикса
//! частичного файла: шаблон `{id}.{title}.f140.{id}` даёт
//! `<id>.Название.f140.<id>.m4a` под префиксом потока `<id>.Название.f140.`,
//! а `{id}.{title}.f139` — готовый файл одной задачи под префиксом потока
//! другой задачи того же ролика. Поэтому подчистка удаляет не всё под
//! префиксом, а только точные рабочие имена своей задачи — белый список из
//! кода и замера yt-dlp ([`is_working_name_of`], TL-106). Свой готовый файл
//! на `Done` она ещё и щадит по имени ([`Cleanup::apply_sparing`]) — на
//! случай, когда он занял рабочее имя пропавшего потока.
//!
//! # Запись в историю (TL-89, Р-1 эпика E5)
//!
//! Пишется только `Done`, ровно одна запись, через managed-состояние истории
//! (`commands::history::HistoryState`) — своего открытия хранилища здесь нет.
//! Пишется **до** события `done` и до возврата очереди: к моменту, когда о
//! готовой задаче узнает окно, запись уже в базе (Ф-3). Отказ записи исход не
//! меняет: Done остаётся Done, экран истории получает пометку
//! `lastWriteFailed`. `Failed` и `Cancelled` в историю не пишутся.
//!
//! `folderDisplay` у `Done` строит `storage::history::folder_display` —
//! та же функция, что у записи на экране истории, на том же значении папки,
//! что уходит в запись, и с тем же резолвом системной «Загрузок». Без
//! канонизации ни с одной стороны.
//!
//! # Три места, где задача может кончиться
//!
//! `Done` — файл под финальным именем в папке назначения. `Failed` — один
//! из девяти классов Ф-10. `Cancelled` — пользователь. Больше выходов у
//! автомата нет: любая ветка ведёт в один из трёх, и каждая перед этим
//! решает судьбу частичных файлов (см. [`Cleanup`]).

