/// Сколько секунд yt-dlp может **молчать в stdout** на фазе «Подготовка»,
/// прежде чем его снимут (таблица «Числа» дизайна: 20 с).
///
/// Ключевое слово — «молчать»: срок считается не от последней строки
/// **прогресса**, а от последней строки вообще. Разница между двумя
/// прочтениями решает судьбу критерия К-7, и выбрана она замером, а не
/// вкусом.
///
/// # Замер (macOS 15, пин yt-dlp 2026.08.19, 2026-08-27)
///
/// Здоровая подготовка — от `spawn` до первой строки прогресса:
///
/// | Что | Время |
/// |---|---|
/// | `[youtube] Extracting URL` | 0,46–0,48 с |
/// | `Downloading visionos player API JSON` | 1,9 с |
/// | `[info] Downloading 1 format(s)` | 2,8 с |
/// | первая строка прогресса | **3,33–3,34 с** |
///
/// То есть запас до порога — шестикратный.
///
/// Мёртвая сеть (транспорт принимает соединение и молчит, ни RST, ни
/// FIN — то же, что видит клиент при выключенном Wi-Fi):
///
/// | Время | Что в stdout |
/// |---|---|
/// | 0,46 с | `Extracting URL`, `Downloading webpage` |
/// | 10,5 с | `Downloading webpage` (внутренний повтор 1/3) |
/// | 20,5 с | то же (2/3) |
/// | 30,5 с | то же (3/3) |
/// | 40,5 с | `Downloading initial data API JSON` |
/// | …каждые 10 с | то же |
/// | **80,7 с** | код 1, в stderr `Read timed out` |
///
/// Отсюда весь смысл прочтения «молчит». **Сеть, умершая на подготовке,
/// печатает строку каждые 10 секунд** — то есть до порога в 20 с не
/// доходит никогда и сроком не снимается. Она доходит до честного отказа
/// самого yt-dlp с текстом `Read timed out`, который классификация
/// относит к [`AttemptVerdict::Interrupted`] (маркер живёт в
/// `DOWNLOAD_TRANSPORT_MARKERS`), — то есть уходит в цикл повторов и
/// кончается классом «соединение потеряно», как и требует К-7.
///
/// Считай мы срок по строкам прогресса — тот же случай снимался бы на
/// 20-й секунде и приезжал бы пользователю как «Не удалось скачать
/// ролик», а не как «Соединение потеряно», и цикл повторов С-6 не
/// начинался бы вовсе. Ровно этот дефект и разводит здесь одно слово.
///
/// Что остаётся за порогом после такого прочтения: yt-dlp, не сказавший
/// **ничего** за 20 секунд. Здоровая подготовка так себя не ведёт (самый
/// длинный измеренный разрыв — 1,9 с), мёртвая сеть тоже (10 с). Значит
/// сработавший срок означает зависший процесс, и класс у него честный —
/// `ytDlpFailure` («Не удалось скачать ролик. Попробуйте ещё раз»), как и
/// предписывает doc [`crate::types::DownloadErrorKind`].
///
/// Число подлежит калибровке на bundle вместе с остальными числами эпика;
/// замеры выше сняты прямым запуском вложенного бинарника, а не через
/// смонтированный `.app` (см. отчёт задачи).
pub const FETCH_SILENCE_TIMEOUT_SECS: u64 = 20;

/// [`FETCH_SILENCE_TIMEOUT_SECS`] как [`Duration`].
const FETCH_SILENCE_TIMEOUT: Duration = Duration::from_secs(FETCH_SILENCE_TIMEOUT_SECS);

/// Минимальный промежуток между событиями `download://progress` одной
/// задачи (таблица «Числа» дизайна: не чаще раза в 300 мс).
///
/// Троттлинг здесь — **второй** пояс, а не первый. Первый стоит у
/// источника: запуск несёт `--progress-delta`
/// ([`PROGRESS_DELTA_ARG`]) с тем же значением, потому что поток через
/// манифест печатает 15,7 строк в секунду и резать его дешевле до
/// разбора, чем после (замер TL-41).
///
/// Зачем тогда второй. Во-первых, `--progress-delta` режет строки
/// **одного потока**, а у задачи их два, и на стыке видео → звук две
/// строки приходят вплотную. Во-вторых, событие эмитится не только на
/// строку прогресса.
///
/// Терминальные переходы и смена фазы троттлингом не глотаются никогда —
/// см. [`Emitter::emit`].
const PROGRESS_THROTTLE: Duration = Duration::from_millis(300);

/// Как часто обновляется обратный отсчёт паузы перед повтором.
///
/// Секунда — шаг самого числа на экране («через 8 с…»): чаще значило бы
/// слать события, ничего не меняющие, реже — показывать число, которое
/// отстаёт от правды.
const RETRY_COUNTDOWN_TICK: Duration = Duration::from_secs(1);

/// Предел длины идентификатора формата, который ядро согласно передать
/// процессу (Ф-1: непроверенного ввода в аргументах не бывает).
///
/// Идентификаторы yt-dlp короткие (`137`, `140-drc`, `hls-1080`); предел
/// нужен не им, а бюджету имени файла: идентификатор входит в имя
/// частичного файла ([`download_stem_budget`]), и без предела название
/// ролика теряло бы длину из-за чужой строки.
const MAX_FORMAT_ID_BYTES: usize = 16;

// ─────────────────────── Аргументы запуска ───────────────────────

/// Значение `--progress-delta`.
///
/// То же, что [`PROGRESS_THROTTLE`], но строкой: аргумент процесса —
/// текст, и превращать число в текст по месту значило бы завести способ
/// их разойтись. Сторож — тест `the_source_side_throttle_matches_ours`.
const PROGRESS_DELTA_ARG: &str = "0.3";

/// Значение `--socket-timeout`.
///
/// То же отношение к [`crate::download::retry::SOCKET_TIMEOUT_SECS`], что у
/// [`PROGRESS_DELTA_ARG`] к [`PROGRESS_THROTTLE`], и тот же сторож
/// (`the_socket_timeout_argument_matches_the_policy`). Почему именно
/// десять и что это меняет — в doc самой константы: число разводит по
/// времени наш сторож «нет продвижения» и внутренние повторы yt-dlp.
const SOCKET_TIMEOUT_ARG: &str = "10";

/// Аргументы запуска скачивания, кроме формата, путей и ссылки.
///
/// Каждый обязателен, и ни один не выбран на вкус:
///
/// - `--no-playlist` — `watch?v=…&list=…` скачивается как **ролик**, а не
///   как плейлист (то же решение и та же причина, что в
///   [`crate::probe`]).
/// - `--newline` — без него полоса прогресса пишется возвратом каретки в
///   одну строку, и построчное чтение не увидит ни одной законченной
///   строки до конца потока.
/// - `--progress-template` со значением [`PROGRESS_TEMPLATE`] — разбор
///   читает **свой** шаблон; человекочитаемую полосу шаблон заменяет
///   собой. Почему по ней нельзя считать знаменатель агрегации —
///   в шапке [`crate::download::progress`].
/// - `--progress-delta` — режет частоту у источника (см.
///   [`PROGRESS_THROTTLE`]).
/// - `--socket-timeout` — разводит сторож «нет продвижения» и внутренние
///   повторы yt-dlp (см. [`crate::download::retry::SOCKET_TIMEOUT_SECS`]).
///
/// Чего здесь нет намеренно: `-N`/`--concurrent-fragments` (инвариант
/// «число соединений дефолтное»), `--proxy` (системный прокси yt-dlp
/// уважает сам), `--retries`/`--fragment-retries` (у yt-dlp свои
/// умолчания, а наш цикл повторов стоит поверх, а не вместо),
/// `--ignore-config` (то же решение, что в разборе: поведение «как у
/// обычного yt-dlp на машине пользователя» ближе к инварианту эпика, чем
/// герметичность запуска).
const DOWNLOAD_ARGS: [&str; 8] = [
    "--no-playlist",
    "--newline",
    "--progress-template",
    PROGRESS_TEMPLATE,
    "--progress-delta",
    PROGRESS_DELTA_ARG,
    "--socket-timeout",
    SOCKET_TIMEOUT_ARG,
];

/// Полный argv одного потока.
///
/// Отдельная функция, а не строки внутри запуска, потому что её проверяют
/// тесты Ф-1: ссылка обязана стоять последней и после `--`, формат —
/// значением `-f`, а папка назначения — значением `-P` с явным префиксом
/// `home:`.
///
/// Про `home:`. `-P` разбирает своё значение как `[ТИП:]ПУТЬ`, отрезая
/// **первое** двоеточие; без явного префикса папка, в пути которой есть
/// двоеточие, была бы прочитана как неизвестный тип. Проверено живьём:
/// с префиксом каталог `dir with: colon` принимается как есть.
fn download_args<'a>(
    format_id: &'a str,
    destination: &'a str,
    output_template: &'a str,
    url: &'a str,
) -> Vec<&'a str> {
    let mut args = DOWNLOAD_ARGS.to_vec();
    args.push("-f");
    args.push(format_id);
    args.push("-P");
    args.push(destination);
    args.push("-o");
    args.push(output_template);
    // Разделитель аргументов (Ф-1, второй пояс поверх [`validate_url`]):
    // всё после него — позиционный аргумент, что бы в нём ни стояло.
    args.push("--");
    args.push(url);
    args
}

/// Значение `-P`: папка назначения с префиксом типа.
fn destination_arg(dir: &Path) -> Option<String> {
    dir.to_str().map(|dir| format!("home:{dir}"))
}

/// Значение `-o` для одного потока: `<основа>.f%(format_id)s.%(ext)s`.
///
/// Расширение отдаёт yt-dlp (`%(ext)s`), а не мы: контейнер потока
/// зависит от кодека, и угадывать его до скачивания незачем.
/// Идентификатор формата в имени — не украшение: без него видео и звук
/// одного семейства (VP9 + Opus, оба `.webm`) писались бы в один файл.
///
/// Экранирования здесь нет и не должно быть: основа приходит из
/// [`download_stem`], который пропускает только заведомо инертные
/// символы. Почему именно так, а не списком опасных, — там же.
fn output_template(download_stem: &str) -> String {
    format!("{download_stem}.f%(format_id)s.%(ext)s")
}

/// Префикс всех файлов одного потока в папке назначения.
///
/// По нему и подчищается, и проверяется наличие частичного: под этим
/// префиксом лежат и сам файл (`.mp4`), и незаконченный (`.mp4.part`), и
/// служебные хвосты фрагментного протокола (`.ytdl`, `.part-Frag17`).
///
/// Точка после идентификатора формата обязательна: без неё префикс
/// `Название.f` совпал бы с посторонним `Название.flv` — то есть
/// подчистка удаляла бы чужой файл. С ней совпадение требует названия,
/// идентификатора формата и точки подряд.
fn stream_prefix(download_stem: &str, format_id: &str) -> String {
    format!("{download_stem}.f{format_id}.")
}

/// Префикс рабочего файла склейки — см. [`crate::download::merge`].
fn merge_prefix(stem: &str) -> String {
    format!("{stem}.tl-merging.")
}

