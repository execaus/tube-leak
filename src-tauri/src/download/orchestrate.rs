/// Аргументы запуска скачивания, кроме формата, путей и ссылки.
///
/// Каждый обязателен, и ни один не выбран на вкус:
///
/// - `--no-playlist` — `watch?v=…&list=…` скачивается как **ролик**, а не
///   как плейлист (то же решение и та же причина, что в
///   [`crate::probe`]).
/// - `--newline` — без него полоса прогресса пишется возвратом каретки в
///   одну строку, и построчное чтение не увидит ни одной законченной
///   строки до конца потока.
/// - `--progress-template` со значением [`PROGRESS_TEMPLATE`] — разбор
///   читает **свой** шаблон; человекочитаемую полосу шаблон заменяет
///   собой. Почему по ней нельзя считать знаменатель агрегации —
///   в шапке [`crate::download::progress`].
/// - `--progress-delta` — режет частоту у источника (см.
///   [`PROGRESS_THROTTLE`]).
/// - `--socket-timeout` — разводит сторож «нет продвижения» и внутренние
///   повторы yt-dlp (см. [`crate::download::retry::SOCKET_TIMEOUT_SECS`]).
///
/// Чего здесь нет намеренно: `-N`/`--concurrent-fragments` (инвариант
/// «число соединений дефолтное»), `--proxy` (системный прокси yt-dlp
/// уважает сам), `--retries`/`--fragment-retries` (у yt-dlp свои
/// умолчания, а наш цикл повторов стоит поверх, а не вместо),
/// `--ignore-config` (то же решение, что в разборе: поведение «как у
/// обычного yt-dlp на машине пользователя» ближе к инварианту эпика, чем
/// герметичность запуска).
///
/// Аргументов JS-рантайма (`--js-runtimes deno:<путь>` или
/// `--no-js-runtimes`, TL-109) здесь тоже нет: путь известен только на
/// рантайме, и ставит их вместе с окружением deno запускатель
/// ([`SidecarDownloader`]) — перед этим набором, то есть заведомо до `--`.
/// Фикстуры одного запуска сняты без рантайма; переснятие — после v0.1.
const DOWNLOAD_ARGS: [&str; 10] = [
    "--no-playlist",
    "--newline",
    "--progress-template",
    PROGRESS_TEMPLATE,
    "--progress-delta",
    PROGRESS_DELTA_ARG,
    "--socket-timeout",
    SOCKET_TIMEOUT_ARG,
    // Кодировка вывода yt-dlp, прибитая к UTF-8 (TL-130). Без неё имя
    // файла потока не читается на локали, которая не UTF-8, и это не
    // гипотеза, а замер: yt-dlp кодирует **весь** свой текст
    // `enc = encoding or out.encoding or preferredencoding()`
    // (`utils/write_string`), то есть при выводе в канал — кодировкой
    // локали. На русской Windows это cp1251, и кириллица в строке
    // `[download] Destination: …` приходит байтами, которые UTF-8 не
    // являются; чтение вывода (`String::from_utf8_lossy`) меняет их на
    // U+FFFD, имя перестаёт совпадать с нашим `-o`, поток считается
    // незабранным и склейка не начинается (#137, живая Windows).
    //
    // Почему флагом, а не окружением: `PYTHONIOENCODING` этот бинарник
    // не читает вовсе — он собран PyInstaller-ом, и замер показал, что
    // даже заведомо битое значение (`PYTHONIOENCODING=totally-bogus-
    // encoding`) не роняет запуск, а `=ascii` не меняет байтов вывода.
    // `--encoding` же меняет: с `cp1251` вывод воспроизводимо ломается,
    // с `utf-8` остаётся UTF-8 при любой локали.
    "--encoding",
    "utf-8",
];

/// Полный argv одной попытки.
///
/// Отдельная функция, а не строки внутри запуска, потому что её проверяют
/// тесты Ф-1: ссылка обязана стоять последней и после `--`, селектор
/// форматов — значением `-f` ([`format_selector`]), а папка назначения —
/// значением `-P` с явным префиксом `home:`.
///
/// Про `home:`. `-P` разбирает своё значение как `[ТИП:]ПУТЬ`, отрезая
/// **первое** двоеточие; без явного префикса папка, в пути которой есть
/// двоеточие, была бы прочитана как неизвестный тип. Проверено живьём:
/// с префиксом каталог `dir with: colon` принимается как есть.
fn download_args<'a>(
    format_selector: &'a str,
    destination: &'a str,
    output_template: &'a str,
    url: &'a str,
) -> Vec<&'a str> {
    let mut args = DOWNLOAD_ARGS.to_vec();
    args.push("-f");
    args.push(format_selector);
    args.push("-P");
    args.push(destination);
    args.push("-o");
    args.push(output_template);
    // Разделитель аргументов (Ф-1, второй пояс поверх [`validate_url`]):
    // всё после него — позиционный аргумент, что бы в нём ни стояло.
    args.push("--");
    args.push(url);
    args
}

/// Значение `-P`: папка назначения с префиксом типа.
fn destination_arg(dir: &Path) -> Option<String> {
    dir.to_str().map(|dir| format!("home:{dir}"))
}

/// Значение `-o` для одного потока: `<основа>.f%(format_id)s.%(ext)s`.
///
/// Расширение отдаёт yt-dlp (`%(ext)s`), а не мы: контейнер потока
/// зависит от кодека, и угадывать его до скачивания незачем.
/// Идентификатор формата в имени — не украшение: без него видео и звук
/// одного семейства (VP9 + Opus, оба `.webm`) писались бы в один файл.
///
/// Экранирования здесь нет и не должно быть: основа приходит из
/// [`download_stem`], который пропускает только заведомо инертные
/// символы. Почему именно так, а не списком опасных, — там же.
fn output_template(download_stem: &str) -> String {
    format!("{download_stem}.f%(format_id)s.%(ext)s")
}

/// Начало имён одного потока в папке назначения: `<основа>.f<формат>.`.
///
/// От него строятся атрибуция файла потоку ([`is_file_of_stream`]) и рабочие
/// имена подчистки ([`is_stream_working_name`]). Само по себе оно ничего не
/// разрешает удалить: под ним может лежать и чужое — готовый файл с шаблоном
/// `{id}.{title}.f139`, заметки пользователя (TL-106).
///
/// Точка после идентификатора формата обязательна: без неё начало
/// `<id>.Название.f` совпало бы с посторонним `<id>.Название.flv`. С ней
/// совпадение требует id ролика, названия, идентификатора формата и точки
/// подряд. Почему id впереди — doc [`download_stem`].
fn stream_prefix(download_stem: &str, format_id: &str) -> String {
    format!("{download_stem}.f{format_id}.")
}

/// Значение `-f` одной попытки: идентификаторы ещё не забранных потоков
/// через запятую, в порядке «видео, звук» (TL-48).
///
/// Запятая, а не плюс: плюс включает чужую склейку, запятая — нет (замер в
/// шапке модуля). Структура селектора целиком наша: каждый идентификатор
/// прошёл [`usable_format_id`], где ни запятой, ни плюса, ни косой черты
/// не бывает, — склеить из них другой оператор нечем.
fn format_selector<'a>(format_ids: impl IntoIterator<Item = &'a str>) -> String {
    format_ids.into_iter().collect::<Vec<_>>().join(",")
}

/// Принадлежит ли файл, названный yt-dlp, этому потоку (TL-48).
///
/// Имя файла потока строим мы: [`output_template`] даёт
/// `<основа>.f<формат>.<расширение>`. Значит файл потока — это ровно
/// префикс [`stream_prefix`] и за ним непустое расширение **без точек**.
/// Сравнивается только имя, не каталог: каталог yt-dlp печатает в своей
/// форме (абсолютный путь из `-P`, разделители ОС), а имя — в нашей.
///
/// Требование «расширение без точек» — не украшение, а то, что делает
/// сопоставление однозначным при любых двух идентификаторах: у потоков
/// `sb` и `sb.0` префиксы `….fsb.` и `….fsb.0.`, и без него файл
/// `….fsb.0.mhtml` принадлежал бы обоим. Заодно им отсекаются
/// `.part`, `.ytdl` и `.temp.<расширение>` — рабочие хвосты, которые
/// файлом потока не являются.
///
/// Файл потока **другого** ролика сюда не проходит ни при каком названии:
/// основа начинается с `<id>.`, а точки в id нет ([`PartialId`]).
fn is_file_of_stream(download_stem: &str, format_id: &str, path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    name.strip_prefix(stream_prefix(download_stem, format_id).as_str())
        .is_some_and(|extension| !extension.is_empty() && !extension.contains('.'))
}

// ─────────────────────── Имя частичного файла ───────────────────────

/// Бюджет длины рабочей основы (название, точка, id ролика) в байтах.
///
/// Своя величина, а не [`crate::download::filename::MAX_STEM_BYTES`], и
/// это не дубль. Финальному имени дописывают расширение, суффикс
/// коллизии и метку склейки; частичному — другое и больше: `.f` плюс
/// идентификатор формата ([`MAX_FORMAT_ID_BYTES`]), расширение и `.part`,
/// который yt-dlp дописывает сам. Возьми мы чужой бюджет — предельно
/// длинное название дало бы корректное финальное имя и слишком длинное
/// частичное, то есть отказ ровно на длинных названиях и только на них.
///
/// Рабочий файл склейки из этой же основы короче частичного:
/// `.tl-merging.webm` (16 байт) против `.f` + 16 + `.` + 8 + `.part`
/// (32 байта). Сторож обоих — `the_partial_name_of_the_longest_title_still_fits_the_file_system`.
fn download_stem_budget() -> usize {
    const NAME_MAX: usize = crate::download::filename::MAX_FILE_NAME_BYTES;
    // `.f` + идентификатор + `.` + расширение (до 8) + `.part`
    NAME_MAX - (2 + MAX_FORMAT_ID_BYTES) - 9 - 5
}

/// Бюджет названия в рабочей основе: всё, что осталось после точки и id
/// ролика предельной длины ([`MAX_PARTIAL_ID_BYTES`]).
///
/// Вычитается предел, а не длина конкретного id: иначе ссылка, для которой
/// id не распознан (запасной вариант длиннее), на предельно длинном
/// названии давала бы имя длиннее, чем та же ссылка с id.
fn download_title_budget() -> usize {
    download_stem_budget() - 1 - MAX_PARTIAL_ID_BYTES
}

/// Сколько шестнадцатеричных знаков sha256 ссылки уходит в запасной
/// вариант id ([`PartialId`]).
///
/// Шестнадцать знаков — 64 бита: случайно слипнуться две разные ссылки с
/// одинаковым названием в одной папке могут с вероятностью порядка 2⁻⁶⁴.
/// Длина нарочно не равна длине id YouTube (11): запасной вариант не
/// совпадёт ни с одним настоящим id, даже если алфавиты пересекаются.
const PARTIAL_ID_HASH_HEX: usize = 16;

/// Предел длины id ролика в рабочей основе, в байтах.
///
/// Равен длине запасного варианта: настоящий id YouTube (11) короче, а
/// длиннее запасного в основу не попадает ничего.
const MAX_PARTIAL_ID_BYTES: usize = PARTIAL_ID_HASH_HEX;

// Длина запасного варианта не равна длине id YouTube (11) и чётна (два знака
// на байт хеша) — проверяется при компиляции, а не надеждой.
const _: () = assert!(PARTIAL_ID_HASH_HEX != 11 && PARTIAL_ID_HASH_HEX % 2 == 0);

/// Id ролика в имени частичных файлов и файла склейки (TL-104).
///
/// # Зачем
///
/// Без него рабочая основа — только название, и два **разных** ролика с
/// одинаковым названием («Трейлер», «Эпизод 1», перезалив) в одной папке
/// получают одни и те же имена частичных файлов. Пока частичных не
/// остаётся, это незаметно; но отказ с сохранением (`connectionLost`,
/// `mergeFailed`) и приостановленная задача их оставляют, и следующая
/// задача другого ролика докачивала чужой `.part` (`--continue` yt-dlp),
/// принимала чужой готовый поток за свой, а её подчистка удаляла чужие
/// частичные файлы.
///
/// # Откуда берётся
///
/// Только через белый список форм ссылки —
/// [`crate::queue::video_id::canonical_video_id`] (TL-72): ровно 11 знаков
/// `[A-Za-z0-9_-]`, форма ссылки измерена настоящим yt-dlp, плейсхолдеры в
/// позиции id (`videoseries`, `live_stream`) отвергнуты. Везде, где он
/// отвечает, его ответ совпадает с [`video_id_of`] — сторож
/// `the_fallback_stem_id_agrees_with_the_canonical_id_wherever_that_one_exists`.
///
/// Проверки одной формы id (11 знаков из алфавита) здесь мало, и это урок
/// E4, а не осторожность: плейсхолдеры её проходят, и две ссылки на разные
/// плейлисты `embed/videoseries?list=…` дали бы один id.
///
/// # Запасной вариант
///
/// Ссылка, для которой белый список id не дал (чужой хост, неизмеренная
/// форма, плейсхолдер, мусор в `v=`), получает первые
/// [`PARTIAL_ID_HASH_HEX`] знаков sha256 от ссылки без окаймляющих пробелов
/// в строчной шестнадцатеричной записи. Алфавит фиксирован и целиком входит
/// в [`template_safe`]; из самой ссылки в имя не попадает ни байта.
/// Детерминизм сохранён: та же ссылка — то же имя, и докачка Р-2 работает.
/// Цена названа: одна и та же ссылка, записанная по-разному в
/// нераспознанной форме, докачивается только в той же записи.
/// Докачка чужого хоста работает только в той же записи с точностью до
/// регистра схемы и хоста. Задача, начатая до TL-81 со ссылкой в верхнем
/// регистре, после обновления скачивается заново, а её старые частичные
/// файлы остаются.
///
/// # Алфавит: точки нет
///
/// Каждый байт id проходит [`partial_id_byte`] — `[A-Za-z0-9_-]`, — и
/// точки в этом алфавите нет (проверка при компиляции). На этом стоит
/// однозначность рабочих имён между роликами ([`is_file_of_stream`],
/// [`is_working_name_of`]): рабочая основа начинается с `<id>.`, и первая
/// точка имени отделяет id целиком. Проверка стоит здесь, а не только в
/// [`crate::queue::video_id`]: гарантию подчистки
/// не должна отменять правка чужого модуля. Id, который её не прошёл бы,
/// уходит в запасной вариант, а не в имя.
struct PartialId(String);

/// Байт, допустимый в id рабочей основы ([`PartialId`]).
const fn partial_id_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'-' || byte == b'_'
}

/// Знаки запасного варианта id ([`url_digest`]).
const PARTIAL_ID_HEX: &[u8; 16] = b"0123456789abcdef";

// Точки в алфавите id нет, и запасной вариант целиком в алфавите: без этого
// префикс `<id>.` перестаёт быть однозначным (doc [`PartialId`]).
const _: () = {
    assert!(!partial_id_byte(b'.'));
    let mut index = 0;
    while index < PARTIAL_ID_HEX.len() {
        assert!(partial_id_byte(PARTIAL_ID_HEX[index]));
        index += 1;
    }
};

impl PartialId {
    /// Единственный конструктор: белый список или хеш, третьего пути нет.
    fn of_url(url: &str) -> Self {
        match canonical_video_id(url) {
            Some(id) if id.as_str().bytes().all(partial_id_byte) => Self(id.as_str().to_owned()),
            _ => Self(url_digest(url)),
        }
    }

    fn as_str(&self) -> &str {
        &self.0
    }
}

/// Первые [`PARTIAL_ID_HASH_HEX`] знаков sha256 ссылки, строчная hex-запись.
///
/// Пробелы по краям срезаются тем же правилом, что у
/// [`crate::probe::validate_url`]: `build_task` принимает такую ссылку, и
/// это та же ссылка.
fn url_digest(url: &str) -> String {
    use sha2::{Digest as _, Sha256};

    let digest = Sha256::digest(url.trim().as_bytes());
    digest
        .iter()
        .take(PARTIAL_ID_HASH_HEX / 2)
        .flat_map(|byte| {
            [
                PARTIAL_ID_HEX[usize::from(byte >> 4)],
                PARTIAL_ID_HEX[usize::from(byte & 0x0f)],
            ]
        })
        .map(char::from)
        .collect()
}

/// Символы, которые ядро согласно отдать в шаблон вывода yt-dlp.
///
/// Список **разрешённых**, а не запрещённых, и это не стиль. Шаблон имени
/// у yt-dlp — не просто строка: перед подстановкой полей значение
/// проходит раскрытие переменных окружения и домашнего каталога. Что
/// именно раскрывается, измерено прямыми запусками вложенного бинарника
/// (macOS, пин 2026.08.19, 2026-08-27, `--print filename`):
///
/// | В шаблоне | Что вышло |
/// |---|---|
/// | `A$HOME B` | `…/A/Users/execaus B` — в имени появились разделители пути |
/// | `$HOME-leading` | `/Users/execaus-leading` — **путь стал абсолютным**, папка назначения потеряна |
/// | `${HOME}` | раскрывается так же |
/// | `$$HOME` | раскрывается: **удвоение доллара экранированием не является** |
/// | `~/leading` | `/Users/execaus/leading` — **тоже уводит из папки назначения** |
/// | `%(ext)s` | поле подставляется |
/// | `%%(ext)s` | остаётся текстом: удвоение процента экранированием является |
/// | `$TL_NO_SUCH_VAR`, `%HOME%`, `~` в середине, `\` | остаются текстом |
///
/// Список опасного здесь уже подводил дважды: сперва в шаблоне
/// экранировался только процент, и мимо прошёл доллар; при разборе
/// доллара нашёлся ещё и ведущий тильда-путь. Третьего раза не будет:
/// перечисляется безопасное. Ошибка перечисления в эту сторону стоит
/// некрасивого имени **частичного** файла, ошибка в ту — файла за
/// пределами папки назначения, собранного из названия, которое пришло от
/// YouTube.
///
/// Финального имени это не касается: его строит [`finalize_in_dir`] уже
/// после того, как yt-dlp сделал своё дело, и в нём название сохраняется
/// целиком — с долларом, процентом и чем угодно ещё.
fn template_safe(ch: char) -> bool {
    ch.is_alphanumeric()
        || matches!(
            ch,
            ' ' | '-' | '_' | '.' | ',' | '(' | ')' | '[' | ']' | '\'' | '!'
        )
}

/// Чем заменяется всё, что в шаблон не пускают.
const TEMPLATE_REPLACEMENT: char = '_';

/// Рабочая основа — имя частичных файлов потоков и рабочего файла склейки:
/// `<id>.<название>`.
///
/// Название — основа E3 (`sanitized_stem(название, video_id_of(ссылка))`),
/// пропущенная через белый список [`template_safe`] и укороченная под
/// [`download_title_budget`]. Id — [`PartialId`], целиком и без обрезки.
///
/// **Рабочая основа — из запроса, финальная — шаблон** (ревью TL-89, B1).
/// Сюда не входят ни шаблон имени из настроек, ни `{date}`: на этом стоит
/// обещание Р-2 — после выхода из приложения, после ночной паузы, после
/// смены шаблона пользователь вставляет ту же ссылку, ядро строит **то
/// же** имя частичного файла, и yt-dlp продолжает с места своим штатным
/// механизмом. Любая часть имени, зависящая от чего-то кроме запроса
/// (дата, настройка), это обещание отменяет. Финальное имя строит шаблон
/// при завершении (doc модуля, «Две основы имени»); совпадать с ним рабочее
/// не обязано.
///
/// **Id в основе** (TL-104) разводит разные ролики с одинаковым названием:
/// частичные файлы, сохранённые одной задачей, другая не докачивает, не
/// принимает за свои и не удаляет. Почему не название — doc [`PartialId`].
///
/// Цена белого списка названа прямо: два разных названия, отличающихся
/// только непропущенными символами, дают одно название в основе — для
/// **одного** ролика, разные ролики разводит id. Финальные имена не
/// сталкиваются никогда: их разводит суффикс коллизии (Ф-7).
///
/// **Id пишется перед названием, а не после** (ревью TL-104, S1), и это не
/// вкус. Название приходит от YouTube и может содержать что угодно из
/// белого списка, в том числе точку и чужой id: при `<название>.<id>` ролик
/// с названием `Трейлер.aqz-KE-bpKQ.f139` клал файлы под префикс потока
/// ролика «Трейлер» (`aqz-KE-bpKQ`), и подчистка того удаляла их. С id
/// впереди первая точка имени стоит сразу за id, а в алфавите id точки нет
/// ([`partial_id_byte`]): имя, построенное нами для другого ролика, начинается
/// с `<его id>.` и под префикс `<наш id>.` не попадает. Файлы рядом с
/// названием в папке — цена: теперь они сортируются по id.
///
/// Точка на конце названия срезается, хотя больше не стоит на конце имени:
/// основа одна на все хвосты, и её форма от расположения не зависит.
fn download_stem(stem: &str, id: &PartialId) -> String {
    let allowed: String = stem
        .chars()
        .map(|ch| {
            if template_safe(ch) {
                ch
            } else {
                TEMPLATE_REPLACEMENT
            }
        })
        .collect();

    let budget = download_title_budget();
    let mut cut = budget.min(allowed.len());
    while cut > 0 && !allowed.is_char_boundary(cut) {
        cut -= 1;
    }
    // Точка и пробел на конце: первую Windows молча срезает, второй —
    // тоже. Обрезка легко оставляет и то и другое посреди слова.
    let fitted = allowed[..cut].trim_end_matches(['.', ' ']);

    // Пустое название недостижимо на выходе `sanitized_stem` (пустой основы
    // он не отдаёт), но имя частичного файла обязано быть непустым при
    // любом входе, а не при том, который мы ожидаем.
    let title = if fitted.is_empty() {
        TEMPLATE_REPLACEMENT.to_string()
    } else {
        fitted.to_string()
    };
    format!("{}.{title}", id.as_str())
}

/// Идентификатор формата, который ядро согласно передать процессу (Ф-1).
///
/// Белый список **формы**, а не алфавита и не чистка (TL-97). Значение
/// `-f` yt-dlp читает как селектор, и строка из одних «разрешённых» букв
/// может оказаться не идентификатором, а словом селектора: `best`,
/// `bestvideo`, `all`, `mp4`, `3gp`. Такое слово заказало бы у yt-dlp
/// **другой** формат — лучший, худший или первый с этим расширением, — то
/// есть скачало бы не то, что выбрал пользователь, тот же обман, что и
/// подмена качества «ближайшим», которую С-10 запрещает прямым текстом.
/// Прежняя проверка алфавита (буквы, цифры, `-_.`) эти слова пропускала.
///
/// Пропускаются ровно формы, встреченные в фикстурах (все `format_id` из
/// `tests/fixtures/ytdlp-probe/*.json` и строк прогресса
/// `tests/fixtures/ytdlp-download/`, замер TL-97 на пине 2026.08.19):
///
/// | Форма | Примеры | Что это у YouTube |
/// |---|---|---|
/// | `<цифры>` | `18`, `137`, `616` | обычный поток |
/// | `<цифры>-<цифры>` | `140-0`, `251-21` | звуковая дорожка на языке |
/// | `<цифры>-drc` | `140-drc`, `251-drc` | звук со сжатием динамики |
/// | `sb<цифры>` | `sb0`…`sb3` | раскадровка превью |
///
/// Ни одно слово селектора этих форм не имеет: всё, что yt-dlp понимает
/// как фильтр, — буквы (с цифрой только внутри, `3gp`) без дефиса, а
/// единственная буквенная форма списка — `sb` с цифрами. Какие слова
/// селектор понимает, снято тем же пином офлайн (`--load-info-json`,
/// мёртвый прокси, `sandbox-exec` без сети): формат с идентификатором,
/// равным слову, yt-dlp не выбирает по `-f <слово>` — берёт другой или
/// отвечает `Requested format is not available`. Список — в тесте
/// `a_selector_word_is_not_a_format_id`.
///
/// Цена белого списка названа: форма, которой нет в фикстурах (`hls-1080p`
/// у других сайтов, новый суффикс у YouTube), будет отвергнута —
/// `noStreamsSelected` при постановке, а не тихий запуск с чужим
/// селектором. Расширять список — по живой фикстуре разбора с этой формой.
///
/// Всё, что отсекал прежний алфавит, отсекается и формой: плюс (оператор
/// объединения `137+140` — склейку снова вёл бы yt-dlp), запятая (ею ядро
/// само соединяет потоки в [`format_selector`]), косая черта, ведущий
/// дефис (строка-флаг), ведущая точка (имя частичного файла стало бы
/// скрытым) и любая точка вообще.
fn usable_format_id(format_id: &str) -> bool {
    let digits = |part: &str| !part.is_empty() && part.bytes().all(|byte| byte.is_ascii_digit());

    if format_id.len() > MAX_FORMAT_ID_BYTES {
        return false;
    }
    if let Some(number) = format_id.strip_prefix("sb") {
        return digits(number);
    }
    match format_id.split_once('-') {
        None => digits(format_id),
        Some((number, suffix)) => digits(number) && (suffix == "drc" || digits(suffix)),
    }
}

// ────────────────────────── Приёмник событий ──────────────────────────

/// Куда уходят события хода задачи.
///
/// Шов ровно ради тестов — тот же приём и та же причина, что у
/// [`crate::ytdlp::prepare::ProgressSink`]: автомат фаз нельзя проверить,
/// поднимая настоящее Tauri-приложение, а проверить его надо.
pub trait ProgressSink: Send + Sync {
    fn emit(&self, event: DownloadProgressEvent);
}

/// Боевой приёмник: Tauri-событие [`PROGRESS_EVENT`] всем окнам.
pub struct AppSink(pub tauri::AppHandle);

impl ProgressSink for AppSink {
    fn emit(&self, event: DownloadProgressEvent) {
        use tauri::Emitter as _;

        // Неотправленное событие — не повод бросать загрузку: работа
        // важнее индикатора (то же решение, что в подготовке yt-dlp).
        if let Err(err) = self.0.emit(PROGRESS_EVENT, event) {
            eprintln!("download: не удалось отправить событие прогресса: {err}");
        }
    }
}

/// Троттлинг и запись последнего состояния задачи в одном месте.
///
/// Через него проходит **каждое** изменение фазы: он и отправляет
/// событие, и обновляет снимок, по которому очередь решает, что случилось
/// с задачей и можно ли её повторить. Двух путей к этим двум действиям
/// нет намеренно — разойдясь, они дали бы задачу, о состоянии которой
/// экран и ядро думают разное.
struct Emitter<'a> {
    task: &'a Arc<DownloadTask>,
    sink: &'a dyn ProgressSink,
    last_emit: Option<Instant>,
}

impl<'a> Emitter<'a> {
    fn new(task: &'a Arc<DownloadTask>, sink: &'a dyn ProgressSink) -> Self {
        Self {
            task,
            sink,
            last_emit: None,
        }
    }

    /// Записать состояние и, если можно, отправить событие.
    ///
    /// Троттлинг пропускает вперёд всё, что меняет **вид** состояния:
    /// смену фазы, смену состояния внутри `downloading`
    /// (`running` ⇄ `waitingRetry`) и любой терминальный переход.
    /// Придерживается он только частых обновлений одного и того же вида —
    /// то есть ровно того, ради чего заведён.
    ///
    /// Снимок задачи обновляется **всегда**, даже когда событие
    /// проглочено: он не для экрана, а для команд, и отставший снимок
    /// означал бы отказ `retry_download` по причине, которой уже нет.
    fn emit(&mut self, progress: DownloadProgress) {
        self.emit_with(progress, false);
    }

    /// То же, но мимо троттлинга.
    ///
    /// Нужно ровно одному месту — последнему обновлению перед уходом из
    /// «Скачивания». Вид состояния там не меняется (`running` остаётся
    /// `running`), значит троттлинг вправе его проглотить, и шаг
    /// «Скачивание» закончился бы на том проценте, который случайно
    /// успел проехать, — 43 % вместо ста. Смены фазы это не спасает:
    /// она приезжает следующим событием и рисует уже другой шаг.
    fn force(&mut self, progress: DownloadProgress) {
        self.emit_with(progress, true);
    }

    fn emit_with(&mut self, progress: DownloadProgress, force: bool) {
        let previous = self.task.snapshot();
        let now = monotonic_now();

        let shape_changed = previous.phase() != progress.phase()
            || downloading_shape(&previous) != downloading_shape(&progress);
        // `Option::is_none_or` подошёл бы лучше, но он стабилен с 1.82,
        // а нижняя граница проекта — 1.77.
        let due = match self.last_emit {
            None => true,
            Some(last) => now.duration_since(last) >= PROGRESS_THROTTLE,
        };

        self.task.set_progress(progress.clone());

        if !(force || shape_changed || progress.is_terminal() || due) {
            return;
        }

        self.last_emit = Some(now);
        self.sink.emit(DownloadProgressEvent {
            task_id: self.task.id.clone(),
            progress,
        });
    }
}

/// Вид состояния внутри фазы `downloading`; `None` — фаза другая.
fn downloading_shape(progress: &DownloadProgress) -> Option<&'static str> {
    match progress {
        DownloadProgress::Downloading(DownloadingState::Running { .. }) => Some("running"),
        DownloadProgress::Downloading(DownloadingState::WaitingRetry { .. }) => {
            Some("waitingRetry")
        }
        _ => None,
    }
}

// ────────────────────────── Запуск yt-dlp ──────────────────────────

/// Запускатель yt-dlp, отдающий stdout построчно, — единственный шов
/// между автоматом фаз и настоящим процессом.
///
/// `on_line` возвращает момент, до которого обязана прийти следующая
/// строка; `None` снимает срок. Так сторож «нет продвижения» получается
/// **таймером, а не счётчиком строк**, чего и требует находка TL-41:
/// замерший поток либо не печатает ничего, либо печатает «Read timed out»,
/// ничего не принимая, — счётчик строк обманулся бы в обе стороны.
pub trait DownloadLauncher: Send + Sync {
    fn launch<'a>(
        &'a self,
        args: &'a [&'a str],
        handle: &'a RunHandle,
        first_deadline: Instant,
        on_line: &'a mut (dyn FnMut(&str) -> Option<Instant> + Send),
    ) -> Pin<Box<dyn Future<Output = Result<StreamedRun, SidecarError>> + Send + 'a>>;
}

/// Продакшен-реализация: запуск через домен `sidecar` (E1) — реестр
/// процессов, группа процессов и убийство по сроку живут в
/// [`crate::sidecar::run_streaming`].
///
/// JS-рантайм yt-dlp (TL-109) — часть запускателя: аргументы и окружение
/// deno берутся из одного [`YtDlpJsRuntime`] в одной точке запуска, как у
/// разбора (`crate::probe::SidecarLauncher`). Отмена убивает группу
/// процессов, и deno, потомок yt-dlp в той же группе, уходит вместе с ним.
pub struct SidecarDownloader<'a> {
    /// `None` — готовой установки yt-dlp нет вовсе (подготовка не
    /// выполнялась, дерево не сошлось с манифестом).
    ///
    /// Отсутствие пути выражено здесь, а не отдельной веткой у
    /// вызывающего, ради единственности терминального пути: задача,
    /// которой не на чем работать, обязана кончиться тем же событием
    /// `failed` и той же подчисткой, что и любая другая, — и так же
    /// вернуть управление очереди. Подменять недостающий путь относительным именем
    /// (`"yt-dlp"`) нельзя: относительное имя ОС ищет в `PATH`, то есть
    /// приложение запустило бы **чужой** yt-dlp с машины пользователя.
    executable: Option<PathBuf>,
    js_runtime: YtDlpJsRuntime,
    registry: &'a ChildRegistry,
}

impl<'a> SidecarDownloader<'a> {
    pub fn new(
        executable: Option<PathBuf>,
        js_runtime: YtDlpJsRuntime,
        registry: &'a ChildRegistry,
    ) -> Self {
        Self {
            executable,
            js_runtime,
            registry,
        }
    }
}

impl DownloadLauncher for SidecarDownloader<'_> {
    fn launch<'a>(
        &'a self,
        args: &'a [&'a str],
        handle: &'a RunHandle,
        first_deadline: Instant,
        on_line: &'a mut (dyn FnMut(&str) -> Option<Instant> + Send),
    ) -> Pin<Box<dyn Future<Output = Result<StreamedRun, SidecarError>> + Send + 'a>> {
        let Some(executable) = self.executable.as_deref() else {
            return Box::pin(std::future::ready(Err(SidecarError::NotFound)));
        };

        Box::pin(async move {
            let argv = self.js_runtime.argv(args);
            let env = self.js_runtime.env();
            run_streaming(
                executable,
                &argv,
                &env,
                self.registry,
                handle,
                first_deadline,
                on_line,
            )
            .await
        })
    }
}

// ─────────────────────────── Состояние ───────────────────────────

/// Отмена задачи: флаг плюс побудка ждущих.
///
/// Флаг нужен потому, что отмена приходит в любой момент, а проверяется в
/// нескольких; побудка — потому, что пауза перед повтором длится до
/// минуты, и просыпаться от неё по таймеру значило бы отвечать на
/// «Отменить» через сорок секунд (Н-3 требует секунд).
#[derive(Debug, Default)]
struct CancelToken {
    flag: AtomicBool,
    notify: tokio::sync::Notify,
}

impl CancelToken {
    fn cancel(&self) {
        self.flag.store(true, Ordering::SeqCst);
        self.notify.notify_waiters();
    }

    fn is_cancelled(&self) -> bool {
        self.flag.load(Ordering::SeqCst)
    }

    /// Ждёт отмены. Регистрация в [`tokio::sync::Notify`] делается **до**
    /// проверки флага — иначе отмена, случившаяся между проверкой и
    /// ожиданием, была бы потеряна навсегда (та же ловушка и то же её
    /// закрытие, что в [`RunHandle`]).
    async fn cancelled(&self) {
        loop {
            let notified = self.notify.notified();
            if self.is_cancelled() {
                return;
            }
            notified.await;
            if self.is_cancelled() {
                return;
            }
        }
    }
}

/// Один поток задачи.
#[derive(Debug, Clone)]
struct StreamJob {
    stream: DownloadStream,
    format_id: String,
    /// Путь к файлу потока, как только его назвал сам yt-dlp
    /// (`[download] Destination: …` или `… has already been downloaded`).
    file: Option<PathBuf>,
    /// Поток забран целиком — качать его в следующей попытке не нужно.
    ///
    /// Отметка — утверждение о диске, и ему не верят на слово: на старте
    /// задачи и перед склейкой она сверяется с файлом
    /// ([`forget_streams_missing_on_disk`], TL-105).
    done: bool,
}

/// Состояние работы, живущее между попытками и повторами задачи.
///
/// Переживает и автоматические повторы, и ручной `retry_download`, и
/// именно поэтому процент не откатывается к нулю (К-6): агрегатор
/// помнит принятые байты, а не начинает считать заново.
struct TaskWork {
    aggregator: ProgressAggregator,
    jobs: Vec<StreamJob>,
    /// Рабочая основа — [`download_stem`]: `<id ролика>.<название>`. От неё —
    /// имена частичных файлов потоков, рабочий файл склейки и белый список
    /// подчистки ([`is_working_name_of`]). Строится из запроса при создании
    /// задачи и не зависит ни от шаблона, ни от даты (doc модуля, «Две основы
    /// имени»).
    download_stem: String,
    /// Папка назначения последнего старта. `None` — задача ещё не
    /// стартовала: имён нет, подчищать нечего.
    destination: Option<PathBuf>,
    /// Детали последней прерванной попытки.
    ///
    /// Хранятся здесь, потому что понадобятся не там, где получены:
    /// решение сдаться принимает политика повторов, а деталей она не
    /// несёт (её собственная документация говорит об этом прямо), и без
    /// этого поля в «Подробнее» у исчерпания попыток не было бы ничего.
    last_interrupt: Option<DownloadErrorDetails>,
}

/// Изменяемая часть задачи, к которой ходят и воркер, и команды.
#[derive(Debug)]
struct TaskState {
    progress: DownloadProgress,
    /// Класс последнего отказа — по нему `retry_download` решает, есть ли
    /// смысл в повторе. Держится отдельно от `progress` потому, что
    /// доставать его из варианта пришлось бы в двух местах.
    failure: Option<DownloadErrorKind>,
    /// Дескриптор процесса, идущего прямо сейчас (yt-dlp или ffmpeg).
    child: Option<Arc<RunHandle>>,
}

/// Задача скачивания: то, что живёт между вызовами трёх команд.
pub struct DownloadTask {
    pub id: String,
    pub plan: DownloadPlan,
    request: StartDownloadRequest,
    state: StdMutex<TaskState>,
    cancel: CancelToken,
    work: tokio::sync::Mutex<TaskWork>,
}

impl DownloadTask {
    fn lock(&self) -> std::sync::MutexGuard<'_, TaskState> {
        self.state
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Последнее известное состояние задачи.
    pub fn snapshot(&self) -> DownloadProgress {
        self.lock().progress.clone()
    }

    /// Данные постановки — то, с чем задача создана.
    ///
    /// Планировщику они нужны целиком: заголовок и пункт качества едут в
    /// снимок очереди (Ф-1), ссылка и `streams` — в сравнение дублей
    /// (Ф-8), а весь запрос как есть — в файл-снимок на диске (Ф-9).
    /// Отдаётся ссылкой, а не копией: запрос неизменяем с момента
    /// создания задачи.
    pub fn request(&self) -> &StartDownloadRequest {
        &self.request
    }

    /// Класс последнего отказа — по нему решается, есть ли смысл в
    /// повторе (Ф-5).
    ///
    /// Отдельно от [`Self::snapshot`], потому что доставать его из
    /// варианта пришлось бы в двух местах; здесь то же поле, что читал
    /// `retry_download` E3 до переезда в очередь.
    pub fn failure(&self) -> Option<DownloadErrorKind> {
        self.lock().failure
    }

    /// Ставит состояние задачи, минуя события.
    ///
    /// Зовут двое: [`Emitter`] (и он же шлёт событие) и планировщик
    /// очереди — на переходах, у которых события прогресса нет по
    /// построению. Их ровно два, и оба про ожидающую задачу: повтор
    /// возвращает её в `Queued` (Ф-5), отмена ожидающей — в `Cancelled`
    /// без единого побочного действия (Ф-4, С-2). Ожидающие задачи
    /// молчат в `download://progress` (Ф-6), а изменение состава очереди
    /// уезжает `queue://changed`.
    pub fn set_progress(&self, progress: DownloadProgress) {
        let mut state = self.lock();
        if let DownloadProgress::Failed { error } = &progress {
            state.failure = Some(error.kind);
        }
        state.progress = progress;
    }

    fn set_child(&self, child: Option<Arc<RunHandle>>) {
        self.lock().child = child;
    }

    /// Отменяет задачу: поднимает флаг, будит ждущих паузу и убивает
    /// процесс, если он сейчас есть.
    ///
    /// Возврат означает, что убийство уже отправлено, — то есть новую
    /// загрузку можно начинать, не рискуя оставить два живых процесса
    /// (то же обещание, что у [`RunHandle::cancel`]).
    pub async fn cancel(&self) {
        self.cancel.cancel();
        let child = self.lock().child.clone();
        if let Some(child) = child {
            child.cancel().await;
        }
    }
}

// ─────────────────────── Создание задачи ───────────────────────

/// Проверяет запрос и собирает задачу — всё, что делается **до** того,
/// как её возьмёт планировщик очереди (`crate::queue::scheduler`).
///
/// Слота здесь больше нет, и это главное отличие от E3: где задача
/// встанет, когда стартует и что случится с её предшественницей, решает
/// очередь (Ф-2, Ф-3 эпика E4), а этот модуль ведёт **одну** задачу от
/// `Queued` до терминальной фазы и ничего не знает о соседях. Раньше обе
/// обязанности жили в одной функции `start_download`, и цена этого была
/// названа прямо: второй старт вытеснял идущую загрузку.
///
/// Идентификатор выдаёт вызывающий, а не эта функция: он же ведёт
/// очередь, он же восстанавливает её с диска — а восстановленная задача
/// обязана получить **тот же** id, что был в снимке (Ф-5, Ф-9), и новый
/// счётчик здесь этого не дал бы.
///
/// # Что здесь проверяется и почему заново
///
/// Ссылка проверяется той же функцией, что и в разборе
/// ([`crate::probe::validate_url`]): её уже разбирал E2, но между разбором
/// и стартом лежит граница IPC, а через неё приезжает то, что прислали, а
/// не то, что показывали. Идентификаторы потоков — [`usable_format_id`].
///
/// Отказ непригодного идентификатора носит класс `noStreamsSelected`, и
/// это решение, а не совпадение. Своего класса у него нет: список отказов
/// команд зафиксирован контрактом (TL-38, правка TL-70), а лишний класс
/// стоил бы правки в трёх областях ради состояния, до которого исправный
/// фронтенд не доводит — идентификаторы он берёт из нашей же выдачи
/// разбора. Из существующих подходит ровно этот: строка, которую ядро
/// отказывается передать процессу, идентификатором потока не является,
/// то есть пригодных потоков в запросе нет. Молча выбросить негодный и
/// скачать оставшийся — путь, отвергнутый прямо: пользователь получил бы
/// не то качество, которое выбрал. Настоящая причина при этом уезжает в
/// лог, где на неё есть место.
pub fn build_task(
    id: String,
    mut request: StartDownloadRequest,
) -> Result<Arc<DownloadTask>, DownloadCommandRejection> {
    // Ссылка в запросе заменяется нормализованной (TL-81): схема и хост в
    // нижнем регистре, остальное как есть. Замена стоит здесь, до всего, и
    // это единственное место, где ссылка входит в задачу, — постановка и
    // восстановление снимка идут через эту функцию. Поэтому argv
    // скачивания, сравнение дублей, рабочее имя, снимок очереди и запись
    // истории видят одну и ту же строку, и ту же, что ушла в разбор.
    request.url = crate::probe::validate_url(&request.url)
        .map_err(|_| {
            eprintln!("download: ссылка не является http(s)-адресом — yt-dlp не запускался");
            DownloadCommandRejection::InvalidUrl
        })?
        .into_owned();

    if !request.streams.has_any() {
        return Err(DownloadCommandRejection::NoStreamsSelected);
    }
    for format_id in format_ids(&request.streams) {
        if !usable_format_id(format_id) {
            eprintln!(
                "download: идентификатор потока «{format_id}» не является \
                 идентификатором формата yt-dlp — запуска не будет"
            );
            return Err(DownloadCommandRejection::NoStreamsSelected);
        }
    }

    let aggregator = ProgressAggregator::new(&request.streams, request.size)
        .ok_or(DownloadCommandRejection::NoStreamsSelected)?;
    let plan = aggregator.plan();

    // Рабочие имена — из запроса, как в E3 (ревью TL-89, B1): тот же запрос
    // в любой день и при любом шаблоне даёт те же частичные файлы. Папки и
    // финального имени здесь нет: их снимает с настроек старт задачи, а
    // постановка случается раньше — иногда в прошлом сеансе (снимок
    // очереди), — и ожидающая задача обязана увидеть настройки своего
    // старта (Р-4).
    //
    // Id ролика в рабочей основе (TL-104) — через белый список форм или хеш
    // ссылки ([`PartialId`]); из самой ссылки в имя не идёт ни байта.
    let download_stem = download_stem(
        &sanitized_stem(&request.title, &video_id_of(&request.url)),
        &PartialId::of_url(&request.url),
    );
    let jobs = jobs_of(&request.streams);

    eprintln!(
        "download: задача {id} создана, потоков {}, план {plan:?}",
        format_ids(&request.streams).count()
    );

    Ok(Arc::new(DownloadTask {
        id,
        plan,
        request,
        state: StdMutex::new(TaskState {
            progress: DownloadProgress::Queued,
            failure: None,
            child: None,
        }),
        cancel: CancelToken::default(),
        work: tokio::sync::Mutex::new(TaskWork {
            aggregator,
            jobs,
            download_stem,
            destination: None,
            last_interrupt: None,
        }),
    }))
}

/// Идентификаторы потоков запроса — в том порядке, в каком они
/// скачиваются.
fn format_ids(streams: &QualityStreams) -> impl Iterator<Item = &str> {
    [
        streams.video_format_id.as_deref(),
        streams.audio_format_id.as_deref(),
    ]
    .into_iter()
    .flatten()
}

fn jobs_of(streams: &QualityStreams) -> Vec<StreamJob> {
    let job = |stream, format_id: &Option<String>| {
        format_id.as_ref().map(|format_id| StreamJob {
            stream,
            format_id: format_id.clone(),
            file: None,
            done: false,
        })
    };

    [
        job(DownloadStream::Video, &streams.video_format_id),
        job(DownloadStream::Audio, &streams.audio_format_id),
    ]
    .into_iter()
    .flatten()
    .collect()
}

/// Идентификатор ролика из ссылки — для запасного имени файла, когда от
/// названия после санитизации не осталось ничего (Ф-6), и для `{id}`
/// шаблона. В рабочую основу (TL-104) он напрямую **не** идёт: там только
/// то, что прошло белый список форм ([`PartialId`]).
///
/// Разбором ссылок YouTube это не является и являться не должно
/// (инвариант проекта: адреса — дело yt-dlp). Берётся значение `v=`,
/// иначе — последний непустой сегмент пути; доверия ему не больше, чем
/// названию, и [`crate::download::filename::sanitized_stem`] пропускает его через собственный белый
/// список.
fn video_id_of(url: &str) -> String {
    let after_scheme = url.split_once("://").map_or(url, |(_, rest)| rest);
    let (path, query) = match after_scheme.split_once('?') {
        Some((path, query)) => (path, query),
        None => (after_scheme, ""),
    };

    for pair in query.split('&') {
        if let Some(value) = pair.strip_prefix("v=") {
            return value.split('#').next().unwrap_or_default().to_string();
        }
    }

    path.rsplit('/')
        .find(|segment| !segment.is_empty())
        .unwrap_or_default()
        .to_string()
}

// ─────────────────── Настройки и история задачи (TL-89) ───────────────────

/// Откуда задача берёт настройки и куда пишет историю (E5).
///
/// Здесь **хранилища**, а не значения из них: значения снимает сам
/// [`run_task`] в своей первой строке (Р-4). Окружение живёт дольше
/// задачи — в бою это managed-состояние приложения, — и прочитай его
/// кто-нибудь раньше, при постановке или при старте очереди, ожидающие
/// задачи не увидели бы смены настроек, сделанной, пока они стояли.
pub struct TaskEnv {
    /// Настройки процесса. `None` — `setup` их не положил; тогда, как и у
    /// хранилища, не открывшегося на сеанс, действуют умолчания (Н-4).
    pub settings: Option<Arc<SettingsState>>,
    /// История процесса — то же managed-состояние, что у команд истории
    /// (TL-90). `None` — `setup` его не положил: Done без записи, в лог.
    pub history: Option<Arc<HistoryState>>,
    /// Системная «Загрузки» (`download_dir()`) — тот же резолв, что у
    /// команд истории и настроек. `None` — ОС её не дала.
    pub system_downloads: Option<PathBuf>,
    /// Сегодняшняя дата для `{date}`. В бою — [`today_utc_date`]; шов ради
    /// тестов, которые не ждут полуночи.
    pub today: fn() -> TemplateDate,
}

/// Сегодняшняя дата по UTC для `{date}`: `clock::today_utc` — та же
/// функция, что у предпросмотра шаблона (TL-91), и то же преобразование
/// ([`TemplateDate::from_civil`]).
///
/// Часы ОС за 9999 годом — не повод ронять готовую загрузку: подставляется
/// [`TemplateDate::UNIX_EPOCH`], причина — в лог.
pub fn today_utc_date() -> TemplateDate {
    let civil = clock::today_utc();
    TemplateDate::from_civil(civil).unwrap_or_else(|| {
        eprintln!(
            "download: часы ОС дают дату {civil:?} вне 1…9999 года — в {{date}} уходит 1970-01-01"
        );
        TemplateDate::UNIX_EPOCH
    })
}

/// Что задача сняла с настроек на своём старте и держит до терминального
/// исхода (Р-4, Ф-14).
struct TaskStart {
    /// Папка назначения: своя из настроек либо системная «Загрузки».
    destination: PathBuf,
    /// Снимок настроек: шаблон имени и предел попыток.
    settings: Settings,
}

impl TaskStart {
    /// Единственное место, где оркестрация читает настройки.
    ///
    /// Системная папка, которую ОС не дала, — пустой путь: он честно
    /// доезжает до класса `destinationUnavailable` проверкой
    /// [`ensure_destination`], своей ветки отказа не нужно (как и в E3).
    fn read(task: &DownloadTask, env: &TaskEnv) -> Self {
        let settings = match env.settings.as_deref().map(SettingsState::store) {
            Some(Ok(store)) => store.current(),
            Some(Err(reason)) => {
                eprintln!(
                    "download: задача {}: хранилища настроек нет ({reason}) — действуют умолчания",
                    task.id
                );
                Settings::default()
            }
            None => {
                eprintln!(
                    "download: задача {}: настройки не подключены — действуют умолчания",
                    task.id
                );
                Settings::default()
            }
        };
        let destination = match settings.destination() {
            Destination::System => env.system_downloads.clone().unwrap_or_default(),
            Destination::Custom(folder) => folder.as_path().to_path_buf(),
        };
        Self {
            destination,
            settings,
        }
    }

    /// **Финальная** основа имени по снятому шаблону на дату `date` (Ф-12).
    ///
    /// Только для имени готового файла: рабочие имена от шаблона не зависят
    /// (doc модуля, «Две основы имени»).
    fn file_stem(&self, task: &DownloadTask, date: TemplateDate) -> String {
        let video_id = video_id_of(&task.request.url);
        self.settings.file_stem(&TemplateContext {
            title: &task.request.title,
            video_id: &video_id,
            quality: task.request.quality,
            date,
        })
    }
}

impl TaskWork {
    /// Запоминает папку этого старта.
    ///
    /// Сменилась **папка** с прошлого старта — забранные потоки забываются
    /// (doc модуля, «Настройки снимаются на старте задачи»). Шаблон и дата
    /// сюда не приходят вовсе: рабочие имена от них не зависят (B1).
    ///
    /// Папка та же — забранные потоки сверяются с диском
    /// ([`forget_streams_missing_on_disk`], TL-105): файл потока могли удалить
    /// между стартами, и повтор обязан спросить такой поток у yt-dlp, а не
    /// пропустить его мимо запуска.
    fn begin(&mut self, task_id: &str, destination: &Path) {
        let moved = self
            .destination
            .as_deref()
            .is_some_and(|previous| previous != destination);
        if moved {
            eprintln!(
                "download: папка назначения сменилась с прошлого старта задачи — потоки \
                 качаются заново, прежние частичные файлы остаются на месте (Р-4)"
            );
            forget_streams(self);
        }
        self.destination = Some(destination.to_path_buf());
        forget_streams_missing_on_disk(self, task_id, "на старте");
    }
}

/// Пишет запись Done в историю — ровно одну (Ф-3, Р-1, Р-2).
///
/// Отказ исход задачи не меняет (Н-4). Пометку `lastWriteFailed` при
/// отказе вставки выставляет сам `HistoryStore::insert`; здесь она
/// ставится только за отказы раньше вставки: не снялся размер файла,
/// запись прервалась паникой.
///
/// Работа блокирующая (`metadata` и транзакция SQLite с `fsync`) и уходит с
/// потока рантайма (Н-3) — тот же приём, что у команд истории.
///
/// `write` — тело блокирующей записи, в бою [`write_done`]. Параметр — шов
/// ради тестов (ревью TL-89, S2): паника на потоке блокирующего пула
/// приходит сюда `JoinError`, а настоящую запись довести до паники нечем.
async fn record_done(
    task: &DownloadTask,
    env: &TaskEnv,
    folder: &Path,
    file_name: &str,
    write: WriteDone,
) {
    let Some(history) = env.history.clone() else {
        eprintln!(
            "download: задача {} готова, но история не подключена — запись не сделана",
            task.id
        );
        return;
    };

    let writer = Arc::clone(&history);
    let task_id = task.id.clone();
    let request = task.request.clone();
    let folder = folder.to_path_buf();
    let file_name = file_name.to_owned();
    let written = tokio::task::spawn_blocking(move || {
        write(&writer, &task_id, &request, folder, file_name);
    })
    .await;

    if let Err(err) = written {
        eprintln!(
            "download: запись истории задачи {} прервана: {err}",
            task.id
        );
        if let Ok(store) = history.store() {
            store.record_write_failure(HistoryWriteFailure::StorageFailed);
        }
    }
}

/// Тело блокирующей записи истории — [`write_done`] в бою (шов [`record_done`]).
type WriteDone = fn(&HistoryState, &str, &StartDownloadRequest, PathBuf, String);

/// Тело [`record_done`] — на потоке блокирующего пула.
fn write_done(
    history: &HistoryState,
    task_id: &str,
    request: &StartDownloadRequest,
    folder: PathBuf,
    file_name: String,
) {
    let store = match history.store() {
        Ok(store) => store,
        Err(unavailable) => {
            eprintln!(
                "download: задача {task_id} готова, но история на сеанс недоступна ({:?}) — \
                 запись не сделана",
                unavailable.reason
            );
            return;
        }
    };

    let size_bytes = match std::fs::metadata(folder.join(&file_name)) {
        Ok(meta) => meta.len(),
        Err(err) => {
            eprintln!(
                "download: задача {task_id}: размер готового файла не снят ({err}) — запись \
                 истории не сделана"
            );
            store.record_write_failure(if err.kind() == io::ErrorKind::PermissionDenied {
                HistoryWriteFailure::NoAccess
            } else {
                HistoryWriteFailure::StorageFailed
            });
            return;
        }
    };

    let record = NewHistoryRecord {
        // Канонический id очереди (TL-72), как требует запись. Ссылка, форму
        // которой он не разбирает, даёт пустую строку, а не догадку: поле
        // обещает тот id, по которому очередь сравнивает дубли.
        video_id: canonical_video_id(&request.url)
            .map(|id| id.as_str().to_owned())
            .unwrap_or_default(),
        url: request.url.clone(),
        title: request.title.clone(),
        quality: request.quality,
        file_name,
        folder,
        size_bytes,
        finished_at_unix_secs: clock::now_unix_secs(),
    };
    match store.insert(&record) {
        Ok(id) => eprintln!("download: задача {task_id} записана в историю под id {id}"),
        Err(err) => eprintln!("download: задача {task_id} не записана в историю: {err}"),
    }
}

// ──────────────────────────── Воркер ────────────────────────────

/// Чем кончилась задача.
enum TaskEnd {
    Done { file_name: String },
    Failed(DownloadFailure),
    Cancelled,
}

/// Ведёт задачу от `Queued` до одной из трёх терминальных фаз.
///
/// Функция ведёт **одну** задачу и о существовании соседей не знает:
/// единственность активной держит очередь (`crate::queue::scheduler`),
/// которая зовёт воркера следующей только после возврата отсюда. В E3
/// здесь стояли два шага, которых больше нет, — «добить предшественника»
/// и «встать в шлюз»: они были платой за вытеснение, а вытеснения в
/// очереди не бывает (Ф-3, строгий FIFO). Двух yt-dlp во времени это
/// по-прежнему не допускает, но держится это теперь на планировщике, а
/// не на шлюзе внутри воркера.
pub async fn run_task(
    task: &Arc<DownloadTask>,
    launcher: &dyn DownloadLauncher,
    ffmpeg: &dyn FfmpegLauncher,
    sink: &dyn ProgressSink,
    env: &TaskEnv,
) {
    run_task_with(task, launcher, ffmpeg, sink, env, write_done).await;
}

/// [`run_task`] с телом записи истории параметром (шов [`record_done`]).
async fn run_task_with(
    task: &Arc<DownloadTask>,
    launcher: &dyn DownloadLauncher,
    ffmpeg: &dyn FfmpegLauncher,
    sink: &dyn ProgressSink,
    env: &TaskEnv,
    write: WriteDone,
) {
    // Р-4: настройки снимаются здесь и больше не читаются — ни на повторах
    // внутри задачи, ни на финализации. Папка запоминается до всего
    // остального: подчистка любого исхода ищет файлы в ней. Рабочие имена
    // уже есть — они из запроса (B1).
    let start = TaskStart::read(task, env);
    let destination = start.destination.as_path();
    task.work.lock().await.begin(&task.id, destination);

    let mut emitter = Emitter::new(task, sink);
    let started = monotonic_now();
    let end = execute(task, launcher, ffmpeg, &mut emitter, &start, env).await;
    let elapsed = monotonic_now().duration_since(started);

    // Подчистка и терминальное событие — в одном месте на все ветки:
    // «что осталось на диске» уезжает на провод фактом, а не догадкой по
    // классу (doc [`crate::types::PartialData`]), и узнаётся он ровно тем,
    // что подчистка сделала.
    let mut work = task.work.lock().await;
    let mut finished = None;
    let progress = match end {
        TaskEnd::Done { file_name } => {
            // Готовый файл лежит под финальным именем; рабочие файлы задачи
            // рядом (потоки после склейки, хвосты фрагментов) — мусор, а Н-4
            // требует, чтобы штатные исходы его не оставляли. Удаляются
            // только точные рабочие имена (TL-106): готовый файл другой
            // задачи того же ролика под префиксом потока не трогается. Свой
            // готовый файл щадится на случай точного совпадения с рабочим
            // именем (doc [`Cleanup::apply_sparing`]). Потоки, принятые как
            // «уже скачан» у другой задачи того же ролика, удаляются тоже:
            // её повтор перекачает их (TL-105, doc
            // [`forget_streams_missing_on_disk`]).
            Cleanup::Remove.apply_sparing(destination, &work, Some(&file_name));
            eprintln!(
                "download: задача {} готова за {} мс: «{file_name}»",
                task.id,
                elapsed.as_millis()
            );
            // Та же функция, что у записи на экране истории, на том же
            // значении папки, что уходит в запись (doc модуля).
            let folder_display = folder_display(destination, env.system_downloads.as_deref());
            finished = Some(file_name.clone());
            DownloadProgress::Done {
                file_name,
                folder_display,
            }
        }
        TaskEnd::Cancelled => {
            let partial_data = Cleanup::Remove.apply(destination, &work);
            forget_streams(&mut work);
            eprintln!(
                "download: задача {} отменена за {} мс, частичное: {partial_data:?}",
                task.id,
                elapsed.as_millis()
            );
            DownloadProgress::Cancelled { partial_data }
        }
        TaskEnd::Failed(failure) => {
            let kind = failure.kind();
            let cleanup = Cleanup::for_failure(kind);
            let partial_data = cleanup.apply(destination, &work);
            if cleanup == Cleanup::Remove {
                forget_streams(&mut work);
            }
            eprintln!(
                "download: задача {} провалена за {} мс, класс {kind:?} ({failure}), \
                 частичное: {partial_data:?}",
                task.id,
                elapsed.as_millis()
            );
            DownloadProgress::Failed {
                error: failure.to_contract(partial_data),
            }
        }
    };
    // Снимаем ссылку на процесс до терминального события: после него
    // задача кончилась, и убивать по чужому дескриптору уже нечего.
    task.set_child(None);
    work.last_interrupt = None;
    drop(work);

    // Запись — раньше события: к моменту, когда о готовой задаче узнает
    // окно, она уже в базе (Ф-3).
    if let Some(file_name) = finished {
        record_done(task, env, destination, &file_name, write).await;
    }

    emitter.emit(progress);

    // Границу задач (Ф-7, Р-2 эпика E6) объявляет не воркер, а очередь —
    // после возврата отсюда. Причина в определении самой границы: «задач
    // нет» — свойство очереди, а не одной задачи, и объявить его тому,
    // кто видит одну, было бы неправдой ровно тогда, когда за этой
    // задачей стоит следующая.
}

/// Автомат фаз: подготовка → скачивание (с повторами) → склейка →
/// финализация.
async fn execute(
    task: &Arc<DownloadTask>,
    launcher: &dyn DownloadLauncher,
    ffmpeg: &dyn FfmpegLauncher,
    emitter: &mut Emitter<'_>,
    start: &TaskStart,
    env: &TaskEnv,
) -> TaskEnd {
    let destination = start.destination.as_path();
    if task.cancel.is_cancelled() {
        return TaskEnd::Cancelled;
    }

    if let Err(failure) = ensure_destination(destination) {
        return TaskEnd::Failed(failure);
    }
    let Some(destination_arg) = destination_arg(destination) else {
        // Путь, не представимый в UTF-8: аргументы процесса домен
        // `sidecar` принимает строками. На macOS и Windows не возникает
        // вовсе (там имена и так Unicode).
        return TaskEnd::Failed(DownloadFailure::DestinationUnavailable {
            reason: "путь к папке назначения не представим в UTF-8".to_string(),
            details: no_details(),
        });
    };

    let mut work = task.work.lock().await;
    // Предел — снятый на старте (Ф-13), а не текущая настройка: смена числа
    // посреди задачи её `total` не трогает.
    let mut policy = RetryPolicy::new(monotonic_now(), start.settings.max_attempts());

    emitter.emit(DownloadProgress::Fetching);

    // ── Скачивание с повторами ──
    loop {
        if task.cancel.is_cancelled() {
            return TaskEnd::Cancelled;
        }

        policy.attempt_started(monotonic_now());

        // Все потоки уже забраны — это повтор после неудачной склейки
        // (С-11): yt-dlp не запускается вовсе, ни одного обращения к
        // YouTube ради того, что уже лежит на диске.
        let interrupted = if work.jobs.iter().all(|job| job.done) {
            None
        } else {
            match download_attempt(
                task,
                &mut work,
                &mut policy,
                launcher,
                emitter,
                &destination_arg,
            )
            .await
            {
                AttemptRun::Completed => None,
                AttemptRun::Interrupted(details) => Some(details),
                AttemptRun::Failed(failure) => return TaskEnd::Failed(failure),
                AttemptRun::Cancelled => return TaskEnd::Cancelled,
            }
        };

        let Some(details) = interrupted else {
            // Шаг «Скачивание» заканчивается на своих ста процентах, а не
            // на том, что успело проехать сквозь троттлинг.
            emitter.force(DownloadProgress::Downloading(
                work.aggregator.running(Some(policy.attempt())),
            ));
            break;
        };
        work.last_interrupt = Some(details);

        match policy.attempt_failed() {
            RetryDecision::Retry { attempt, delay } => {
                let state = work.aggregator.waiting_retry(attempt, 0, 0);
                let percent = frozen_percent(&state);
                if !wait_before_retry(task, emitter, attempt, delay, percent).await {
                    return TaskEnd::Cancelled;
                }
            }
            RetryDecision::GiveUp { attempts } => {
                // Класс «соединение потеряно» собирается здесь из двух
                // половин: решение сдаться даёт политика, детали — та
                // самая последняя прерванная попытка. Политика деталей не
                // несёт по своей же документации.
                return TaskEnd::Failed(DownloadFailure::ConnectionLost {
                    attempts,
                    details: work.last_interrupt.clone().unwrap_or_else(no_details),
                });
            }
        }
    }

    // ── Склейка либо единственный поток ──
    //
    // Вторая сверка с диском (TL-105): первая была на старте, а файл
    // забранного прошлым стартом потока могли удалить, пока шёл запуск.
    // Пропавший поток перестаёт быть забранным и уходит в ветку «файла нет»
    // ниже — отказ сохраняет частичное, повтор спросит поток снова. Снова
    // качать здесь же нельзя: запуск, назвавший файл, которого нет, делал
    // бы это без счёта попыток.
    forget_streams_missing_on_disk(&mut work, &task.id, "перед склейкой");
    let ready = match task.plan {
        DownloadPlan::VideoAndAudio => {
            emitter.emit(DownloadProgress::Merging);

            let (Some(video), Some(audio)) = (
                stream_file(&work, DownloadStream::Video),
                stream_file(&work, DownloadStream::Audio),
            ) else {
                // Сюда ведут две ветки. Запуск кончился кодом 0, формат в
                // перечне выбранных yt-dlp назвал, а файла потока — нет
                // (выпавший из перечня формат отсекается раньше классом
                // `staleFormat`, а запуск без перечня — `ytDlpFailure`,
                // TL-97). Либо файл забранного потока пропал с диска
                // до склейки — сверка выше уже написала об этом в лог.
                // Склеивать нечего. Класс прежний и повторяемый: повтор
                // спросит незабранный поток снова.
                let unnamed: Vec<&str> = work
                    .jobs
                    .iter()
                    .filter(|job| job.file.is_none())
                    .map(|job| job.format_id.as_str())
                    .collect();
                eprintln!("download: файлов потоков {unnamed:?} к склейке нет — склеивать нечего");
                // Класс тот же, а причина — своя: ffmpeg здесь не
                // запускался, и текст про его ошибку был бы неправдой
                // (TL-130).
                return TaskEnd::Failed(DownloadFailure::MergeFailed {
                    reason: MergeFailedReason::StreamsMissing,
                    details: no_details(),
                });
            };

            let handle = Arc::new(RunHandle::new());
            task.set_child(Some(Arc::clone(&handle)));
            // Отмена, пришедшая между проверкой и установкой дескриптора,
            // иначе никого не убила бы: процесс запускается уже после неё.
            if task.cancel.is_cancelled() {
                handle.cancel().await;
            }
            let verdict = merge_streams(
                ffmpeg,
                &MergeRequest {
                    video: &video,
                    audio: &audio,
                    destination_dir: destination,
                    stem: &work.download_stem,
                },
                &handle,
            )
            .await;
            task.set_child(None);

            match verdict {
                MergeVerdict::Merged(merged) => {
                    (merged.path, merged.container.extension().to_string())
                }
                MergeVerdict::Cancelled => return TaskEnd::Cancelled,
                MergeVerdict::Failed(failure) => return TaskEnd::Failed(failure),
            }
        }
        DownloadPlan::SingleStream => {
            // Ни склейки, ни перекодирования (С-2, С-3): фазы `merging` в
            // жизни такой задачи не бывает вовсе, и расширение берётся
            // фактическое — то, которое дал скачанному файлу yt-dlp.
            let Some(file) = work.jobs.first().and_then(|job| job.file.clone()) else {
                eprintln!("download: файла потока к финализации нет");
                return TaskEnd::Failed(DownloadFailure::YtDlpFailure {
                    reason: YtDlpFailureReason::Generic,
                    details: no_details(),
                });
            };
            let extension = file
                .extension()
                .map(|ext| ext.to_string_lossy().into_owned())
                .unwrap_or_default();
            (file, extension)
        }
    };

    if task.cancel.is_cancelled() {
        return TaskEnd::Cancelled;
    }

    // ── Финализация имени ──
    //
    // Ровно один вызов, и он же переименование: занять имя и переименовать
    // внутри одной операции — требование TL-40, между ними не должно быть
    // ни строки нашего кода.
    let (ready_file, extension) = ready;
    // Финальная основа — шаблон старта на дату завершения (Ф-12); рабочая,
    // по которой лежат потоки и склейка, от неё не зависит (B1). Считается
    // до финализации, а не между занятием имени и переименованием.
    let final_stem = start.file_stem(task, (env.today)());
    match finalize_in_dir(destination, &ready_file, &final_stem, &extension) {
        Ok(file_name) => TaskEnd::Done { file_name },
        Err(error) => {
            eprintln!("download: не удалось положить готовый файл в папку назначения: {error}");
            TaskEnd::Failed(DownloadFailure::DestinationUnavailable {
                reason: error.to_string(),
                details: no_details(),
            })
        }
    }
}

/// Путь файла потока, если он известен.
fn stream_file(work: &TaskWork, stream: DownloadStream) -> Option<PathBuf> {
    work.jobs
        .iter()
        .find(|job| job.stream == stream)
        .and_then(|job| job.file.clone())
}

/// Замороженный процент из состояния паузы — чтобы не доставать его из
/// агрегатора вторым способом.
fn frozen_percent(state: &DownloadingState) -> Option<DownloadPercent> {
    match state {
        DownloadingState::WaitingRetry { percent, .. } => *percent,
        DownloadingState::Running { percent, .. } => *percent,
    }
}

fn no_details() -> DownloadErrorDetails {
    DownloadErrorDetails {
        stderr_tail: None,
        exit_code: None,
    }
}

/// Проверяет папку назначения до всякого запуска.
///
/// # Где ловится «папка назначения недоступна» (решение реализации)
///
/// Дизайн оставил момент обнаружения на усмотрение исполнителя. Выбрано
/// **раздельно**, по природе двух разных бед:
///
/// - **папки нет** — проверкой здесь, до запуска процесса. Дёшево,
///   достоверно (существование каталога — не гонка того же рода, что
///   права) и избавляет пользователя от трёхсекундного «Подготовка» перед
///   отказом, причина которого известна сразу;
/// - **нет прав на запись** — по факту, из ошибки того, кто писал.
///   Пробное создание файла было бы гаданием дважды: права на запись
///   каталога не гарантируют записи (квота, ACL, том только для чтения),
///   а сам пробный файл пришлось бы за собой убирать — и он остался бы
///   мусором ровно в том случае, когда убирать некому. Настоящих
///   писателей двое, и оба уже отвечают за свою ошибку: yt-dlp
///   (`classify_attempt` относит «Permission denied» к
///   `destinationUnavailable` по снятой живьём фикстуре
///   `destination-read-only`) и финализация имени (её `io::Error` тем же
///   классом приезжает выше).
///
/// Класс один и тот же, панель одна и та же — расходится только момент,
/// и расходится он в пользу пользователя.
fn ensure_destination(destination: &Path) -> Result<(), DownloadFailure> {
    match std::fs::metadata(destination) {
        Ok(meta) if meta.is_dir() => Ok(()),
        Ok(_) => Err(DownloadFailure::DestinationUnavailable {
            reason: format!("{} — не папка", destination.display()),
            details: no_details(),
        }),
        Err(error) => Err(DownloadFailure::DestinationUnavailable {
            reason: format!("{}: {error}", destination.display()),
            details: no_details(),
        }),
    }
}

// ──────────────────────── Одна попытка ────────────────────────

/// Чем кончился запуск одной попытки.
enum AttemptRun {
    Completed,
    Interrupted(DownloadErrorDetails),
    Failed(DownloadFailure),
    Cancelled,
}

/// Запускает yt-dlp на все ещё не забранные потоки задачи — **одним**
/// процессом (TL-48) — и ведёт его до конца.
///
/// Здесь же живёт сторож продвижения: срок, до которого обязана прийти
/// следующая строка, пересчитывается **на каждой строке** и уходит в
/// запуск, который по нему и убивает процесс. До первой строки прогресса
/// срок держит [`FETCH_SILENCE_TIMEOUT`] («Подготовка»), после — политика
/// повторов ([`RetryPolicy::stall_deadline`], С-8).
///
/// Вывод относится к потокам не по факту запуска, а по формату и по имени
/// файла — правила в шапке модуля, раздел «К какому потоку относится
/// строка».
async fn download_attempt(
    task: &Arc<DownloadTask>,
    work: &mut TaskWork,
    policy: &mut RetryPolicy,
    launcher: &dyn DownloadLauncher,
    emitter: &mut Emitter<'_>,
    destination_arg: &str,
) -> AttemptRun {
    let pending: Vec<usize> = (0..work.jobs.len())
        .filter(|&index| !work.jobs[index].done)
        .collect();
    let selector = format_selector(
        pending
            .iter()
            .map(|&index| work.jobs[index].format_id.as_str()),
    );
    let template = output_template(&work.download_stem);
    let args = download_args(&selector, destination_arg, &template, &task.request.url);

    let handle = Arc::new(RunHandle::new());
    task.set_child(Some(Arc::clone(&handle)));
    if task.cancel.is_cancelled() {
        handle.cancel().await;
    }

    eprintln!(
        "download: запуск yt-dlp для потоков {selector}: {}",
        args.join(" ")
    );

    // Доказательство конца, собранное **этим** запуском, по каждому потоку
    // задачи (индексы — те же, что у `work.jobs`): строка `finished` его
    // формата или `has already been downloaded` с его именем. Нужно
    // потому, что отказ одного формата не останавливает другой (замер в
    // шапке модуля): код выхода 1 ещё не значит, что не забрано ничего.
    let mut ended = vec![false; work.jobs.len()];
    // Назван ли уже файл потока в этом запуске — начало потока заводит
    // сторож заново только один раз (doc [`RetryPolicy::stream_started`]).
    let mut named = vec![false; work.jobs.len()];
    // Перечень форматов, которые yt-dlp выбрал, если он его напечатал.
    let mut selected: Option<Vec<String>> = None;
    // Видел ли этот запуск хоть одну строку прогресса. От него зависит,
    // какой из двух сторожей держит срок, и он же решает, чем стал
    // истёкший срок: зависшей подготовкой или зависшим потоком.
    let mut saw_progress = false;

    let outcome = {
        let mut on_line = |line: &str| -> Option<Instant> {
            let now = monotonic_now();

            match crate::download::progress::parse_line(line) {
                StdoutLine::Progress(sample) => {
                    saw_progress = true;
                    match work.aggregator.apply(&sample) {
                        SampleOutcome::Applied { .. } => {
                            if sample.status == SampleStatus::Finished {
                                for &index in &pending {
                                    if work.jobs[index].format_id == sample.format_id {
                                        ended[index] = true;
                                    }
                                }
                            }
                            policy.observe(work.aggregator.received_bytes(), now);
                            emitter.emit(DownloadProgress::Downloading(
                                work.aggregator.running(Some(policy.attempt())),
                            ));
                        }
                        SampleOutcome::UnknownFormat => {
                            // yt-dlp качает не тот формат, который заказан.
                            // Строка не идёт ни в процент, ни в сторож —
                            // но и убивать по ней живой процесс не за что:
                            // цена ошибки несимметрична (пропавший процент
                            // против оборванной здоровой загрузки),
                            // поэтому срок продлевается по факту вывода.
                            eprintln!(
                                "download: строка прогресса формата «{}» не относится ни к \
                                 одному потоку задачи",
                                sample.format_id
                            );
                            return Some(now + FETCH_SILENCE_TIMEOUT);
                        }
                    }
                }
                StdoutLine::MalformedProgress(line) => {
                    // Маркер наш, а форма не читается: yt-dlp сменил вывод
                    // полей шаблона. Проглотить молча значило бы показывать
                    // замерший процент вместо честного отказа, поэтому
                    // строка идёт в лог целиком, а решение принимает
                    // сторож — продвижения по ней нет.
                    eprintln!("download: строка прогресса не разобрана: {line}");
                }
                StdoutLine::SelectedFormats { format_ids } => {
                    eprintln!("download: yt-dlp выбрал форматы {format_ids:?}");
                    selected = Some(format_ids.iter().map(|id| (*id).to_owned()).collect());
                }
                StdoutLine::Destination { path } => {
                    let owners = attribute_file(work, &pending, Path::new(path));
                    note_stream_start(policy, &mut named, &owners, now);
                }
                StdoutLine::AlreadyDownloaded { path } => {
                    let owners = attribute_file(work, &pending, Path::new(path));
                    note_stream_start(policy, &mut named, &owners, now);
                    for index in owners {
                        eprintln!(
                            "download: поток {} уже был скачан целиком",
                            work.jobs[index].format_id
                        );
                        ended[index] = true;
                        // Поток, который качать не пришлось, не присылает
                        // ни одной строки `downloading`, а `finished` следом
                        // бывает не при любых аргументах (замер TL-48).
                        // Закрывается он здесь, а не по концу процесса:
                        // процесс ещё качает соседний поток, и его процент
                        // иначе упирался бы в 99 до самого конца.
                        let format_id = work.jobs[index].format_id.clone();
                        work.aggregator.mark_complete(&format_id);
                    }
                }
                StdoutLine::Resuming { byte_offset } => {
                    eprintln!("download: попытка продолжает частичный файл с байта {byte_offset}");
                }
                StdoutLine::Other => {}
            }

            if saw_progress {
                policy.stall_deadline()
            } else {
                Some(now + FETCH_SILENCE_TIMEOUT)
            }
        };

        launcher
            .launch(
                &args,
                &handle,
                monotonic_now() + FETCH_SILENCE_TIMEOUT,
                &mut on_line,
            )
            .await
    };

    task.set_child(None);

    // Отмена отсекается раньше цикла повторов и раньше классификации:
    // убитый нами процесс возвращает ровно то же, что процесс,
    // оборвавшийся сам, и не отсеки её здесь — отмена ушла бы в повторы.
    // Потоки при этом забранными не отмечаются: отмена удаляет всё.
    if task.cancel.is_cancelled() || handle.was_cancelled() {
        return AttemptRun::Cancelled;
    }

    let run = match outcome {
        Ok(run) => run,
        Err(error) => {
            // Процесса не случилось вовсе: yt-dlp пропал из каталога
            // данных, нет прав на запуск, битый файл. Класс — честный
            // catch-all девятки.
            eprintln!("download: yt-dlp не запустился: {error}");
            return AttemptRun::Failed(DownloadFailure::YtDlpFailure {
                reason: YtDlpFailureReason::Generic,
                details: no_details(),
            });
        }
    };

    let verdict = if run.deadline_expired {
        let details = DownloadErrorDetails {
            stderr_tail: stderr_tail(&run.stderr),
            // Убитый нами процесс своего кода завершения не оставил.
            exit_code: None,
        };
        if saw_progress {
            // С-8: поток замер, явного обрыва нет. Попытка признаётся
            // неудавшейся и уходит в тот же цикл повторов, что и обрыв, —
            // отдельного «поток завис» пользователю не показывается.
            eprintln!("download: попытка {selector} замерла — снята сторожем продвижения");
            AttemptRun::Interrupted(details)
        } else {
            // yt-dlp не сказал ничего за весь отпущенный срок. Мёртвая
            // сеть так себя не ведёт (см. doc [`FETCH_SILENCE_TIMEOUT`]),
            // значит завис сам процесс.
            eprintln!(
                "download: yt-dlp молчал {FETCH_SILENCE_TIMEOUT_SECS} с на подготовке — снят"
            );
            AttemptRun::Failed(DownloadFailure::YtDlpFailure {
                reason: YtDlpFailureReason::Generic,
                details,
            })
        }
    } else {
        match classify_attempt(&AttemptOutcome {
            exit_code: run.exit_code,
            stderr: &run.stderr,
        }) {
            AttemptVerdict::Completed => AttemptRun::Completed,
            AttemptVerdict::Interrupted { details } => AttemptRun::Interrupted(details),
            AttemptVerdict::Failed(failure) => AttemptRun::Failed(failure),
        }
    };

    // Р-1 ревью TL-48: заказанный формат, которого yt-dlp не выбрал, не
    // появится ни на каком повторе. До TL-48 отдельный запуск на него сразу
    // давал `staleFormat`; здесь тот же класс выводится из перечня. Поверх
    // успеха и поверх обрыва — но не поверх содержательного отказа: его
    // класс точнее.
    let run_details = || DownloadErrorDetails {
        stderr_tail: stderr_tail(&run.stderr),
        exit_code: run.exit_code,
    };
    let missing = missing_from_selection(work, &pending, selected.as_deref());
    let verdict = match verdict {
        AttemptRun::Completed if !missing.is_empty() => stale_format(&missing, run_details()),
        AttemptRun::Interrupted(details) if !missing.is_empty() => stale_format(&missing, details),
        other => other,
    };

    let completed = matches!(verdict, AttemptRun::Completed);
    settle_streams(work, &pending, &ended, completed);

    // TL-97: перечня не было — сторож Р-1 ослеп. Забранное выше забрано
    // честно (код 0 и файл), а про оставшееся без файла сказать нечего:
    // ни «формат выпал», ни «оба потока скачались» из вывода не следуют.
    if completed && selected.is_none() {
        let unverified = unverified_streams(work, &pending);
        if !unverified.is_empty() {
            return unlisted_selection(&unverified, run_details());
        }
    }
    verdict
}

/// Потоки, про которые запуск с кодом 0 **без перечня** выбранных форматов
/// не сказал ничего проверяемого (TL-97).
///
/// Перечень `[info] … Downloading N format(s): …` — единственное, по чему
/// видно выпадение формата из выбора ([`missing_from_selection`]). Нет его
/// в выводе — значит сменился текст строки (новый пин yt-dlp или
/// обновление отдельным контуром E6), и незабранный поток мог как выпасть
/// из выбора, так и потеряться иначе. Пусто, если заказан один формат: его
/// отсутствие в метаданных yt-dlp называет сам — `Requested format is not
/// available` и код 1, а через запятую тот же формат выпадает молча, с
/// кодом 0 (замер TL-97 на пине 2026.08.19 офлайн: `--load-info-json` с
/// одним форматом 133, `-f 139` против `-f 133,139`), перечень при одном
/// формате не сторож. Пусто и тогда, когда файлы получили все потоки: успех
/// доказан без перечня, и сменившийся текст строки не должен ломать
/// работающие загрузки до выпуска приложения.
fn unverified_streams(work: &TaskWork, pending: &[usize]) -> Vec<String> {
    if pending.len() < 2 {
        return Vec::new();
    }
    pending
        .iter()
        .map(|&index| &work.jobs[index])
        .filter(|job| !job.done)
        .map(|job| job.format_id.clone())
        .collect()
}

/// Исход запуска, у которого поток остался без файла, а перечня выбранных
/// форматов не было (TL-97).
///
/// Класс — `ytDlpFailure` с под-причиной `generic`, и это выбор из
/// существующих, а не новый класс контракта:
///
/// - `mergeFailed` — ложь: его текст «оба потока скачались», а второго
///   потока нет (дефект Р-1 ревью TL-48, от которого перечень и защищал);
/// - `staleFormat` — догадка: без перечня выпадение не доказано, а класс
///   неповторяемый и удаляет скачанное — ошибись он, пользователь потерял
///   бы готовый поток и кнопку «Повторить»;
/// - `ytDlpFailure`/`outdated` — тоже ложь: устарел не yt-dlp, а наш
///   разбор его вывода;
/// - `ytDlpFailure`/`generic` — правда: yt-dlp завершился, а что стало с
///   потоком, из его вывода не узнать. Класс повторяемый и частичное
///   сохраняет. Повтор заказывает только незабранный поток — **один**
///   формат, — и тогда выпавший формат yt-dlp назовёт сам, кодом 1 и
///   `Requested format is not available`, то есть `staleFormat` придёт уже
///   доказанным.
fn unlisted_selection(unverified: &[String], details: DownloadErrorDetails) -> AttemptRun {
    eprintln!(
        "download: запуск завершился с кодом 0 без перечня выбранных форматов, у потоков \
         {unverified:?} нет файла — выпал ли формат, проверить нечем (сменился текст строки \
         `[info] … Downloading N format(s)`?)"
    );
    AttemptRun::Failed(DownloadFailure::YtDlpFailure {
        reason: YtDlpFailureReason::Generic,
        details,
    })
}

/// Заказанные этой попыткой форматы, которых yt-dlp не выбрал (Р-1 ревью
/// TL-48).
///
/// Решается только по перечню `[info] … Downloading N format(s): …`: нет
/// перечня в выводе — нет и вывода о выборе. Этот случай не молчаливый:
/// поток без файла после такого запуска разбирает [`unverified_streams`]
/// (TL-97). Формат, названный в перечне, сюда не попадает, даже если файла
/// его yt-dlp так и не назвал.
fn missing_from_selection(
    work: &TaskWork,
    pending: &[usize],
    selected: Option<&[String]>,
) -> Vec<String> {
    let Some(selected) = selected else {
        return Vec::new();
    };
    pending
        .iter()
        .map(|&index| &work.jobs[index].format_id)
        .filter(|format_id| !selected.contains(format_id))
        .cloned()
        .collect()
}

fn stale_format(missing: &[String], details: DownloadErrorDetails) -> AttemptRun {
    eprintln!(
        "download: yt-dlp не выбрал заказанные форматы {missing:?} — в метаданных ролика их \
         больше нет"
    );
    AttemptRun::Failed(DownloadFailure::StaleFormat { details })
}

/// Сообщает сторожу о начале потоков, файл которых назван в этом запуске
/// впервые (М-2 ревью TL-48).
///
/// Граница — именно первая строка, называющая файл потока: `Destination`
/// или `has already been downloaded`. До TL-48 с неё начинался новый
/// процесс с полным сроком. Повтор той же строки срок не продлевает, так
/// что замерший процесс не может жить на собственных строках.
///
/// Строки постпроцессоров (`[FixupM4a]` и подобные) границей не считаются.
/// Снято с ffmpeg в `PATH`: постпроцессор потока идёт после его `finished`
/// и до `Destination` следующего, то есть живёт в сроке от последнего байта
/// своего потока — ровно как до TL-48, когда он шёл в том же процессе перед
/// выходом.
fn note_stream_start(policy: &mut RetryPolicy, named: &mut [bool], owners: &[usize], now: Instant) {
    for &index in owners {
        if !named[index] {
            named[index] = true;
            policy.stream_started(now);
        }
    }
}

/// Приписывает файл, названный yt-dlp, тем заказанным в этой попытке
/// потокам, чьё имя он носит ([`is_file_of_stream`]), и возвращает их
/// индексы.
///
/// Заказанным — а не всем потокам задачи: забранный поток в `-f` этой
/// попытки не стоял, и строка о нём означала бы, что yt-dlp делает не то,
/// что просили. Не совпавший ни с кем путь не приписывается никому и
/// уходит в лог: угадывать владельца по порядку строк — ровно то, от чего
/// ушла TL-48.
fn attribute_file(work: &mut TaskWork, pending: &[usize], path: &Path) -> Vec<usize> {
    let owners: Vec<usize> = pending
        .iter()
        .copied()
        .filter(|&index| is_file_of_stream(&work.download_stem, &work.jobs[index].format_id, path))
        .collect();

    if owners.is_empty() {
        eprintln!(
            "download: yt-dlp назвал файл «{}», который не принадлежит ни одному \
             заказанному потоку, — не приписан никому",
            path.display()
        );
    }
    for &index in &owners {
        work.jobs[index].file = Some(path.to_path_buf());
    }
    owners
}

/// Отмечает забранными потоки, конец которых этот запуск доказал.
///
/// Забран — значит известен файл **и** есть доказательство конца: нулевой
/// код выхода всего запуска (`completed`) либо собственная строка потока
/// (`ended`: `finished` его формата или `has already been downloaded` с
/// его именем). Одного кода мало в обе стороны: при коде 1 соседний
/// поток мог быть забран целиком, а при коде 0 без названного файла
/// склеивать нечего. Формат, выпавший из перечня выбранных, сюда уже не
/// доходит — его отсёк [`missing_from_selection`]. Остаётся названный в
/// перечне, но без файла: что с ним случилось, из вывода не узнать, поток
/// остаётся незабранным, и повтор спросит его снова.
fn settle_streams(work: &mut TaskWork, pending: &[usize], ended: &[bool], completed: bool) {
    for &index in pending {
        let job = &mut work.jobs[index];
        if job.file.is_some() && (completed || ended[index]) {
            job.done = true;
            // Поток, забранный кодом 0 без собственной строки `finished`,
            // иначе так и остался бы в агрегаторе незакрытым, и повтор
            // после неудачной склейки упирался бы в неполный процент.
            work.aggregator.mark_complete(&job.format_id);
        } else if completed {
            eprintln!(
                "download: запуск завершился с кодом 0, формат {} yt-dlp выбрал, но файла \
                 потока не назвал — поток не считается забранным, повтор спросит его снова",
                job.format_id
            );
        }
    }
}

// ──────────────────────── Пауза перед повтором ────────────────────────

/// Выдерживает паузу перед следующей попыткой, показывая обратный отсчёт.
///
/// `false` — задачу отменили во время паузы. Ожидание прерывается
/// побудкой, а не истечением тика: «Отменить» в паузе обязано отвечать
/// секундами (Н-3), а пауза длится до минуты.
async fn wait_before_retry(
    task: &Arc<DownloadTask>,
    emitter: &mut Emitter<'_>,
    attempt: crate::types::DownloadAttempt,
    delay: Duration,
    percent: Option<DownloadPercent>,
) -> bool {
    let delay_secs = delay.as_secs();
    eprintln!(
        "download: попытка {} из {} через {delay_secs} с",
        attempt.number, attempt.total
    );

    // Момент отсчёта берётся у **того же** таймера, который потом спит:
    // разойдись они — отсчёт на экране шёл бы по одним часам, а сон по
    // другим. Побочная польза: набор тестов вправе сдвинуть эти часы и не
    // ждать полторы минуты пауз по-настоящему.
    let deadline = tokio::time::Instant::now() + delay;
    loop {
        let remaining = deadline.saturating_duration_since(tokio::time::Instant::now());
        emitter.emit(DownloadProgress::Downloading(
            DownloadingState::WaitingRetry {
                percent,
                attempt,
                delay_secs,
                // Округление вверх: «через 0 с…» на экране, за которым
                // ещё что-то происходит, — та же маленькая ложь, что
                // застывшая скорость.
                remaining_secs: remaining.as_millis().div_ceil(1_000) as u64,
            },
        ));

        if remaining.is_zero() {
            return true;
        }

        let tick = remaining.min(RETRY_COUNTDOWN_TICK);
        tokio::select! {
            () = task.cancel.cancelled() => return false,
            () = tokio::time::sleep(tick) => {}
        }
    }
}

