/// Сколько секунд yt-dlp может **молчать в stdout** на фазе «Подготовка»,
/// прежде чем его снимут (таблица «Числа» дизайна: 20 с).
///
/// Ключевое слово — «молчать»: срок считается не от последней строки
/// **прогресса**, а от последней строки вообще. Разница между двумя
/// прочтениями решает судьбу критерия К-7, и выбрана она замером, а не
/// вкусом.
///
/// # Замер (macOS 15, пин yt-dlp 2026.08.19, 2026-08-27)
///
/// Здоровая подготовка — от `spawn` до первой строки прогресса:
///
/// | Что | Время |
/// |---|---|
/// | `[youtube] Extracting URL` | 0,46–0,48 с |
/// | `Downloading visionos player API JSON` | 1,9 с |
/// | `[info] Downloading 1 format(s)` | 2,8 с |
/// | первая строка прогресса | **3,33–3,34 с** |
///
/// То есть запас до порога — шестикратный.
///
/// Мёртвая сеть (транспорт принимает соединение и молчит, ни RST, ни
/// FIN — то же, что видит клиент при выключенном Wi-Fi):
///
/// | Время | Что в stdout |
/// |---|---|
/// | 0,46 с | `Extracting URL`, `Downloading webpage` |
/// | 10,5 с | `Downloading webpage` (внутренний повтор 1/3) |
/// | 20,5 с | то же (2/3) |
/// | 30,5 с | то же (3/3) |
/// | 40,5 с | `Downloading initial data API JSON` |
/// | …каждые 10 с | то же |
/// | **80,7 с** | код 1, в stderr `Read timed out` |
///
/// Отсюда весь смысл прочтения «молчит». **Сеть, умершая на подготовке,
/// печатает строку каждые 10 секунд** — то есть до порога в 20 с не
/// доходит никогда и сроком не снимается. Она доходит до честного отказа
/// самого yt-dlp с текстом `Read timed out`, который классификация
/// относит к [`AttemptVerdict::Interrupted`] (маркер живёт в
/// `DOWNLOAD_TRANSPORT_MARKERS`), — то есть уходит в цикл повторов и
/// кончается классом «соединение потеряно», как и требует К-7.
///
/// Считай мы срок по строкам прогресса — тот же случай снимался бы на
/// 20-й секунде и приезжал бы пользователю как «Не удалось скачать
/// ролик», а не как «Соединение потеряно», и цикл повторов С-6 не
/// начинался бы вовсе. Ровно этот дефект и разводит здесь одно слово.
///
/// Что остаётся за порогом после такого прочтения: yt-dlp, не сказавший
/// **ничего** за 20 секунд. Здоровая подготовка так себя не ведёт (самый
/// длинный измеренный разрыв — 1,9 с), мёртвая сеть тоже (10 с). Значит
/// сработавший срок означает зависший процесс, и класс у него честный —
/// `ytDlpFailure` («Не удалось скачать ролик. Попробуйте ещё раз»), как и
/// предписывает doc [`crate::types::DownloadErrorKind`].
///
/// Число подлежит калибровке на bundle вместе с остальными числами эпика;
/// замеры выше сняты прямым запуском вложенного бинарника, а не через
/// смонтированный `.app` (см. отчёт задачи).
pub const FETCH_SILENCE_TIMEOUT_SECS: u64 = 20;

/// [`FETCH_SILENCE_TIMEOUT_SECS`] как [`Duration`].
const FETCH_SILENCE_TIMEOUT: Duration = Duration::from_secs(FETCH_SILENCE_TIMEOUT_SECS);

/// Минимальный промежуток между событиями `download://progress` одной
/// задачи (таблица «Числа» дизайна: не чаще раза в 300 мс).
///
/// Троттлинг здесь — **второй** пояс, а не первый. Первый стоит у
/// источника: запуск несёт `--progress-delta`
/// ([`PROGRESS_DELTA_ARG`]) с тем же значением, потому что поток через
/// манифест печатает 15,7 строк в секунду и резать его дешевле до
/// разбора, чем после (замер TL-41).
///
/// Зачем тогда второй. Во-первых, `--progress-delta` режет строки
/// **одного потока**, а у задачи их два, и на стыке видео → звук две
/// строки приходят вплотную. Во-вторых, событие эмитится не только на
/// строку прогресса.
///
/// Терминальные переходы и смена фазы троттлингом не глотаются никогда —
/// см. [`Emitter::emit`].
const PROGRESS_THROTTLE: Duration = Duration::from_millis(300);

/// Как часто обновляется обратный отсчёт паузы перед повтором.
///
/// Секунда — шаг самого числа на экране («через 8 с…»): чаще значило бы
/// слать события, ничего не меняющие, реже — показывать число, которое
/// отстаёт от правды.
const RETRY_COUNTDOWN_TICK: Duration = Duration::from_secs(1);

/// Предел длины идентификатора формата, который ядро согласно передать
/// процессу (Ф-1: непроверенного ввода в аргументах не бывает).
///
/// Идентификаторы yt-dlp короткие (`137`, `140-drc`, `hls-1080`); предел
/// нужен не им, а бюджету имени файла: идентификатор входит в имя
/// частичного файла ([`download_stem_budget`]), и без предела название
/// ролика теряло бы длину из-за чужой строки.
const MAX_FORMAT_ID_BYTES: usize = 16;

