//! Скачивание ролика: запуск yt-dlp, прогресс, склейка, отмена, повторы
//! (эпик E3).
//!
//! Пока в модуле только контракт задачи TL-38 — типизированная ошибка
//! домена ([`DownloadFailure`]) и имя события прогресса. Остальное придёт
//! отдельными задачами: разбор строк прогресса и агрегация двух потоков
//! (TL-41), склейка ffmpeg (TL-42), классификация вывода и политика
//! ретраев (TL-43), оркестрация фаз и сами команды (TL-44).
//!
//! # Три команды задачи: вход и выход
//!
//! Сигнатуры — часть контракта (TL-38), тела — TL-44. Состояние
//! (`State<'_, …>`, `AppHandle`) частью JS-видимого контракта не является,
//! как и в `commands::probe`.
//!
//! ```ignore
//! // invoke('start_download', { request: { url, title, streams } })
//! async fn start_download(request: StartDownloadRequest)
//!     -> Result<DownloadStarted, DownloadCommandError>;
//!
//! // invoke('cancel_download', { taskId })
//! async fn cancel_download(task_id: String) -> Result<(), DownloadCommandError>;
//!
//! // invoke('retry_download', { taskId })
//! async fn retry_download(task_id: String) -> Result<(), DownloadCommandError>;
//! ```
//!
//! Что из этого не видно по типам и потому зафиксировано здесь:
//!
//! - **Старт возвращается быстро** — id задачи и план, не результат
//!   загрузки: ждать в промисе часовую работу нечего, всё идёт событиями.
//!   Проверка занятого слота — в ядре, а не только в неактивной кнопке
//!   (`alreadyActive`), и она мгновенная: слот занят, пока текущая задача
//!   не терминальна.
//! - **Недоступная папка назначения — отказ задачи, а не команды.**
//!   Даже если ядро обнаружит её проверкой до запуска процесса (дизайн
//!   оставил момент обнаружения реализации), команда всё равно отдаёт id,
//!   а класс `destinationUnavailable` приезжает событием фазы `failed`:
//!   иначе один и тот же класс ошибки рисовался бы то панелью, то отказом
//!   промиса, и у панели появилось бы второе место, откуда берутся тексты.
//! - **Отмена терминальной задачи — не ошибка, а ничего.** Пользователь
//!   способен нажать «Отменить» ровно в тот момент, когда приехало
//!   `done`; отклонять такой вызов значило бы показывать ошибку за
//!   безобидную гонку. Неизвестный id — другое дело: это `unknownTask`.
//! - **Повтор продолжает ту же задачу и сохраняет её id** (задел под
//!   историю попыток в E4), поэтому и не возвращает ничего: панель уже
//!   подписана, новую сущность создавать незачем. Слот при этом снова
//!   занимается, а поток событий по задаче **возобновляется** — `failed`
//!   не означает, что задача замолчала навсегда (см.
//!   [`crate::types::DownloadProgress::is_terminal`]). Докачивать ли
//!   потоки или пересобирать только склейку, решает ядро по классу
//!   ошибки, а не флаг от фронтенда.
//!
//! # Чего в наборе нет: команда снимка состояния задачи
//!
//! Четвёртой команды — «отдай текущее состояние задачи по её id» — в E3
//! **сознательно нет**, и это решение с ценой, а не недосмотр.
//!
//! Цена названа прямо: сегодня название ролика и выбранное качество живут
//! только во фронтенде (он снимает их с карточки в момент клика и держит у
//! себя), а фазу и процент он знает лишь из событий, пришедших при нём.
//! Значит после перезагрузки webview — а в dev это каждый hot-reload —
//! идущую загрузку восстановить нечем: ядро её ведёт, панель её не видит.
//!
//! Почему всё равно нет. Восстановление состояния задач эпик откладывает в
//! E4 прямым текстом («очередь — E4: … восстановление списка задач после
//! перезапуска»), а Р-2 фиксирует, что до E4/E5 приложение вообще не
//! помнит о задаче между запусками. Команда снимка — это первая половина
//! того самого механизма: заведи её сейчас, и E4 придётся либо расширять
//! её до списка задач, либо держать рядом вторую. Добавка же её позже
//! **аддитивна** — новая команда, ни одного изменения в уже объявленных
//! типах и ни строчки правок в панели, которая к тому времени будет уметь
//! рисовать любое состояние из события той же формы.
//!
//! Ошибка домена и контрактный [`crate::types::DownloadError`] — разные
//! типы по той же причине, что и в [`crate::probe`]: домен несёт всё, что
//! знает ядро (включая полную формулировку для лога и данные, которые на
//! экран не идут вовсе, — например, сколько попыток было исчерпано), а
//! через границу команды уходит классификация и уже урезанные технические
//! детали (Н-4).

mod error;

