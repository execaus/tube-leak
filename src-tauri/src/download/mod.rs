//! Скачивание ролика: запуск yt-dlp, прогресс, склейка, отмена, повторы
//! (эпик E3).
//!
//! Готовы контракт задачи (TL-38) — типизированная ошибка домена
//! ([`DownloadFailure`]) и имя события прогресса — и разбор прогресса
//! (TL-41): [`progress`] превращает строку stdout yt-dlp в структурную
//! пробу, [`aggregate`] складывает видео и аудио в один процент и выдаёт
//! состояние фазы «Скачивание». Оба модуля чистые: процессов не
//! запускают, файлов не трогают, событий не эмитят.
//!
//! Готовы также классификация исхода попытки и политика повторов
//! (TL-43): [`classify`] превращает код завершения и stderr в вердикт о
//! попытке, [`retry`] решает, повторять ли её и когда. Оба тоже чистые —
//! процессов не убивают и пауз не выдерживают.
//!
//! [`merge`] (TL-42) — первый модуль домена, который процесс **запускает**:
//! склейка скачанных потоков отдельным ffmpeg через тот же `sidecar`, что
//! и yt-dlp. Чистой её сделать нельзя по построению — предмет и есть
//! чужой процесс, — поэтому запуск отделён швом [`merge::FfmpegLauncher`],
//! а вся остальная логика (контейнер, рабочее имя, подчистка, класс
//! отказа) проверяется без ffmpeg.
//!
//! [`filename`] (TL-40) — имя готового файла: санитизация названия
//! ролика под три ОС (Ф-6) и суффикс « (N)» при совпадении имён (Ф-7).
//! Вычисление имени чистое; файловую систему трогает одна функция —
//! `filename::finalize_in_dir`, и она же кладёт готовый файл под
//! выбранным именем. Занятие имени и переименование в ней намеренно
//! неразделимы: разделённой парой можно снять заявку после удачного
//! переименования и удалить этим готовый файл, а одной операцией —
//! нельзя. Оркестрации (TL-44) на переходе Merging → Done остаётся один
//! вызов, а не последовательность с обязанностями.
//!
//! Остальное придёт отдельной задачей: оркестрация фаз и сами команды
//! (TL-44).
//!
//! # Что запуск обязан передать yt-dlp (TL-44)
//!
//! Разбор прогресса не универсален и универсальным быть не должен: он
//! читает вывод **своего** шаблона. Значит запуск обязан нести
//! `--progress-template` со значением [`progress::PROGRESS_TEMPLATE`] и
//! `--newline` (иначе полоса пишется возвратом каретки в одну строку).
//! Человекочитаемую полосу шаблон заменяет собой — разбирать её не нужно
//! и нечего, а почему именно, написано в шапке [`progress`].
//!
//! Второе требование к запуску — `--socket-timeout`
//! ([`retry::SOCKET_TIMEOUT_SECS`]): оно разводит по времени сторож «нет
//! продвижения» и внутренние повторы самого yt-dlp, чтобы они не
//! срабатывали одновременно. Обоснование замером — там же.
//!
//! # Три команды задачи: вход и выход
//!
//! Сигнатуры — часть контракта (TL-38), тела — TL-44, а с TL-73 они
//! ведут не слот, а очередь: сами команды живут в
//! [`crate::queue::scheduler`], потому что «куда встанет задача» и «когда
//! она стартует» — вопросы очереди, а не одной задачи. Здесь остаётся
//! то, что относится к задаче: её сборка с проверками
//! ([`orchestrate::build_task`]) и её ведение от `Queued` до
//! терминальной фазы ([`orchestrate::run_task`]). Состояние
//! (`State<'_, …>`, `AppHandle`) частью JS-видимого контракта не является,
//! как и в `commands::probe`.
//!
//! ```ignore
//! // invoke('start_download', { request: { url, title, streams } })
//! async fn start_download(request: StartDownloadRequest)
//!     -> Result<DownloadStarted, DownloadCommandError>;
//!
//! // invoke('cancel_download', { taskId })
//! async fn cancel_download(task_id: String) -> Result<(), DownloadCommandError>;
//!
//! // invoke('retry_download', { taskId })
//! async fn retry_download(task_id: String) -> Result<(), DownloadCommandError>;
//! ```
//!
//! Что из этого не видно по типам и потому зафиксировано здесь:
//!
//! - **Старт возвращается быстро** — id задачи и план, не результат
//!   загрузки: ждать в промисе часовую работу нечего, всё идёт событиями.
//!   Отказа «слот занят» у команды больше нет: Ф-2 эпика E4 убрала этот
//!   класс из контракта, потому что постановка при активной задаче —
//!   штатный путь (задача встаёт в хвост очереди), а не ошибка. Очередь
//!   ставит TL-73, и с ней постановка при занятом слоте — это хвост
//!   очереди (Ф-3, строгий FIFO): идущая загрузка не вытесняется ничем.
//! - **Недоступная папка назначения — отказ задачи, а не команды.**
//!   Даже если ядро обнаружит её проверкой до запуска процесса (дизайн
//!   оставил момент обнаружения реализации), команда всё равно отдаёт id,
//!   а класс `destinationUnavailable` приезжает событием фазы `failed`:
//!   иначе один и тот же класс ошибки рисовался бы то панелью, то отказом
//!   промиса, и у панели появилось бы второе место, откуда берутся тексты.
//! - **Отмена терминальной задачи — не ошибка, а ничего.** Пользователь
//!   способен нажать «Отменить» ровно в тот момент, когда приехало
//!   `done`; отклонять такой вызов значило бы показывать ошибку за
//!   безобидную гонку. Неизвестный id — другое дело: это `unknownTask`.
//! - **Повтор продолжает ту же задачу и сохраняет её id** (задел под
//!   историю попыток в E4), поэтому и не возвращает ничего: панель уже
//!   подписана, новую сущность создавать незачем. Задача при этом снова
//!   встаёт в очередь (в хвост, Ф-5 E4), а поток событий по ней
//!   **возобновляется** — `failed`
//!   не означает, что задача замолчала навсегда (см.
//!   [`crate::types::DownloadProgress::is_terminal`]). Докачивать ли
//!   потоки или пересобирать только склейку, решает ядро по классу
//!   ошибки, а не флаг от фронтенда.
//!
//! # Чего в наборе нет: команда снимка состояния задачи
//!
//! Четвёртой команды — «отдай текущее состояние задачи по её id» — здесь
//! нет, и это решение E3 с названной ценой, а не недосмотр: до E4
//! перезагрузка webview теряла идущую загрузку с экрана, потому что ядро
//! её вело, а панель не видела.
//!
//! Обещание, данное там же, выполнено эпиком E4 и выполнено аддитивно:
//! снимок отдаёт не эта команда, а `queue_state` очереди — сразу списком
//! задач (`crate::queue::scheduler::queue_snapshot`), той же формой, что
//! едет событием `queue://changed`. Ни один объявленный здесь тип от
//! этого не поменялся, и панель E3 не тронута ни строкой — ровно так, как
//! обещал дизайн E3.
//!
//! Ошибка домена и контрактный [`crate::types::DownloadError`] — разные
//! типы по той же причине, что и в [`crate::probe`]: домен несёт всё, что
//! знает ядро (включая полную формулировку для лога и данные, которые на
//! экран не идут вовсе, — например, сколько попыток было исчерпано), а
//! через границу команды уходит классификация и уже урезанные технические
//! детали (Н-4).

