/**
 * Разбор поля «Число попыток» (эпик E5, TL-94; добавка к критерию по ревью
 * TL-83, комментарий ведущего в issue #101, 2026-09-13): «пустое значение,
 * не-число и дробь не отправляются». Ядро принимает `i64` — Tauri сам
 * отклоняет `null`/строку при разборе аргументов команды нетипизированной
 * ошибкой ещё до кода команды, так что отправлять в `settings_set` можно
 * только то, что уже разобралось в целое число здесь, на клиенте.
 *
 * Возвращает `undefined` для пустой строки, нечислового ввода и дробного
 * значения — ровно три случая из комментария ведущего. Значения **вне**
 * диапазона 1…20 (например, `0`/`21`/отрицательные) разбираются и
 * возвращаются как есть: диапазон проверяет сервер (`invalidValue`),
 * клиент лишь гарантирует, что в `settings_set` уходит настоящее целое
 * число, а не строка/`NaN`/дробь (К-6: «0 и 21 отклоняются при сохранении»
 * — именно сервером, а не этой функцией).
 *
 * Регулярное выражение требует **только** цифр с необязательным знаком
 * минус — ни точки, ни запятой, ни экспоненты, ни пробелов внутри числа
 * (пробелы по краям обрезаются `trim()` заранее, как обычно для текстовых
 * полей).
 */
export function parseAttemptsInput(raw: string): number | undefined {
  const trimmed = raw.trim()
  if (trimmed.length === 0) return undefined
  if (!/^-?\d+$/.test(trimmed)) return undefined
  const value = Number(trimmed)
  if (!Number.isSafeInteger(value)) return undefined
  return value
}

/** Зажимает значение в границы 1…20 (Ф-13) — для кнопок «−»/«+» (клиентская граница, К-6). */
export function clampAttempts(value: number): number {
  return Math.min(20, Math.max(1, value))
}
