/**
 * Контейнер файла (эпик E5, экран истории, дизайн «Экран истории»: строка
 * «mp4 · 214 МБ · 3 часа назад») — из расширения имени файла записи
 * ({@link import('@/types/generated/history').HistoryEntry.fileName}), не
 * отдельное поле контракта: `Ф-2` называет состав записи исчерпывающе, и
 * контейнера там нет — расширение уже несёт этот факт («Имя готового файла
 * с расширением, без пути»), заводить второе поле ради того же самого
 * значило бы дублировать источник истины.
 *
 * Расширение — то, что после последней точки, без самой точки, в нижнем
 * регистре (в проекте расширения контейнеров — латиница: `mp4`/`webm`/
 * `m4a`/`opus`, регистр не несёт смысла). Имя без точки (по контракту
 * недостижимо — `sanitized_stem`/`finalize_in_dir`, эпик E3, всегда
 * добавляют расширение) — оборона возвращает пустую строку, а не бросает,
 * симметрично другим местам, обрабатывающим «недостижимое по контракту»
 * значение защитно, а не молча (см. `formatRelativeTime.ts`).
 */
export function fileContainer(fileName: string): string {
  const dotIndex = fileName.lastIndexOf('.')
  if (dotIndex === -1 || dotIndex === fileName.length - 1) return ''
  return fileName.slice(dotIndex + 1).toLowerCase()
}
