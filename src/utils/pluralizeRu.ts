/**
 * Русское склонение по числу (1 → one, 2–4 → few, 0/5–20 → many), с учётом
 * исключения 11–14 (эти всегда «many», а не «few» вопреки последней
 * цифре). Тот же алгоритм, что и у приватной копии в
 * `formatRelativeTime.ts` (эпик E1) — здесь вынесен в общий util, потому
 * что очередь (эпик E4) считает по-русски то же самое число задач в двух
 * разных падежах (именительный — баннер «N задач ждут»; родительный после
 * «после» — строка ожидающей задачи «после N задач(и)»), и с
 * `formatRelativeTime.ts` это уже третье место с той же грамматикой.
 */
export function pluralizeRu(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few
  return many
}
