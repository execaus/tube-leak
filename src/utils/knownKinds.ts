/**
 * Общий приём для белых списков, дублирующих Rust-перечисления
 * (`XxxKind`, `XxxErrorKind` и т.п.) на границе Tauri (TL-52).
 *
 * # Почему белый список вообще нужен
 *
 * Значения приходят с границы как `unknown` (реджект `invoke`, тело
 * события) — TS-объединение из `src/types/generated/*.ts` не существует в
 * рантайме, и проверить «это один из известных вариантов `kind`» можно
 * только сравнением строки со списком известных значений.
 *
 * # Почему не голый массив
 *
 * До TL-52 такой список писался как `readonly Kind[] = ['a', 'b', ...]` —
 * второй, ручной источник истины рядом со сгенерированным типом. Когда в
 * Rust появился новый класс ошибки (TL-18), а массив не обновили,
 * `npm run type-check` остался зелёным. Итог — белый список тихо
 * превратил незнакомый `kind` в неконтрактный фолбэк и **потерял текст
 * сообщения** (дыру нашёл человек на ревью, см. CLAUDE.md и
 * doc-комментарий `src-tauri/src/types/bindings.rs`).
 *
 * # Почему проверка — не в generic-параметре этой функции
 *
 * Первая версия (TL-52, до ревью) была
 * `knownKindsOf<K extends string>(whitelist: Record<K, true>)`, где `K`
 * выводился из аргумента как обычный generic. Это компилировалось и
 * **без** явного `<K>` в вызове — TS в таком случае выводил `K` из самих
 * ключей переданного объекта, а не из предполагаемого перечисления, и
 * список из двух элементов молча становился «полным» списком типа
 * `('a' | 'b')[]`, не имея никакого отношения к настоящему объединению
 * (ревью TL-52 воспроизвело это мутацией). Защита, которая держится на
 * том, что автор вызова не забудет дописать `<Kind>`, — это дисциплина, а
 * не гарантия компилятора.
 *
 * Поэтому здесь `knownKindsOf` **не дженерик, выводящий тип из своего
 * аргумента для проверки полноты** — она принимает уже проверенный
 * объект. Проверка полноты сделана `satisfies` прямо на литерале в точке
 * вызова:
 *
 * ```ts
 * const KNOWN_ERROR_KINDS = knownKindsOf({
 *   notAUrl: true,
 *   videoUnavailable: true,
 *   // ...
 * } satisfies Record<ProbeErrorKind, true>)
 * ```
 *
 * `satisfies Record<ProbeErrorKind, true>` требует от литерала ровно
 * набора ключей `ProbeErrorKind` — ни одного лишнего, ни одного
 * недостающего — и делает это на самом литерале, а не через
 * type-параметр функции, который можно случайно не написать. Опустить
 * эту проверку целиком по-прежнему возможно (`knownKindsOf({ a: true })`
 * без `satisfies` скомпилируется), но это уже не «забыл один токен в
 * вызове функции», а видимое отсутствие всего выражения `satisfies
 * Record<...>` рядом с объектом — на порядок заметнее на ревью.
 */
export function knownKindsOf<T extends Record<string, true>>(whitelist: T): ReadonlyArray<keyof T> {
  return Object.keys(whitelist) as (keyof T)[]
}
