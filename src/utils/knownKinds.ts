/**
 * Общий приём для белых списков, дублирующих Rust-перечисления
 * (`XxxKind`, `XxxErrorKind` и т.п.) на границе Tauri (TL-52).
 *
 * # Почему белый список вообще нужен
 *
 * Значения приходят с границы как `unknown` (реджект `invoke`, тело
 * события) — TS-объединение из `src/types/generated/*.ts` не существует в
 * рантайме, и проверить «это один из известных вариантов `kind`» можно
 * только сравнением строки со списком известных значений.
 *
 * # Почему не голый массив
 *
 * До TL-52 такой список писался как `readonly Kind[] = ['a', 'b', ...]` —
 * второй, ручной источник истины рядом со сгенерированным типом. Когда в
 * Rust появился новый класс ошибки (TL-18), а массив не обновили,
 * `npm run type-check` остался зелёным: массив и тип из одного и того же
 * файла синтаксически никак не связаны, и рассинхронизация возможна без
 * единой ошибки компиляции. Итог — белый список тихо превратил
 * незнакомый `kind` в неконтрактный фолбэк и **потерял текст сообщения**
 * (дыру нашёл человек на ревью, см. CLAUDE.md и doc-комментарий
 * `src-tauri/src/types/bindings.rs`).
 *
 * {@link knownKindsOf} принимает не массив, а объект вида
 * `Record<Kind, true>` — и требует явно указать `Kind` в вызове
 * (`knownKindsOf<Kind>({...})`). Тогда компилятор проверяет сам объектный
 * литерал на полное и точное совпадение множества ключей с объединением
 * `Kind` (лишний ключ — избыточное свойство литерала, недостающий —
 * отсутствующее обязательное свойство `Record`). Если сгенерированный тип
 * получит новый вариант, а вызывающий код не будет обновлён — свалится
 * `npm run type-check`, а не рантайм у пользователя. Список значений
 * по-прежнему пишется руками (перечисление литералов в рантайме иначе
 * взять неоткуда), но теперь каждая правка типа обязана сопровождаться
 * правкой этого объекта — иначе сборка красная.
 */
export function knownKindsOf<K extends string>(whitelist: Record<K, true>): readonly K[] {
  return Object.keys(whitelist) as K[]
}
