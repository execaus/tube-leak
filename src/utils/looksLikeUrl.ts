/**
 * Мгновенная (без debounce) проверка «похоже ли содержимое поля на
 * `http(s)://…`» (дизайн E2, раздел «Триггер разбора и отмена»).
 *
 * Не полная валидация — та всё равно делается в Rust перед формированием
 * аргументов запуска (Ф-2). Здесь только быстрая подсказка «стоит ли вообще
 * пробовать»: строка вида `-о--` или произвольный путь не похожа на
 * ссылку — и не должна запускать процесс (С-4).
 *
 * Пустая строка/строка из пробелов — особый случай (состояние «пусто»),
 * обрабатывается вызывающей стороной отдельно, не здесь.
 */
const URL_LIKE_PATTERN = /^https?:\/\//i

export function looksLikeUrl(value: string): boolean {
  return URL_LIKE_PATTERN.test(value.trim())
}
