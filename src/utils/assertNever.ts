/**
 * Сторож исчерпывающего `switch`/`if` по объединению, сгенерированному из
 * Rust (TL-52 ревью): вызывается только в ветке, которая после
 * перечисления всех известных сегодня вариантов остаётся недостижимой —
 * TS проверяет это по параметру типа `never`.
 *
 * # Зачем это отдельная функция, а не просто убрать `default`
 *
 * Голый `switch` без `default` не защищает сам по себе: если возвращаемый
 * тип функции и так допускает `undefined` (например, `StepKey | undefined`
 * у степпера панели), падение через конец `switch` даёт легальный
 * implicit `return undefined` — компилятор не увидит тут проблемы даже
 * без `noImplicitReturns` в `tsconfig.json` (в этом проекте флаг не
 * включён). Ровно так в TL-18 новый класс ошибки yt-dlp тихо прошёл
 * мимо белого списка: неохваченная ветка не считалась ошибкой типов,
 * потому что результат по форме совпадал с ожидаемым.
 *
 * `assertNever` не оставляет такого зазора: параметр типизирован как
 * `never`, и передать в него значение, оставшееся после исчерпывающего
 * перечисления всех *известных сегодня* вариантов родительского
 * объединения, безопасно ровно потому, что там действительно `never`.
 * Стоит объединению обзавестись новым вариантом (сгенерированный Rust-тип
 * поменялся, а switch — нет) — этот же вызов перестаёт собираться:
 * оставшийся тип уже не `never`, и `npm run type-check` красный на самой
 * этой строке, а не на рантайме у пользователя.
 */
export function assertNever(value: never): never {
  throw new Error(`Необработанное значение объединения контракта: ${JSON.stringify(value)}`)
}
