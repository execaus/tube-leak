import type { HistoryUnavailableReason } from '@/types/generated/history'
import { assertNever } from './assertNever'

/**
 * Единственный абзац, которым экран истории целиком заменяется, когда базы
 * нет в этом сеансе (Ф-1 б/в/д, дизайн E5, «База новее приложения / нет
 * доступа / отказ миграции — экран блокируется целиком, кроме заголовка»).
 * Тексты — дословно по дизайну; `corrupted` сюда не входит по контракту
 * ({@link HistoryUnavailableReason} не несёт этого варианта — порча не
 * лишает сеанс истории, см. doc `HistoryUnavailableReason` в
 * `src/types/generated/history.ts`).
 */
/**
 * Абзац для отказа `history_page`, который **не** типизированный
 * {@link import('@/types/generated/history').HistoryUnavailableError} (С-6,
 * правки ревью TL-93, второй раунд) — исключение самого IPC-вызова
 * (сериализация сломалась, канал недоступен и т. п.), а не решение ядра
 * «истории в этом сеансе нет». Раньше такой отказ тихо превращался в
 * «История пуста» (ложное: пустой список и «не смогли спросить» — разные
 * факты), теперь экран показывает то же блокирующее состояние, что и три
 * типизированные причины, но с нейтральной причиной без предположений о
 * том, что именно случилось — гадать о причине по перехваченному
 * исключению нечестно.
 */
export const HISTORY_IPC_FAILURE_TEXT =
  'История недоступна в этом сеансе: не удалось получить данные. Причина не распознана — ' +
  'попробуйте переключить вкладку или перезапустить приложение позже.'

export function getHistoryUnavailableText(reason: HistoryUnavailableReason): string {
  switch (reason) {
    case 'newerVersion':
      return (
        'История недоступна в этом сеансе: файл базы данных создан более новой ' +
        'версией tube-leak — эта версия прочитать его не может. Файл не тронут: ' +
        'откроется снова, когда вы обновите приложение до этой или более новой ' +
        'версии.'
      )
    case 'noAccess':
      return (
        'История недоступна в этом сеансе: нет доступа на запись в папку данных ' +
        'приложения. Проверьте права доступа к ней и запустите tube-leak снова.'
      )
    case 'migrationFailed':
      return (
        'История недоступна в этом сеансе: не удалось обновить формат базы данных ' +
        'до текущей версии приложения. Файл остался на прежней версии и не ' +
        'повреждён — сообщите об этом, если увидите снова.'
      )
    case 'storageFailed':
      // Контракт: недоступен этот ответ, следующий запрос может пройти
      // (doc `HistoryUnavailableReason::StorageFailed`) — экран повторяет
      // запрос при открытии вкладки и снимает блокировку при успехе. Поэтому
      // ни «в этом сеансе», ни «перезапустите», ни обещаний о файле.
      return (
        'История сейчас недоступна: не удалось прочитать базу данных. ' +
        'Откройте вкладку «История» ещё раз; если повторяется, сообщите об этом.'
      )
    default:
      return assertNever(reason)
  }
}
