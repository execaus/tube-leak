import { pluralizeRu } from './pluralizeRu'

/**
 * Родительный падеж «N задач(и)» — после предлога «после» (эпик E4,
 * дизайн «Пять состояний», строка ожидающей задачи, и «Продолжение после
 * перезапуска», строки под баннером). В родительном падеже у русского
 * числительного только две формы, не три: единственное число при 1 (и
 * оканчивающихся на 1, кроме 11) — «задачи», и одна и та же форма
 * множественного числа для всех остальных — «задач» (в отличие от
 * именительного, где 2–4 и 5+ различаются, в родительном они совпадают).
 * Поэтому «few» и «many» здесь — один и тот же аргумент, не ошибка
 * копипаста.
 */
function tasksGenitive(n: number): string {
  return pluralizeRu(n, 'задачи', 'задач', 'задач')
}

/**
 * Текст-статус строки ожидающей задачи (`QueueWaitingRow`, дизайн E4,
 * «Пять состояний одной задачи»). `aheadCount` — число нетерминальных
 * задач строго впереди этой, не считая активную (дизайн: «ноль задач
 * впереди даёт вариант без „и ещё N“»); считается фронтендом по порядку
 * присланного списка, не отдельным полем контракта (см. doc
 * `QueueSnapshot.tasks` в `src/types/generated/queue.ts`).
 *
 * `awaitingContinue` меняет формулировку целиком (дизайн «Продолжение
 * после перезапуска»: «начнётся после текущей загрузки» ещё не
 * буквально — текущей загрузки в этот момент физически нет) — на «как
 * только вы продолжите», а «ноль впереди» — на «первой», а не «после
 * текущей загрузки».
 */
export function getWaitingStatusText(aheadCount: number, awaitingContinue: boolean): string {
  if (awaitingContinue) {
    return aheadCount === 0
      ? 'В очереди — начнётся первой, как только вы продолжите'
      : `В очереди — начнётся после ${aheadCount} ${tasksGenitive(aheadCount)}, как только вы продолжите`
  }
  return aheadCount === 0
    ? 'В очереди — начнётся после текущей загрузки'
    : `В очереди — начнётся после текущей загрузки и ещё ${aheadCount} ${tasksGenitive(aheadCount)}`
}

/**
 * Текст баннера продолжения очереди после перезапуска (Р-3, дизайн
 * «Продолжение после перезапуска»). `waitingCount` — число нетерминальных
 * задач в восстановленном снимке (именительный падеж с согласованием
 * глагола: «1 задача ждёт», «3 задачи ждут», «5 задач ждут» — в отличие
 * от родительного выше, здесь у 2–4 и 5+ разные формы существительного,
 * но один и тот же глагол во множественном числе).
 */
export function getResumeBannerText(waitingCount: number): string {
  const noun = pluralizeRu(waitingCount, 'задача', 'задачи', 'задач')
  const verb = pluralizeRu(waitingCount, 'ждёт', 'ждут', 'ждут')
  return (
    `Очередь приостановлена после перезапуска — ${waitingCount} ${noun} ${verb}. ` +
    'Сетевых обращений не будет, пока вы не нажмёте «Продолжить».'
  )
}

