/**
 * TS-зеркало Rust-контракта разбора ссылки на ролик (эпик E2) из
 * `src-tauri/src/types.rs` (TL-27).
 *
 * Поля и значения enum-строк должны совпадать один в один с Rust-стороной
 * (сериализация там — `serde(rename_all = "camelCase")`). Расхождение с
 * `types.rs` — баг, а не «улучшение»: изменения контракта делаются сначала
 * в Rust, это зеркало обновляется следом.
 */

/**
 * Вид пункта лестницы качеств (решение владельца Р-1).
 *
 * Признак вида приходит явно с бэкенда, а не выводится фронтендом из числа
 * пикселей: иначе правило «2160p» против «максимальное доступное (NNNp)»
 * жило бы двумя копиями — в схлопывании форматов (TL-30) и в подписи
 * строки (TL-33), и копии разошлись бы при первом же уточнении правила.
 *
 * Лестница показывает только доступные строки: пункта, которого у ролика
 * нет, в списке нет вовсе — ни выключенного, ни с пометкой (Р-1).
 *
 * - `standard` — обычная ступень лестницы: 2160p / 1440p / 1080p / 720p.
 *   Подпись строится из `heightPx` («1080p»).
 * - `maxAvailable` — единственная видеострока для ролика, максимум
 *   которого ниже 720p: «Максимальное доступное (NNNp)», число берётся из
 *   `heightPx` (Р-1). Вместо всей видео-лестницы, а не в дополнение к ней.
 * - `audioOnly` — «только аудио», присутствует всегда (Р-1) и идёт
 *   последней строкой; `heightPx` у такого пункта нет.
 */
export type QualityKind = 'standard' | 'maxAvailable' | 'audioOnly'

/**
 * Оценка размера пункта: либо число байт, либо явное «неизвестно» (Ф-4).
 *
 * Отдельный вариант, а не `0`/`null`: «нет данных» и «нулевой размер» —
 * разные вещи, и строка «размер неизвестен» остаётся кликабельной, то есть
 * отсутствие оценки не делает пункт неполноценным. Приблизительность
 * оценки в контракт не выносится — UI показывает любую оценку одинаково,
 * со знаком «≈».
 */
export type QualitySize = { kind: 'known'; bytes: number } | { kind: 'unknown' }

/**
 * Непрозрачные для фронтенда идентификаторы потоков, которые скачает E3.
 *
 * UI не интерпретирует эти строки и ничего по ним не решает — он возвращает
 * объект обратно вместе с выбранным пунктом, поэтому тип ходит в обе
 * стороны границы. Требование Ф-3 — «результат разбора вместе с выбранным
 * пунктом однозначно определяет, что скачивать, без повторного разбора» —
 * держится именно на нём.
 *
 * Присутствие полей задаётся видом пункта и устройством форматов ролика:
 * `audioOnly` — только `audioFormatId`; обычная ступень из раздельных
 * потоков — оба поля; обычная ступень, у которой лучший видеопоток уже
 * содержит звук (прогрессивный формат), — только `videoFormatId`.
 * Инвариант: хотя бы одно из полей заполнено всегда — пункт без единого
 * потока не имеет смысла и в список не попадает.
 */
export interface QualityStreams {
  videoFormatId?: string
  audioFormatId?: string
}

/**
 * Строка лестницы качеств: что это за пункт, сколько примерно весит и что
 * скачивать, если пользователь выберет именно его.
 */
export interface QualityItem {
  kind: QualityKind
  /**
   * Высота кадра в пикселях: есть у `standard` и `maxAvailable`, нет у
   * `audioOnly`. Идёт в подпись строки, а не в решение о её виде.
   */
  heightPx?: number
  size: QualitySize
  streams: QualityStreams
}

/**
 * Успешный разбор ролика — всё, из чего рисуется карточка (Ф-5, Р-2).
 *
 * Порядок `qualities` задаёт ядро и он фиксирован: от большего разрешения
 * к меньшему, «только аудио» последней. UI рисует список как пришёл и не
 * сортирует его сам — иначе правило порядка окажется в двух местах.
 *
 * `channel` и `thumbnailUrl` опциональны не «на всякий случай» —
 * отсутствуют, а не приходят `null`: карточка обязана оставаться полезной,
 * если yt-dlp не отдал имя канала или у ролика нет превью — соответствующий
 * элемент просто не рисуется (превью — со статичным плейсхолдером, дизайн
 * E2).
 */
export interface ProbeResult {
  /**
   * Название как есть, без обрезания и нормализации: К-1 требует
   * посимвольного совпадения с YouTube. Санитизация для имён файлов —
   * забота E3, не этого типа.
   */
  title: string
  /** Длительность в секундах; форматирование в `м:сс`/`ч:мм:сс» — на UI. */
  durationSecs: number
  channel?: string
  /** URL превью, который webview грузит напрямую с CDN YouTube (Р-2). */
  thumbnailUrl?: string
  qualities: QualityItem[]
}

/**
 * Девять классов отказа разбора (Ф-6). Ровно по ним фронтенд выбирает
 * заголовок, пояснение и наличие кнопки «Повторить» (таблица в дизайне
 * E2) — тексты живут на стороне UI, в контракте только классификация.
 *
 * - `notAUrl` — ввод не является http(s)-ссылкой (С-4). Единственный
 *   класс, который возникает до запуска процесса: yt-dlp не запускается
 *   вовсе, поэтому у него нет ни `details`, ни «Подробнее» на экране.
 * - `videoUnavailable` — ролик удалён, скрыт или никогда не существовал
 *   (С-5).
 * - `signInRequired` — нужен вход в аккаунт YouTube: возрастное
 *   ограничение, подписка и прочее (С-6). Возрастное ограничение отдельным
 *   классом не выделено сознательно: без входа (E8) действие пользователя
 *   одно и то же.
 * - `regionBlocked` — ролик не показывается в стране пользователя (С-7).
 * - `networkUnavailable` — нет соединения с интернетом (С-8).
 * - `playlistUnsupported` — ссылка ведёт на плейлист или канал (С-9).
 *   Ролик с параметром плейлиста (`watch?v=…&list=…`) этим классом не
 *   является — он разбирается как одиночный ролик.
 * - `liveUnsupported` — идущий эфир или запланированная премьера (С-10).
 *   Завершённая трансляция с готовой записью — обычный ролик, не этот
 *   класс.
 * - `ytDlpFailure` — сбой yt-dlp, не отнесённый к классам выше (С-12).
 *   Под-причина — в `reason`.
 * - `timeout` — разбор не уложился в отведённое время, процесс убит.
 *   Значение сработавшего порога — в `timeoutSecs`.
 */
export type ProbeErrorKind =
  | 'notAUrl'
  | 'videoUnavailable'
  | 'signInRequired'
  | 'regionBlocked'
  | 'networkUnavailable'
  | 'playlistUnsupported'
  | 'liveUnsupported'
  | 'ytDlpFailure'
  | 'timeout'

/**
 * Под-причина класса `ytDlpFailure` (С-12): меняет только текст пояснения,
 * класс остаётся один — тот же приём, что `launchFailed.reason` в E1.
 *
 * - `generic` — ошибка без узнаваемой сигнатуры: «попробуйте ещё раз».
 * - `outdated` — в выводе опознан признак того, что встроенный yt-dlp не
 *   понимает текущий ответ YouTube. Обновление — E6; здесь только честный
 *   текст.
 */
export type YtDlpFailureReason = 'generic' | 'outdated'

/**
 * Технические детали отказа для свёрнутого «Подробнее».
 *
 * Через границу команды идёт именно это — хвост stderr и код завершения,
 * а не поток целиком: полный stderr пишется в лог приложения и на экран
 * не попадает ни в каком состоянии (Н-4).
 *
 * Отсутствует целиком, когда сказать нечего (см. [`ProbeError.details`]):
 * пустого объекта не бывает.
 */
export interface ProbeErrorDetails {
  /** Хвост stderr процесса, обрезанный по длине. */
  stderrTail?: string
  /** Код завершения процесса yt-dlp, если процесс успел завершиться сам. */
  exitCode?: number
}

/**
 * Отказ разбора в сериализуемом виде — то, чем реджектится `probe_url`.
 *
 * Решение принимается по `kind` (и по `reason` внутри `ytDlpFailure`).
 *
 * `message` — формулировка ядра для свёрнутого «Подробнее» и лога,
 * **не** основной текст на экране: основной текст пользователь видит из
 * таблицы текстов по девяти классам (раздел «Состояния» дизайна E2) и
 * рисуется UI по `kind` — это задача TL-33, не этого зеркала. stderr в
 * `message` не попадает ни в каком состоянии (Н-4). Тот же приём, что
 * `YtDlpPrepareError.message` в `src/types/sidecar.ts` (эпик E1): самое
 * приглашающее имя поля для автора экрана — не повод брать его заголовком.
 */
export interface ProbeError {
  kind: ProbeErrorKind
  message: string
  /** Только при `kind === 'ytDlpFailure'`; для него заполняется всегда. */
  reason?: YtDlpFailureReason
  /**
   * Только при `kind === 'timeout'`: сработавший порог в секундах,
   * подставляется в текст ошибки («…за отведённое время (N с)»).
   */
  timeoutSecs?: number
  /**
   * Отсутствует у `notAUrl` (процесс не запускался) и вообще у любого
   * отказа, о котором нечего сказать технически.
   */
  details?: ProbeErrorDetails
}
