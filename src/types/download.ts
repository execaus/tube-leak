/**
 * TS-зеркало Rust-контракта задачи скачивания (эпик E3) из
 * `src-tauri/src/types.rs` (секция «скачивание ролика (TL-38)», TL-39).
 *
 * Поля и значения enum-строк должны совпадать один в один с Rust-стороной
 * (сериализация там — `serde(rename_all = "camelCase")`, у структур с
 * несколькими тегами — ещё и `rename_all_fields = "camelCase"`).
 * Расхождение с `types.rs` — баг, а не «улучшение»: изменения контракта
 * делаются сначала в Rust, это зеркало обновляется следом.
 */

import type { QualityStreams, YtDlpFailureReason } from './probe'

/**
 * Фаза задачи скачивания (Ф-3). Ровно семь — по автомату
 * `Queued → Fetching → Downloading → Merging → Done / Failed / Cancelled`.
 *
 * Это то, из чего рисуется степпер шагов, а не внутренние шаги реализации.
 * Ожидание повтора между попытками (С-6) отдельной фазой **не** является:
 * по дизайну степпер в паузе продолжает показывать «Скачивание», а
 * отличается панель содержимым — см. {@link DownloadingState}.
 *
 * Шаг «Склейка» рисуется не всегда: для «только аудио» и прогрессивного
 * формата (С-2, С-3) ffmpeg не запускается вовсе, и фазы `merging` в жизни
 * такой задачи не будет — это заранее, с момента старта, сообщает
 * {@link DownloadPlan}, а не догадка по числу форматов.
 */
export type DownloadPhase =
  | 'queued'
  | 'fetching'
  | 'downloading'
  | 'merging'
  | 'done'
  | 'failed'
  | 'cancelled'

/**
 * Сколько потоков скачивает задача — то есть какой степпер рисовать.
 * Отдаётся один раз, в ответе команды старта, а не в каждом событии
 * прогресса: величина постоянна на всю жизнь задачи.
 *
 * Правило «два потока ⇒ будет склейка» умышленно не выводится фронтендом
 * из количества переданных `formatId` — оно живёт в ядре, потому что ядро
 * и решает, запускать ли ffmpeg. Копия правила здесь была бы вторым
 * источником истины и разошлась бы с ним молча.
 */
export type DownloadPlan = 'videoAndAudio' | 'singleStream'

/**
 * Какой из двух потоков принимается прямо сейчас (подпись «Скачиваем
 * видео…» / «Скачиваем звук…»).
 *
 * Подслой внутри шага «Скачивание», а не фаза задачи: смена потока не
 * меняет ни шаг степпера, ни шкалу процента — процент агрегирован по обоим
 * потокам сразу и от перехода видео → аудио назад не откатывается (Ф-2).
 */
export type DownloadStream = 'video' | 'audio'

/**
 * Доля скачанного в процентах, 0..=100.
 *
 * На проводе — просто число (`#[serde(transparent)]` на Rust-стороне), но
 * с инвариантом «не больше ста», зажатым конструктором в ядре: заниженная
 * оценка размера потока может подвести число к сотне раньше, чем придёт
 * уточнение от yt-dlp, и обрезание — только страховка от выезда полосы за
 * край, а не замена уточнению знаменателя. Застывшие подряд «99, 100, 100,
 * 100 %» без движения — такой же дефект, как застывшая скорость.
 */
export type DownloadPercent = number

/**
 * Номер попытки и их предел — «попытка 2 из 6».
 *
 * `number` — номер той попытки, о которой идёт речь **сейчас**: в
 * {@link DownloadingState} с `state === 'running'` это идущая попытка, в
 * `state === 'waitingRetry'` — та, что начнётся по истечении паузы
 * («Ждём повторной попытки (2 из 6)»). Разница ровно на единицу.
 *
 * `total` — предел числа попыток подряд без продвижения (стартовое
 * значение дизайна — 6). Счётчик обнуляется любым продвижением байт
 * (С-6), поэтому `number` за долгую загрузку может доходить до `total`
 * многократно — это не признак близкого отказа.
 */
export interface DownloadAttempt {
  number: number
  total: number
}

/**
 * Что стало с частично скачанными данными к моменту терминальной фазы.
 *
 * Отдельное значение на проводе, а не таблица «класс → судьба файлов» на
 * стороне UI: удаляет данные ядро, оно и отчитывается о сделанном, а
 * таблица классов не постоянна (у `destinationUnavailable` исход зависит
 * от того, доступна ли ещё папка).
 *
 * Для фазы `cancelled` значений бывает ровно два — `removed` либо
 * `nothingCreated` (отмена до старта процесса): подчистка при отмене
 * всегда полная, без исключений по классам (Ф-4).
 */
export type PartialData = 'nothingCreated' | 'removed' | 'kept'

/**
 * Девять классов отказа скачивания (Ф-10). Ровно по ним фронтенд выбирает
 * заголовок и пояснение (таблица дизайна E3) — тексты живут на стороне UI,
 * в контракте только классификация.
 *
 * Пять классов — свои для E3 (`connectionLost`, `diskFull`, `staleFormat`,
 * `mergeFailed`, `destinationUnavailable`); четыре последних
 * (`videoUnavailable`, `signInRequired`, `regionBlocked`, `ytDlpFailure`)
 * переиспользуют смысловые классы разбора — их строки на проводе
 * **совпадают** с одноимёнными значениями {@link ProbeErrorKind}
 * намеренно, чтобы тексты, уже написанные для карточки E2, годились без
 * перевода.
 *
 * Чего в девятке сознательно нет: `timeout` (таймаут фазы «Подготовка»
 * ложится в `ytDlpFailure` — «сбой, не отнесённый к классам выше») и
 * `networkUnavailable` (отсутствие сети во время скачивания — повод к
 * циклу повторов С-6, а не отказ; отказом оно становится только после
 * исчерпания попыток, и тогда это `connectionLost`).
 */
export type DownloadErrorKind =
  | 'connectionLost'
  | 'diskFull'
  | 'staleFormat'
  | 'mergeFailed'
  | 'destinationUnavailable'
  | 'videoUnavailable'
  | 'signInRequired'
  | 'regionBlocked'
  | 'ytDlpFailure'

/**
 * Технические детали отказа для свёрнутого «Подробнее».
 *
 * Форма повторяет `ProbeErrorDetails`, но сознательно не переиспользует
 * его: «Подробнее» панели загрузки и «Подробнее» карточки — разные
 * экраны разных эпиков, и поле, которое понадобится одному, не должно
 * появиться у другого молча. Правило Н-4 E2 общее для обоих: через
 * границу идёт только хвост stderr и код завершения, полный поток — в
 * логе приложения, на экран не попадает никогда.
 *
 * Отсутствует целиком, когда сказать нечего (отказ без процесса за спиной,
 * например недоступная папка назначения, обнаруженная до запуска).
 */
export interface DownloadErrorDetails {
  stderrTail?: string
  exitCode?: number
}

/**
 * Отказ скачивания в сериализуемом виде — полезная нагрузка фазы `failed`.
 *
 * Решение принимается по `kind`.
 */
export interface DownloadError {
  kind: DownloadErrorKind
  /**
   * Формулировка ядра для свёрнутого «Подробнее» и лога — **не** основной
   * текст на экране. Основной текст пользователь видит из таблицы текстов
   * по девяти классам (раздел «Состояния/Ошибки» дизайна E3) и рисуется UI
   * по `kind`; stderr в `message` не попадает ни в каком состоянии (Н-4).
   * Тот же приём, что `ProbeError.message` в E2 — самое приглашающее имя
   * поля для автора панели не повод брать его заголовком.
   */
  message: string
  /**
   * Проекция `DownloadErrorKind.is_retryable` (правило зафиксировано на
   * Rust-стороне): есть ли смысл в команде повтора. Панель рисует кнопку
   * «Повторить» по этому полю, а не по собственной копии таблицы классов.
   */
  retryable: boolean
  /**
   * Под-причина класса `ytDlpFailure` — заполнена **всегда**, когда
   * `kind === 'ytDlpFailure'`, и отсутствует для остальных восьми классов.
   * Это не необязательное украшение: CLAUDE.md требует, чтобы пользователь
   * отличал «yt-dlp устарел» от прочих сбоев — при разборе ссылки (E2) это
   * поле уже обязательный источник текста, и в скачивании оно несёт ту же
   * ответственность. Панель, построенная на `kind === 'ytDlpFailure'` без
   * учёта `reason`, покажет одно и то же обеднённое «Попробуйте ещё раз»
   * и там, где на самом деле нужно честное «встроенный yt-dlp устарел» —
   * ровно тот дефект, которого требование не допускает.
   */
  reason?: YtDlpFailureReason
  /**
   * Что стало с частично скачанным — факт от ядра, не вывод из `kind` на
   * стороне UI (таблица дизайна не постоянна, см. {@link PartialData}).
   */
  partialData: PartialData
  /** Отсутствует, когда деталей нет: отказу технически нечего показать. */
  details?: DownloadErrorDetails
}

/**
 * Что происходит внутри фазы `downloading` — два взаимоисключающих
 * состояния, а не одно с флагом. Тег на проводе — поле `state`.
 *
 * Пауза перед повтором — отдельное, не «то же `running`, только с другим
 * числом» состояние: у неё нет ни скорости, ни оценки оставшегося
 * времени (их неоткуда взять, процесс уже завершился), зато есть обратный
 * отсчёт; показывать в этот момент последнюю известную скорость значило бы
 * врать (тот же класс дефекта, что «не отвечает» в E1).
 *
 * Второй из трёх видов «нет движения» — сторож ядра «ни одного нового
 * байта за 20 с» (С-8) — своего значения на проводе не имеет: зависшая
 * попытка признаётся неудавшейся и уходит в тот же цикл повторов, то есть
 * наблюдаемо становится `waitingRetry`. Третий, «событий не было 5 с», —
 * косметика фронтенда и в контракте невыразим в принципе: это отсутствие
 * событий, а не их содержимое.
 */
export type DownloadingState =
  | {
      state: 'running'
      /**
       * Присутствует только у задачи с двумя потоками
       * (`plan === 'videoAndAudio'`); при одном потоке различать нечего, и
       * подпись на экране — просто «Скачиваем…».
       */
      stream?: DownloadStream
      /**
       * Агрегированная доля обоих потоков. Отсутствует, пока считать не из
       * чего (размер ещё не известен ни из оценки E2, ни от yt-dlp) — не
       * `0`: ноль означал бы «ничего не скачано».
       */
      percent?: DownloadPercent
      /** Мгновенная скорость в байтах в секунду; форматирование — на UI. */
      speedBytesPerSec?: number
      /** Оценка оставшегося времени в секундах, как её даёт yt-dlp. */
      etaSecs?: number
      /**
       * Номер идущей попытки — только начиная со второй: на обычном пути
       * номер всегда «1», и рисовать его значит загромождать экран числом,
       * которое ничего не сообщает.
       */
      attempt?: DownloadAttempt
    }
  | {
      state: 'waitingRetry'
      /**
       * Последний известный процент, замороженный на время паузы (К-6
       * требует, чтобы он не откатывался к нулю). Отсутствует, только если
       * процента не было и до обрыва.
       */
      percent?: DownloadPercent
      /**
       * Попытка, которая начнётся по истечении паузы, и предел («2 из
       * 6») — в этом состоянии известна всегда, паузы без следующей
       * попытки не бывает.
       */
      attempt: DownloadAttempt
      /**
       * Полная длительность текущей паузы: растёт от 5 с удвоением,
       * потолок 60 с (стартовые значения дизайна). Число справочное — для
       * формы, которой нужна доля; инварианта «остаток не больше неё»
       * контракт не держит (значения приезжают из разных источников).
       */
      delaySecs: number
      /** Сколько секунд паузы осталось — обратный отсчёт на экране. */
      remainingSecs: number
    }

/**
 * Состояние задачи скачивания на момент события — размеченное по фазе
 * объединение. Тег на проводе — поле `phase`, те же семь значений, что у
 * {@link DownloadPhase}; у варианта `downloading` рядом появляется второй
 * тег `state` ({@link DownloadingState}), поля которого лежат в том же
 * плоском объекте, а не во вложенном.
 *
 * Форма выбрана так, чтобы сквозная шкала «процентов всей задачи» была
 * невыразима: процент есть только внутри `downloading`, у `merging` его
 * нет и быть не может — remux не даёт надёжной оценки дешевле, чем сам
 * remux, и по дизайну показывается нейтральным индикатором без числа.
 */
export type DownloadProgress =
  | { phase: 'queued' }
  /**
   * yt-dlp запущен, прогресса ещё нет («Подготовка»). Числа здесь нет
   * сознательно: пока не пришло ни одной строки прогресса, любое —
   * выдумка.
   */
  | { phase: 'fetching' }
  | ({ phase: 'downloading' } & DownloadingState)
  /** ffmpeg объединяет скачанные потоки. Без процента — см. doc типа. */
  | { phase: 'merging' }
  | {
      phase: 'done'
      /**
       * Имя готового файла с фактическим расширением, без пути: папка
       * назначения одна и та же на всё приложение (Р-1), подставлять её в
       * текст — дело UI.
       */
      fileName: string
    }
  | { phase: 'failed'; error: DownloadError }
  | {
      phase: 'cancelled'
      /**
       * При отмене подчистка всегда полная, поэтому здесь бывает либо
       * `removed`, либо `nothingCreated` (отмена в `queued`).
       */
      partialData: PartialData
    }

/**
 * Полезная нагрузка события `download://progress`.
 *
 * Ключ задачи — `taskId`: события ключуются им с самого начала, хотя
 * активная задача в E3 ровно одна — требование CLAUDE.md и задел под
 * очередь E4, который не переписывается; подписчик обязан сверять id, а не
 * считать, что любое пришедшее событие — про его панель.
 *
 * Частота эмита ограничена (стартовое значение дизайна — не чаще раза в
 * 300 мс), кроме перехода в терминальную фазу — он не может быть проглочен
 * троттлингом.
 *
 * **Терминальная фаза — не значит «навсегда молчащая».** Поток событий по
 * задаче обрывается насовсем только после `cancelled` и `done` — там
 * задача прожита до конца. После `failed` он **возобновляется** командой
 * повтора: та же задача, тот же `taskId`, снова занимающий слот и снова
 * присылающий события с начала своей фазовой цепочки. Подписчику
 * **нельзя** отписываться от событий или начинать фильтровать их по факту
 * отказа — так повтор нарисовался бы мёртвой панелью, которая уже не
 * получает обновлений.
 */
export type DownloadProgressEvent = { taskId: string } & DownloadProgress

/**
 * Вход команды `start_download`.
 *
 * Собирается ровно из того, что уже есть на экране к моменту клика:
 * ссылка из поля ввода, название ролика и потоки выбранного пункта
 * лестницы. Папка назначения, число попыток и таймауты параметрами не
 * являются — это константы дизайна, и настройками они станут в E5, не
 * меняя форму этой команды.
 */
export interface StartDownloadRequest {
  /** Ссылка на ролик — та же, которую разобрал E2. */
  url: string
  /**
   * Название ролика как его показала карточка, без обрезания: чем оно
   * станет в имени файла, решает санитизация ядра (Ф-6, TL-40).
   */
  title: string
  /**
   * Потоки выбранного пункта лестницы — тип E2 переиспользуется как есть,
   * это то самое единственное поле контракта разбора, которое ходит в обе
   * стороны границы. Объект без единого потока команда обязана отклонить
   * (`DownloadCommandErrorKind.noStreamsSelected`).
   */
  streams: QualityStreams
}

/**
 * Ответ команды `start_download`: задача создана.
 *
 * Возвращается быстро и не дожидается ни одного байта — вся работа идёт
 * событиями, ждать в промисе тут нечего.
 */
export interface DownloadStarted {
  /**
   * Идентификатор задачи, непрозрачный для фронтенда: приходит обратно в
   * событиях и в командах отмены и повтора, но не разбирается на части и
   * ничего не означает.
   */
  taskId: string
  /**
   * Фаза, в которой задача создана. Всегда `queued` в E3 (активная задача
   * одна, стартовать ей нечего ждать), но панель рисуется по этому полю, а
   * не по константе: в E4 задача может встать за уже идущей и остаться в
   * `queued` надолго.
   */
  phase: DownloadPhase
  /** Один поток или два — то есть будет ли шаг «Склейка». */
  plan: DownloadPlan
}

/**
 * Почему команда управления загрузкой (`start_download` /
 * `cancel_download` / `retry_download`) отклонена.
 *
 * Это **не** классы отказа самой загрузки ({@link DownloadErrorKind}): те
 * описывают судьбу задачи и рисуются панелью, а эти — отказ выполнить
 * вызов, то есть состояние, до которого исправный фронтенд не доводит
 * (кнопки, которых нельзя нажать, он не показывает). Тем не менее они
 * типизированы, а не строки — защита на стороне ядра обязана быть
 * настоящей.
 */
export type DownloadCommandErrorKind =
  /**
   * Слот занят: уже есть задача в нетерминальной фазе. В E3 активная
   * задача ровно одна, и проверка живёт в ядре, а не только в неактивной
   * кнопке (С-13). Тем же классом отклоняется и повтор, если пользователь
   * успел запустить новую загрузку поверх завершившейся.
   */
  | 'alreadyActive'
  /**
   * Задачи с таким `taskId` ядро не знает: она никогда не создавалась либо
   * приложение перезапускалось (до E4/E5 задачи не переживают выход —
   * Р-2).
   */
  | 'unknownTask'
  /** Повтор запрошен для задачи, которая не в фазе `failed`. */
  | 'notFailed'
  /**
   * Повтор запрошен для класса ошибки, где он заведомо бесполезен
   * (`DownloadError.retryable === false`): устаревшие данные разбора
   * чинятся новым разбором, а не тем же запросом ещё раз.
   */
  | 'notRetryable'
  /** В запросе нет ни одного идентификатора потока — скачивать нечего. */
  | 'noStreamsSelected'
  /**
   * Ссылка не является http(s)-адресом. Проверяется заново, даже если её
   * уже разобрал E2: ни одна часть пользовательского ввода не попадает в
   * аргументы процесса непроверенной (Ф-1).
   */
