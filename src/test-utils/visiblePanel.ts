import type { DOMWrapper } from '@vue/test-utils'

/**
 * TL-92, правки ревью (Б-2/Н-6): панели `App.vue` переключаются через
 * `v-show`, не `v-if` (К-14 — переключение вкладки не должно пересоздавать
 * «Главный» и терять состояние `ProbeSection`), поэтому скрытая панель
 * остаётся в DOM целиком, и обычный `wrapper.text()`/`wrapper.findAll(...)`
 * видит её содержимое как обычно. Это ровно та ловушка, что уже поймала
 * тест строки паузы на обновление yt-dlp: он оставался зелёным даже без
 * ветки кода, которую был обязан проверять, потому что скрытая панель
 * «Главный» рисует тот же текст внутри своей секции очереди независимо от
 * строки состояния (doc-комментарий `App.tabs.test.ts`).
 *
 * `getComputedStyle(child).display` **не** наследует `none` от скрытого
 * предка — это поведение браузера/jsdom, а не упрощение: спецификация
 * возвращает собственное объявленное/вычисленное значение элемента
 * независимо от того, рисуется ли он на самом деле из-за родителя.
 * Единственный надёжный способ определить видимость — обойти цепочку
 * предков вручную, начиная с самого элемента.
 */
function isVisible(element: Element): boolean {
  let node: Element | null = element
  while (node) {
    if (getComputedStyle(node).display === 'none') return false
    node = node.parentElement
  }
  return true
}

/**
 * Фильтрует список DOM-обёрток `@vue/test-utils` (обычно результат
 * `wrapper.findAll(...)`), оставляя только те, что видны прямо сейчас —
 * ни сам элемент, ни один из его предков не имеет `display: none`.
 *
 * Назначение — тесты, которые не должны знать про содержимое скрытых в
 * данный момент панелей: например, список подписей кнопок экрана E1 не
 * обязан «уметь» отличать свои кнопки от кнопок будущих экранов
 * История/Настройки (TL-93/TL-94) — они и так не видны, пока активна
 * вкладка «Главный», без ручных фильтров по компоненту/классу.
 */
export function onlyVisible<T extends DOMWrapper<Element>>(wrappers: T[]): T[] {
  return wrappers.filter((wrapper) => isVisible(wrapper.element))
}
