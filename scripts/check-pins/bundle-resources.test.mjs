// Сторож: документы §6d обязаны ехать в бандл (TL-134, находка 2026-09-27).
//
// Найдено осмотром выпущенного tube-leak_0.1.1_aarch64.dmg: в
// Contents/Resources/_up_/ лежали README.md и THIRD-PARTY-LICENSES.md, а
// SOURCES-FFMPEG.md не попадал в бандл вовсе — `find … -iname '*SOURCES*'`
// по смонтированному образу пуст. Получатель сборки держал бы в руках
// бинарник ffmpeg под GPL v3 и ни одного доступного ему указателя на
// исходники: на 2026-09-27 репозиторий кода был ещё приватным, и
// единственный наш указатель лежал там, куда получатель не попадёт.
// Репозиторий кода с тех пор открыт, но вывод не изменился: указатель
// §6d должен ехать вместе с бинарником, а не только лежать в
// репозитории. Ссылка на ffmpeg.org есть внутри самого
// SOURCES-FFMPEG.md, то есть недоступен был именно тот файл, который и
// должен вести к исходникам.
//
// Охраны у этого не было никакой: файл завели в репозитории и забыли про
// `bundle.resources`, а обнаружилось это только осмотром готового образа.
// Проверка привязана к DOC_FILES — тому же списку, по которому идут
// сверка документов с пином и сетевая проверка адресов: новый документ
// §6d нельзя будет добавить, забыв про бандл.
//
// Чего сторож НЕ проверяет: что Tauri действительно положила файл в образ
// — это делает сама сборка. Форма пути (`../имя`) взята не из документации,
// а измерена: с нею соседи каталога src-tauri оказываются в
// target/<профиль>/_up_/ и, тем же механизмом copy_resources, в
// Contents/Resources/_up_/ бандла — ровно там, где в .dmg нашлись README.md
// и THIRD-PARTY-LICENSES.md.

import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

import { describe, expect, it } from 'vitest'

import { DOC_FILES, REPO_ROOT } from './sources.mjs'

describe('документы §6d едут в бандл', () => {
  it('каждый документ §6d перечислен в bundle.resources', async () => {
    const config = JSON.parse(
      await readFile(join(REPO_ROOT, 'src-tauri', 'tauri.conf.json'), 'utf8'),
    )

    for (const name of DOC_FILES) {
      expect(config.bundle.resources).toContain(`../${name}`)
    }
  })

  it('называет ровно те документы, которые проверяет остальной сторож', () => {
    // Список один на всё: разойдись он — сторож охранял бы не то, что
    // сверяется с пином и проверяется в сети.
    expect(DOC_FILES).toStrictEqual(['SOURCES-FFMPEG.md', 'THIRD-PARTY-LICENSES.md'])
  })
})
